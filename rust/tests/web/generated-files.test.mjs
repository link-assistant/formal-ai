// R1188-U8: bulk changes are made by rules, so every file that says it is
// generated is checked against its generator in CI, and a hand edit of it
// cannot be merged (scripts/check-generated-files.mjs).

import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';

import {
  checkedInCi,
  exceptionsFrom,
  generatedFileProblems,
  generatorOf,
  readHeader,
  scriptOf,
} from '../../../scripts/check-generated-files.mjs';
import { REPO_ROOT } from './support/browser-runtime.mjs';

test('the generator command is read from the header only', () => {
  assert.equal(generatorOf('# Title\n\nGenerated by `node scripts/render-status.mjs --write`.\n'), 'node scripts/render-status.mjs --write');
  assert.equal(generatorOf('A file says ``Generated by `<command>` `` in its header.'), null);
  const late = `${'line\n'.repeat(20)}Generated by \`node scripts/x.mjs --write\``;
  assert.equal(generatorOf(late), null);
});

test('a generator is checked when CI runs it or its twin', () => {
  assert.equal(scriptOf('rust-script scripts/render-status.rs --write'), 'scripts/render-status');
  assert.equal(scriptOf('node experiments/formal_ai_subagent/requirement-coverage.mjs --write'), 'experiments/formal_ai_subagent/requirement-coverage');
  const ci = 'run "node scripts/render-status.mjs --check"';
  assert.ok(checkedInCi('scripts/render-status', ci));
  assert.ok(!checkedInCi('scripts/render-statistics', ci));
});

test('an unchecked generated file fails unless it is listed with a reason', () => {
  const files = [
    { path: 'docs/a.md', text: 'Generated by `node scripts/a.mjs --write`' },
    { path: 'docs/b.md', text: 'Generated by `node scripts/b.mjs --write`' },
    { path: 'docs/c.md', text: 'Generated by `node scripts/c.mjs --write`' },
  ];
  const ci = 'run "node scripts/a.mjs --check"';
  const exceptions = exceptionsFrom('generated-files\n  unchecked "docs/b.md"\n    reason "Needs the operator\'s sessions."\n');
  const { generated, problems } = generatedFileProblems(files, ci, exceptions);
  assert.deepEqual(generated.map((entry) => entry.checked), [true, false, false]);
  assert.equal(problems.length, 1);
  assert.match(problems[0], /docs\/c\.md is generated by .*no CI gate/);
  const stale = generatedFileProblems(files.slice(0, 1), ci, exceptionsFrom('generated-files\n  unchecked "docs/a.md"\n    reason "x"\n'));
  assert.match(stale.problems.join('\n'), /CI checks it now; remove the row/);
});

test('only the first twelve UTF-8 header lines are read', () => {
  const dir = mkdtempSync(join(tmpdir(), 'generated-header-'));
  try {
    const path = join(dir, 'source.mjs');
    const command = 'Generated by `node scripts/a.mjs --write`';
    const prefix = 'x'.repeat(4095) + 'месяц\n' + 'line\n'.repeat(10);
    writeFileSync(path, prefix + command + '\n' + 'body\n'.repeat(10000));
    assert.equal(readHeader(path), prefix + command + '\n');
    assert.equal(generatorOf(readHeader(path)), 'node scripts/a.mjs --write');
    writeFileSync(path, prefix + 'line twelve\n' + command);
    assert.equal(generatorOf(readHeader(path)), null);
    writeFileSync(path, command);
    assert.equal(readHeader(path), command);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('one-pass file inspection preserves stale exception checks', () => {
  const files = (function* () {
    yield { path: 'docs/a.md', text: 'Generated by `node scripts/a.mjs --write`' };
  })();
  const result = generatedFileProblems(files, 'scripts/a.mjs', new Map([['docs/missing.md', 'reason']]));
  assert.match(result.problems.join('\n'), /lists docs\/missing.md/);
  assert.equal(result.generated[0].checked, true);
});

test('every generated file in the repository is checked in CI or listed', () => {
  const output = execFileSync(process.execPath, ['--max-old-space-size=96', 'scripts/check-generated-files.mjs'], { cwd: REPO_ROOT, encoding: 'utf8', timeout: 30_000 });
  assert.match(output, /generated files: \d+, \d+ checked in CI/);
});


test('file header reads preserve a UTF-8 character split across chunks', (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'generated-header-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const path = join(directory, 'source.mjs');
  const text = 'x'.repeat(4095) + 'π\nGenerated by `node scripts/render.mjs --write`\n';
  writeFileSync(path, text);
  assert.equal(readHeader(path), text);
  assert.equal(generatorOf(readHeader(path)), 'node scripts/render.mjs --write');
});

test('only the first twelve file lines participate in generator detection', (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'generated-header-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const path = join(directory, 'source.mjs');
  const marker = 'Generated by `node scripts/render.mjs --write`';
  const head = 'line\r\n'.repeat(11) + marker + '\r\n';
  writeFileSync(path, head + 'tail\n'.repeat(100_000));
  assert.equal(readHeader(path), head);
  assert.equal(generatorOf(readHeader(path)), 'node scripts/render.mjs --write');
  writeFileSync(path, 'line\n'.repeat(12) + marker);
  assert.equal(readHeader(path), 'line\n'.repeat(12));
  assert.equal(generatorOf(readHeader(path)), null);
});

test('short and empty headers preserve EOF and missing files report read errors', (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'generated-header-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const path = join(directory, 'source.mjs');
  for (const text of ['', 'no final newline', 'Generated by `node scripts/x.mjs`']) {
    writeFileSync(path, text);
    assert.equal(readHeader(path), text);
  }
  assert.throws(() => readHeader(join(directory, 'missing')), { code: 'ENOENT' });
});


test('a lazy file inventory retains unchecked and stale-exception failures', () => {
  function* files() {
    yield { path: 'docs/a.md', text: 'Generated by `node scripts/a.mjs --write`' };
    yield { path: 'docs/plain.md', text: 'ordinary source' };
  }
  const exceptions = new Map([['docs/missing.md', 'operator snapshot']]);
  const result = generatedFileProblems(files(), '', exceptions);
  assert.deepEqual(result.generated, [{
    path: 'docs/a.md', command: 'node scripts/a.mjs --write', checked: false,
  }]);
  assert.equal(result.problems.length, 2);
  assert.match(result.problems[0], /no CI gate or workflow runs/);
  assert.match(result.problems[1], /lists docs\/missing\.md/);
});
