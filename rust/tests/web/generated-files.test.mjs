// R1188-U8: bulk changes are made by rules, so every file that says it is
// generated is checked against its generator in CI, and a hand edit of it
// cannot be merged (scripts/check-generated-files.mjs).

import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import test from 'node:test';

import {
  checkedInCi,
  exceptionsFrom,
  generatedFileProblems,
  generatorOf,
  scriptOf,
} from '../../../scripts/check-generated-files.mjs';
import { REPO_ROOT } from './support/browser-runtime.mjs';

test('the generator command is read from the header only', () => {
  assert.equal(generatorOf('# Title\n\nGenerated by `node scripts/render-status.mjs --write`.\n'), 'node scripts/render-status.mjs --write');
  assert.equal(generatorOf('A file says ``Generated by `<command>` `` in its header.'), null);
  const late = `${'line\n'.repeat(20)}Generated by \`node scripts/x.mjs --write\``;
  assert.equal(generatorOf(late), null);
});

test('a generator is checked when CI runs it or its twin', () => {
  assert.equal(scriptOf('rust-script scripts/render-status.rs --write'), 'scripts/render-status');
  assert.equal(scriptOf('node experiments/formal_ai_subagent/requirement-coverage.mjs --write'), 'experiments/formal_ai_subagent/requirement-coverage');
  const ci = 'run "node scripts/render-status.mjs --check"';
  assert.ok(checkedInCi('scripts/render-status', ci));
  assert.ok(!checkedInCi('scripts/render-statistics', ci));
});

test('an unchecked generated file fails unless it is listed with a reason', () => {
  const files = [
    { path: 'docs/a.md', text: 'Generated by `node scripts/a.mjs --write`' },
    { path: 'docs/b.md', text: 'Generated by `node scripts/b.mjs --write`' },
    { path: 'docs/c.md', text: 'Generated by `node scripts/c.mjs --write`' },
  ];
  const ci = 'run "node scripts/a.mjs --check"';
  const exceptions = exceptionsFrom('generated-files\n  unchecked "docs/b.md"\n    reason "Needs the operator\'s sessions."\n');
  const { generated, problems } = generatedFileProblems(files, ci, exceptions);
  assert.deepEqual(generated.map((entry) => entry.checked), [true, false, false]);
  assert.equal(problems.length, 1);
  assert.match(problems[0], /docs\/c\.md is generated by .*no CI gate/);
  const stale = generatedFileProblems(files.slice(0, 1), ci, exceptionsFrom('generated-files\n  unchecked "docs/a.md"\n    reason "x"\n'));
  assert.match(stale.problems.join('\n'), /CI checks it now; remove the row/);
});

test('every generated file in the repository is checked in CI or listed', () => {
  const output = execFileSync('node', ['scripts/check-generated-files.mjs'], { cwd: REPO_ROOT, encoding: 'utf8' });
  assert.match(output, /generated files: \d+, \d+ checked in CI/);
});
