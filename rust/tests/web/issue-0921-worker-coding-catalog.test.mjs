// Issue #921 R921-8 (with #1021 R1021-6 and #1165 R1165-4/R1165-8): the browser
// worker answers every task in every language the Rust coding catalog holds,
// not only Hello World. JavaScript first: the worker no longer carries its own
// task or template tables; installSeedProgramTasks
// (js/worker/formal_ai_worker_program_requests.js) reads them from
// data/seed/hello-world-programs.lino, the bundle
// rust/tests/source/source_tests/coding/catalog/mod/lino_parity.rs holds equal
// to the compiled tables in rust/src/coding/catalog/{tasks,templates_*}.rs, and
// a pair the seed retires to the documentation route is rediscovered from
// data/seed/coding-documentation-captures.lino as the Rust catalog_table does.
//
// The Rust side of each comparison is data/meta/agentic-coding-catalog.lino,
// generated byte for byte from the Rust tables (task and language rows, and the
// template pair list in Rust table order), read through
// js/agentic/crate/coding_catalog.mjs with the server's seed parser
// (js/seed_loader.js), which is independent of the worker's own reader. The
// answers are the Rust twins' prompts: rust/tests/unit/specification/
// code_generation/task_catalog.rs, extended to Scala and Kotlin, the languages
// the Hive Mind production matrix dispatched.

import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { before, test } from 'node:test';

import { programLanguages, programTasks, programTemplates } from '../../../js/agentic/crate/coding_catalog.mjs';
import { installNodeHost } from '../../../js/agentic/node-host.mjs';
import { childValue, parseLino } from '../../../js/server/lino.mjs';
import { WorkerHost, evaluate } from '../../../js/server/worker-host.mjs';

let host;
let context;
before(async () => {
  host = new WorkerHost();
  context = await host.boot();
  await installNodeHost(new WorkerHost());
});

const worker = (expression) => JSON.parse(evaluate(context, `JSON.stringify(${expression})`));
const workerTemplate = (task, language) =>
  evaluate(context, `writeProgramTemplate(${JSON.stringify(task)}, ${JSON.stringify(language)})`);

/** The seed rows that store their program, as `task:language` -> code. */
const seedPrograms = () => {
  const text = readFileSync(new URL('../../../data/seed/hello-world-programs.lino', import.meta.url), 'utf8');
  const programs = new Map();
  for (const node of parseLino(text).children || []) {
    const code = childValue(node, 'code');
    if (code) programs.set(`${childValue(node, 'task')}:${childValue(node, 'language')}`, code);
  }
  return programs;
};

test('R921-8: the worker installs the Rust catalog tasks from the seed, in Rust table order', () => {
  const installed = worker('WRITE_PROGRAM_TASKS');
  assert.deepEqual(
    Object.entries(installed).map(([slug, task]) => ({ slug, label: task.label, output: task.output, input: task.input })),
    programTasks().map((task) => ({ slug: task.slug, label: task.label, output: task.output, input: task.input })),
  );
});

// The seed bundle's `write_program` row names the languages it stores programs
// for; those rows are the worker's. The Rust catalog's two further rows, swift
// and r (issue #1167), store no template in either root, and the worker answers
// their requests through the coding oracle instead (recorded as an open gap in
// docs/case-studies/pull-request-1188/README.md).
const SEED_LANGUAGES = () => {
  const text = readFileSync(new URL('../../../data/seed/hello-world-programs.lino', import.meta.url), 'utf8');
  const row = (parseLino(text).children || []).find((node) => node.name === 'write_program' || node.id === 'write_program');
  return childValue(row, 'languages').replace(/[()"]/g, ' ').split(/\s+/).filter(Boolean);
};

test('R921-8: the worker language rows equal the Rust catalog rows the seed stores programs for', () => {
  const rows = worker('WRITE_PROGRAM_LANGUAGES');
  const seeded = SEED_LANGUAGES();
  assert.deepEqual(Object.keys(rows), seeded);
  assert.deepEqual(
    Object.entries(rows).map(([slug, row]) => [slug, row.name, row.fence, row.saveAs, row.checkCommand ?? null,
      row.runCommand, row.frameworkOf ?? null]),
    programLanguages().filter((row) => seeded.includes(row.slug)).map((row) => [row.slug, row.name, row.code_fence,
      row.save_as, row.execution.check_command, row.execution.run_command, row.framework_of]),
  );
  assert.deepEqual(programLanguages().map((row) => row.slug).filter((slug) => !seeded.includes(slug)), ['swift', 'r']);
});

test('R921-8: every task x language pair has a worker program exactly when the Rust catalog has one', () => {
  const catalogued = new Map(programTemplates().map((template) =>
    [`${template.task_slug}:${template.language_slug}`, template.code]));
  const stored = seedPrograms();
  let compared = 0;
  for (const task of programTasks()) {
    for (const language of programLanguages()) {
      const pair = `${task.slug}:${language.slug}`;
      const program = workerTemplate(task.slug, language.slug);
      if (!catalogued.has(pair)) {
        assert.equal(program, null, `${pair} is not in the Rust catalog`);
        continue;
      }
      assert.equal(program, catalogued.get(pair), pair);
      if (stored.has(pair)) assert.equal(program, stored.get(pair), `${pair} differs from its seed program`);
      compared += 1;
    }
  }
  assert.equal(compared, programTemplates().length);
  assert.equal(compared, 151);
});

test('R921-8: the worker stores no program for a pair the seed retires to the documentation route', () => {
  const stored = seedPrograms();
  const tables = worker('WRITE_PROGRAM_TEMPLATES');
  const pairs = Object.entries(tables).flatMap(([task, languages]) =>
    Object.keys(languages).map((language) => `${task}:${language}`));
  assert.deepEqual(pairs.sort(), [...stored.keys()].sort());
  assert.equal(tables.hello_world.scala, undefined);
  assert.equal(tables.hello_world.kotlin, undefined);
});

const SCALA_KOTLIN = [['Scala', 'scala'], ['Kotlin', 'kotlin']];

// The English prompts of task_catalog.rs and the issue #324/#440 listing tests.
const ENGLISH_PROMPTS = [
  ['count_to_three', (name) => `Write a ${name} program that counts to three`],
  ['list_files', (name) => `Write me a ${name} program that lists files in the current directory`],
  ['list_files_arg', (name) => `Write me a ${name} program that lists files with a path argument`],
  ['list_files_reverse_sort', (name) => `Write me a ${name} program that lists files sorted in reverse order`],
  ['list_files_arg_reverse_sort', (name) => `Write me a ${name} program that lists files with a path argument sorted descending`],
  ['fizzbuzz', (name) => `Write me a FizzBuzz program in ${name}`],
  ['factorial', (name) => `Write me a ${name} program for the factorial of 5`],
  ['reverse_string', (name) => `Write me a ${name} program to reverse the string hello`],
  ['sum_to_ten', (name) => `Write me a ${name} program for the sum from 1 to 10`],
  ['fibonacci', (name) => `Write a ${name} function that calculates the Fibonacci sequence recursively.`],
  ['copy_stdin_to_stdout', (name) => `Write a ${name} program that copies stdin to stdout`],
];

const parameters = (result) =>
  (result.solverEvents || []).find((event) => event.kind === 'program_parameters')?.payload;

test('R921-8: english Scala and Kotlin requests answer every catalog task with the Rust template', async () => {
  const catalogued = new Set(programTemplates().map((template) => `${template.task_slug}:${template.language_slug}`));
  let answered = 0;
  for (const [name, language] of SCALA_KOTLIN) {
    for (const [task, prompt] of ENGLISH_PROMPTS) {
      if (!catalogued.has(`${task}:${language}`)) continue;
      answered += 1;
      const result = await host.solve(prompt(name), []);
      assert.equal(result.intent, 'write_program', prompt(name));
      assert.equal(parameters(result), `write_program(language=${language}, task=${task})`, prompt(name));
      const program = workerTemplate(task, language);
      assert.ok(result.content.includes(`\`\`\`${language}\n${program}\n\`\`\``), result.content);
      // A listing task shows a sample directory named after the language's file
      // (issue #440); every other task shows the catalog's verified output.
      const output = worker('WRITE_PROGRAM_TASKS')[task].output;
      if (!task.startsWith('list_files')) {
        assert.ok(result.content.includes(`Expected output after verification:\n\`\`\`text\n${output}\n\`\`\``), result.content);
      }
    }
  }
  // Ten tasks each; count_to_three has no Scala or Kotlin program in either catalog.
  assert.equal(answered, 20);
});

test('R921-8: the Scala FizzBuzz answer is the catalog answer with an honest not-run status', async () => {
  const result = await host.solve('Write me a FizzBuzz program in Scala', []);
  assert.equal(result.content.split('\n')[0], 'Here is a minimal Scala FizzBuzz program:');
  assert.equal(result.programExecution.block, 'Execution status: not run - the browser sandbox cannot invoke a scala toolchain.\n\nCopy the snippet into a scala environment to verify.\n\nExpected output after verification:\n```text\n1\n2\nFizz\n4\nBuzz\nFizz\n7\n8\nFizz\nBuzz\n11\nFizz\n13\n14\nFizzBuzz\n```');
  assert.deepEqual(
    [result.programExecution.language, result.programExecution.checkCommand, result.programExecution.runCommand],
    ['scala', 'scalac Main.scala', 'scala Main'],
  );
});

