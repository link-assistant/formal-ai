import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {canonicalize, parseRegistry, renderRust, sourceQualifiedSeedOwners} from '../../../scripts/generate-seed-registry.mjs';
import {generatedSeedOwnerDeclarations, censusDocuments} from '../../../js/agentic/node-host.mjs';
import {installHost} from '../../../js/agentic/host.mjs';
import {parseLino} from '../../../js/server/lino.mjs';
import {resolveRequirementTarget} from '../../../js/agentic/requirement_resolution.mjs';
function fixture(names=['arbitrary-alpha']) {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'formal-ai-generated-owner-'));
  fs.mkdirSync(path.join(root,'data/meta'),{recursive:true});
  fs.mkdirSync(path.join(root,'data/seed'),{recursive:true});
  fs.mkdirSync(path.join(root,'rust/src/seed'),{recursive:true});
  const registry='seed_registry\n'+names.map(name=>'  seed '+name+'\n    bundle true\n    lexicon meaning\n').join('');
  fs.writeFileSync(path.join(root,'data/meta/seed-registry.lino'),registry);
  for(const name of names)fs.writeFileSync(path.join(root,'data/seed/'+name+'.lino'),'meanings\n  arbitrary\n    role request_signal\n    lexeme en "azure dawn"\n');
  fs.writeFileSync(path.join(root,'rust/src/seed/embedded_registry.rs'),renderRust(canonicalize(parseRegistry(registry))));
  return root;
}
function withFixture(action,names) {const root=fixture(names);try{action(root);}finally{fs.rmSync(root,{recursive:true,force:true});}}
function hostFixture(root,documents=[]) {
  installHost({readText:relative=>{try{return fs.readFileSync(path.join(root,relative),'utf8');}catch{return '';}},
    parseLino, censusDocuments:()=>documents, generatedSeedOwnerDeclarations:()=>generatedSeedOwnerDeclarations(root)});
}
test('complete generated source owns arbitrary seeds without a census document',()=>withFixture(root=>{
  const proof=sourceQualifiedSeedOwners(root);
  assert.equal(proof.declarations.length,1);assert.match(proof.sourceSha256,/^[0-9a-f]{64}$/u);
  assert.deepEqual(proof.declarations[0],{seed_path:'data/seed/arbitrary-alpha.lino',module_path:'src/seed/embedded_registry.rs',symbol:'ARBITRARY_ALPHA_LINO',kind:'const'});
  assert.deepEqual(censusDocuments(root),[]);hostFixture(root);
  assert.deepEqual(resolveRequirementTarget('Rename ARBITRARY_ALPHA_LINO after changing its signal'),{module_path:'src/seed/embedded_registry.rs',symbol:'ARBITRARY_ALPHA_LINO',kind:'const'});
  assert.deepEqual(resolveRequirementTarget('Change signal surface from azure dawn to cobalt sun'),{module_path:'src/seed/embedded_registry.rs',symbol:'ARBITRARY_ALPHA_LINO',kind:'const'});
  assert.equal(resolveRequirementTarget('Improve azure dawn.'),null);
  assert.equal(resolveRequirementTarget('Change signal surface from azure dawn in rust/src/missing.rs'),null);
}));
test('changed generated bytes, changed registry, missing files and symlinks refuse owners',()=>{
  for(const mutation of [
    root=>fs.appendFileSync(path.join(root,'rust/src/seed/embedded_registry.rs'),'// drift\n'),
    root=>fs.appendFileSync(path.join(root,'data/meta/seed-registry.lino'),'  seed arbitrary-beta\n    bundle true\n'),
    root=>fs.unlinkSync(path.join(root,'data/seed/arbitrary-alpha.lino')),
    root=>{const file=path.join(root,'rust/src/seed/embedded_registry.rs');fs.renameSync(file,file+'.retained');fs.symlinkSync(file+'.retained',file);},
    root=>fs.writeFileSync(path.join(root,'rust/src/seed/embedded_registry.rs'),Buffer.alloc(1024*1024+1)),
  ])withFixture(root=>{mutation(root);assert.throws(()=>sourceQualifiedSeedOwners(root));assert.deepEqual(generatedSeedOwnerDeclarations(root),[]);hostFixture(root);assert.equal(resolveRequirementTarget('Change signal surface from azure dawn'),null);});
});
test('generator name collisions and equal actual seed surfaces retain refusal',()=>{
  withFixture(root=>{assert.throws(()=>sourceQualifiedSeedOwners(root),/ambiguous/u);assert.deepEqual(generatedSeedOwnerDeclarations(root),[]);},['arbitrary-alpha','arbitrary_alpha']);
  withFixture(root=>{hostFixture(root);assert.equal(resolveRequirementTarget('Change signal surface from azure dawn'),null);},['arbitrary-alpha','arbitrary-beta']);
});
test('existing census declaration ambiguity is not replaced by generated fallback',()=>withFixture(root=>{
  const text=module=>'self_ast_census\n  target '+module+'\n  symbols\n    const ARBITRARY_ALPHA_LINO 1 1\n';
  hostFixture(root,[{text:text('src/first.rs')},{text:text('src/second.rs')}]);
  assert.equal(resolveRequirementTarget('Rename ARBITRARY_ALPHA_LINO after changing signal'),null);
}));
