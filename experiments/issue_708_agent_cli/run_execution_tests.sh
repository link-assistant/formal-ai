#!/usr/bin/env bash
# Reproduce the Agent-CLI-authored bounded-interpreter acceptance tests.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
ARTIFACT_DIR="$ROOT/docs/case-studies/issue-708/self-hosting-execution-tests"
CANONICAL="$ROOT/tests/unit/issue_708_memory_program_execution.rs"
TEST_CONTENT="$(<"$CANONICAL")"
STAGING="$(mktemp -d)"
trap 'rm -rf "$STAGING"' EXIT
TASK="Create a Rust test file named issue_708_memory_program_execution.rs with exactly this content:
$TEST_CONTENT"

TASK="$TASK" \
EXPECT_FILE="issue_708_memory_program_execution.rs" \
EXPECT_TEXT="destructive_program_requires_confirmation" \
MIN_POSTS=3 \
ATTEMPTS=3 \
PORT="${PORT:-8710}" \
ARTIFACT_DIR="$STAGING" \
"$ROOT/experiments/agent_cli_e2e/run_agent_cli.sh"

# Command substitution drops the canonical file's final newline. Validate every
# generated byte before publishing evidence, while leaving the rustfmt-clean
# canonical source untouched.
cmp "$STAGING/issue_708_memory_program_execution.rs" <(printf '%s' "$TEST_CONTENT")
mkdir -p "$ARTIFACT_DIR"
cp "$STAGING/formal-ai.log" "$ARTIFACT_DIR/formal-ai.log"
cp "$STAGING/agent-cli.log" "$ARTIFACT_DIR/agent-cli.log"
cp "$STAGING/issue_708_memory_program_execution.rs" "$ARTIFACT_DIR/issue_708_memory_program_execution.rs"
grep -m1 -o 'ses_[A-Za-z0-9]*' "$ARTIFACT_DIR/agent-cli.log"
