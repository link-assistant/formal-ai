// Derive budgets for the newly generated factory closure and its dispatch glue.
// Existing unrelated ceilings are left to their owners; factory ceilings equal
// the generated source length (original module plus its documented factory frame).
import { writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { generatedFiles } from '../../scripts/generate-worker-crate-modules.mjs';
import { collectBudgets, collectWorkerFiles, shardName } from '../../scripts/check-worker-line-budget.mjs';

const generated = generatedFiles();
const budgets = collectBudgets(process.cwd());
const glue = new Map([
  ['formal_ai_worker_crate_modules.js', 'The factory loader now supplies both meaning and response lexicons from the seed registry, so generated compilers read canonical gap names and responses. This adds three registry projection lines.'],
  ['formal_ai_worker_compiled_procedure.js', 'Browser dispatch of solver_handlers/procedure_rules.rs. Compiler and artifacts run the generated JavaScript crate modules; this glue fills seeded responses and records real compilation or review-only proposal events.'],
  ['formal_ai_worker_capabilities_and_runtime_rules.js', 'The typed behavior-rule compiler declines before the seeded general procedure compiler is tried, matching the native handler. Only this three-line dispatch bridge was added.'],
]);
for (const file of collectWorkerFiles(process.cwd())) {
  const source = generated.get(file.path);
  if (source === undefined && !glue.has(file.module)) continue;
  const old = budgets.get(file.module);
  if (old && old.ceiling >= file.lines && !old.rationale.includes('check-worker-crate-modules')) continue;
  const origin = source === undefined ? null : /^\/\/ from (.+)\.$/mu.exec(source)?.[1];
  const rationale = source === undefined ? glue.get(file.module)
    : 'Generated by scripts/generate-worker-crate-modules.mjs from ' + (origin ?? 'the meaning and response lexicons of data/meta/seed-registry.lino')
      + '. The browser runs the original JavaScript module through a factory; the exact ceiling is source plus factory frame, with named re-exports preserved. generate-worker-crate-modules.mjs --check detects source drift.';
  const text = 'worker_module_budget\n  module ' + JSON.stringify(file.module) + '\n  ceiling ' + file.lines + '\n  rationale ' + JSON.stringify(rationale) + '\n';
  const target = join('data/meta/worker-line-budget', shardName(basename(file.path)));
  writeFileSync(target, text);
  console.log(target);
}
