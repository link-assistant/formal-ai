"""Bring the lexicon-import batch to every registered language, by rule (PR #1188, LEXEMES).

`formal-ai import lexemes --offline` regenerates data/seed/meanings-lexicon-import-*.lino
from the trimmed Wikidata cache (rust/src/lexeme_import.rs). The importer now reads
the `status partial` languages of data/seed/languages.lino as optional surfaces, and
its cache trim keeps them, so the committed cache records need those languages and
the shards need re-rendering. Nothing may be compiled locally, so this script is a
port of the importer's rule, checked against the committed bytes before it writes:

  1. Each cached `<Qid>.json` must equal Python's `json.dump(indent=2,
     ensure_ascii=False)` of itself, and the codec port must reproduce its `.lino`
     sibling (scripts/wikidata_lino_codec.py).
  2. Rendering the committed concepts from the committed cache with the previous
     rule (full languages only, 60 concepts per shard) must reproduce every
     committed shard byte for byte.

Only then does it add the partial languages' labels, descriptions and aliases from
full `Special:EntityData` documents (fetched once into a scratch directory), in the
importer's trim order, and render the shards with the new rule: the full languages
are required, a partial language is emitted when the record holds a clean surface
for it (its label, else its first clean alias) and omitted otherwise, and a shard
holds as many blocks as fit under the line budget.

Usage:
  python3 -I experiments/formal_ai_subagent/import-partial-languages.py <raw-entity-dir> [--write]
"""
from __future__ import annotations

import importlib.util
import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "data/cache/wikidata/entity"
SEED = ROOT / "data/seed"
MIRRORS = [
    ROOT / "rust/embedded/data/seed",
    ROOT / "js/seed",
    ROOT / "packages/formal-ai-engine/assets/seed",
]
CONCEPTS = ROOT / "data/lexicon-import/common-nouns.lino"
SHARD_PREFIX = "meanings-lexicon-import"
SHARD_HEADER = (
    "# `Bulk Wikidata lexeme import for issue 660, R378.`\n"
    "# `Generated by formal-ai import lexemes; regenerate instead of hand-editing.`\n"
    "# `Source records live under data/cache/wikidata/entity/<Qid>.json.`\n"
    "meanings\n"
)
PREVIOUS_CONCEPTS_PER_SHARD = 60
SHARD_LINE_BUDGET = 1_400
# The Unicode script each registered language writes in (the detection registry's
# script ranges, data/seed/language-detection.lino), by Unicode character name.
SCRIPT_NAMES = {"en": "LATIN", "es": "LATIN", "ru": "CYRILLIC", "hi": "DEVANAGARI", "zh": "CJK"}
UNCLEAN = set("#\"'`()")


def load_codec():
    spec = importlib.util.spec_from_file_location("codec", ROOT / "scripts/wikidata_lino_codec.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def languages_with_status(status: str) -> list[str]:
    languages = []
    current = None
    for line in (SEED / "languages.lino").read_text(encoding="utf-8").split("\n"):
        if line.startswith("  language "):
            current = line[len("  language "):]
        elif line == f"    status {status}" and current is not None:
            languages.append(current)
            current = None
    return languages


def parse_concepts() -> list[tuple[str, str]]:
    concepts = []
    for line in CONCEPTS.read_text(encoding="utf-8").split("\n"):
        words = line.split()
        if len(words) == 2 and words[1].startswith("Q") and words[1][1:].isdigit():
            concepts.append((words[0], words[1]))
    return concepts


def dump(document) -> str:
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def matches_script(surface: str, language: str) -> bool:
    script = SCRIPT_NAMES[language]
    return any(
        character.isalpha() and unicodedata.name(character, "").startswith(script)
        for character in surface
    )


def is_clean(surface: str) -> bool:
    return surface != "" and not any(c.isspace() or c in UNCLEAN for c in surface)


def choose_surface(entity: dict, language: str, require_clean: bool):
    """The importer's surface for `language`: the label, else the first usable alias."""
    label = entity.get("labels", {}).get(language, {}).get("value")
    if label is None:
        return None

    def usable(surface: str) -> bool:
        return matches_script(surface, language) and (is_clean(surface) or not require_clean)

    if usable(label):
        return label, f"labels.{language}.value"
    for index, alias in enumerate(entity.get("aliases", {}).get(language, [])):
        if usable(alias["value"]):
            return alias["value"], f"aliases.{language}[{index}].value"
    return None


def render_block(slug: str, qid: str, surfaces: list[tuple[str, str, str]]) -> str:
    lines = [f"  {slug}", f"    grounded-in {qid}", "    defined-by entity"]
    for language, surface, field in surfaces:
        lines += [
            f"    lexeme {language}",
            "      surface",
            f"        text {surface} # source {qid} {field}",
            "        part_of_speech noun",
            "        grammatical_number singular",
        ]
    return "\n".join(lines) + "\n"


def shard_names(count: int) -> list[str]:
    if count == 1:
        return [f"{SHARD_PREFIX}.lino"]
    return [f"{SHARD_PREFIX}-{index + 1:02}.lino" for index in range(count)]


def shards_by_count(blocks: list[str], per_shard: int) -> dict[str, str]:
    chunks = [blocks[start:start + per_shard] for start in range(0, len(blocks), per_shard)]
    return {name: SHARD_HEADER + "".join(chunk) for name, chunk in zip(shard_names(len(chunks)), chunks)}


def shards_by_lines(blocks: list[str]) -> dict[str, str]:
    header_lines = SHARD_HEADER.count("\n")
    chunks: list[list[str]] = []
    lines = 0
    for block in blocks:
        block_lines = block.count("\n")
        if chunks and lines and header_lines + lines + block_lines > SHARD_LINE_BUDGET:
            chunks.append([])
            lines = 0
        if not chunks:
            chunks.append([])
        chunks[-1].append(block)
        lines += block_lines
    return {name: SHARD_HEADER + "".join(chunk) for name, chunk in zip(shard_names(len(chunks)), chunks)}


def committed_shards() -> dict[str, str]:
    return {
        path.name: path.read_text(encoding="utf-8")
        for path in sorted(SEED.glob(f"{SHARD_PREFIX}*.lino"))
    }


def enrich(cached: dict, raw: dict, qid: str, full: list[str], partial: list[str]) -> dict:
    """The importer's trim order over `full + partial`: the cached entries of the full
    languages unchanged, the partial languages' entries taken from `raw`."""
    entity = cached["entities"][qid]
    source = raw["entities"].get(qid) or next(iter(raw["entities"].values()))
    trimmed = {}
    if "type" in entity:
        trimmed["type"] = entity["type"]
    trimmed["id"] = qid
    for section in ("labels", "descriptions", "aliases"):
        kept = {}
        for language in full + partial:
            holder = entity if language in full else source
            entry = holder.get(section, {}).get(language)
            if entry is None or (section == "aliases" and not entry):
                continue
            kept[language] = entry
        if kept:
            trimmed[section] = kept
    return {"entities": {qid: trimmed}, "success": 1}


def main() -> int:
    arguments = sys.argv[1:]
    if not arguments or arguments[0].startswith("--"):
        print(__doc__.strip().split("Usage:")[1], file=sys.stderr)
        return 2
    raw_dir = Path(arguments[0])
    write = "--write" in arguments[1:]
    codec = load_codec()
    full = languages_with_status("full")
    partial = languages_with_status("partial")
    concepts = parse_concepts()

    # 1. The cached records reproduce through this port.
    cached = {}
    for _, qid in concepts:
        text = (CACHE / f"{qid}.json").read_text(encoding="utf-8")
        document = json.loads(text)
        assert dump(document) == text, f"{qid}.json does not reproduce"
        assert codec.json_cache_file(qid, document) == (CACHE / f"{qid}.lino").read_text(encoding="utf-8"), qid
        cached[qid] = document

    # 2. The previous rule reproduces the committed shards.
    previous_blocks = []
    for slug, qid in concepts:
        entity = cached[qid]["entities"][qid]
        surfaces = [(language, *choose_surface(entity, language, require_clean=False)) for language in full]
        previous_blocks.append(render_block(slug, qid, surfaces))
    assert shards_by_count(previous_blocks, PREVIOUS_CONCEPTS_PER_SHARD) == committed_shards(), "shards do not reproduce"
    print(f"reproduced {len(concepts)} cache records and {len(committed_shards())} shards byte for byte")

    # 3. Add the partial languages and render with the new rule.
    blocks = []
    omitted = []
    for slug, qid in concepts:
        raw = json.loads((raw_dir / f"{qid}.json").read_text(encoding="utf-8"))
        cached[qid] = enrich(cached[qid], raw, qid, full, partial)
        entity = cached[qid]["entities"][qid]
        surfaces = [(language, *choose_surface(entity, language, require_clean=True)) for language in full]
        for language in partial:
            chosen = choose_surface(entity, language, require_clean=True)
            if chosen is None:
                omitted.append(f"{slug} {qid} {language}")
            else:
                surfaces.append((language, *chosen))
        blocks.append(render_block(slug, qid, surfaces))
    shards = shards_by_lines(blocks)
    for name, content in shards.items():
        print(f"{name}: {content.count(chr(10))} lines")
    print(f"omitted partial-language surfaces: {omitted}")
    if not write:
        return 0

    for _, qid in concepts:
        (CACHE / f"{qid}.json").write_text(dump(cached[qid]), encoding="utf-8")
        (CACHE / f"{qid}.lino").write_text(codec.json_cache_file(qid, cached[qid]), encoding="utf-8")
    for directory in [SEED, *MIRRORS]:
        for stale in directory.glob(f"{SHARD_PREFIX}*.lino"):
            if stale.name not in shards:
                stale.unlink()
        for name, content in shards.items():
            (directory / name).write_text(content, encoding="utf-8")
    print(f"wrote {len(concepts)} cache records and {len(shards)} shards (+ {len(MIRRORS)} mirrors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
