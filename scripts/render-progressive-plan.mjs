#!/usr/bin/env node
// The progressive plan (R1188-U28, R1188-U29).
//
// The progressive JPEG method (docs/progressive-delivery.md): the whole is
// complete at every moment at some resolution, and each pass raises the
// lowest parts first. This script reads the requirement-status ledger and
// places every requirement on its resolution level:
//
//   1 recorded     the row exists, nothing measures it yet
//   2 measured     a test pins it, but the row says it is not delivered
//   3 partial      delivered in part
//   4 implemented  delivered, with a test
//
// (a superseded or withdrawn requirement is closed, level 0: no pass raises
// it) and, for JavaScript first, which root the test that pins it runs in. It
// renders docs/progressive-plan.md, where the next pass is the lowest
// non-empty level. `--check` regenerates and compares, and holds
// data/meta/progressive-plan-ratchet.lino: an open level grows only by newly
// recorded requirements, and the Rust-only count never grows. `--write` also
// lowers the ratchet; it never raises a ceiling.
//
// Usage: node scripts/render-progressive-plan.mjs [--write | --check]

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const LEDGER = 'data/meta/requirement-status-ledger';
const PLAN = 'docs/progressive-plan.md';
const RATCHET = 'data/meta/progressive-plan-ratchet.lino';
const LEVELS = [
  [0, 'closed', 'superseded or withdrawn; no pass raises it'],
  [1, 'recorded', 'the row exists, nothing measures it yet'],
  [2, 'measured', 'a test pins it, but the row says it is not delivered'],
  [3, 'partial', 'delivered in part'],
  [4, 'implemented', 'delivered, with a test'],
];
const OPEN_LEVELS = LEVELS.filter(([level]) => level > 0 && level < 4);

/**
 * The records of one ledger file, with the file's defaults applied.
 * @param {string} text
 * @returns {Array<{id: string, shard: string, verdict: string, test: string}>}
 */
export function ledgerRecords(text) {
  const [head, ...records] = text.split(/\n  requirement\n/u);
  const field = (block, indent, key) => new RegExp(`^${indent}${key} "([^"]*)"`, 'mu').exec(block)?.[1];
  const shard = field(head, '  ', 'shard') ?? '';
  const read = (block, key) => field(block, '    ', key) ?? field(head, '  ', key) ?? '';
  return records.map((block) => ({
    id: read(block, 'id'),
    shard,
    verdict: read(block, 'verdict'),
    test: read(block, 'automated_test'),
  }));
}

/**
 * A requirement's resolution level.
 * @param {{verdict: string, test: string}} record
 * @returns {number}
 */
export function levelOf({ verdict, test }) {
  if (verdict === 'superseded' || verdict === 'withdrawn') {
    return 0;
  }
  if (verdict === 'implemented') {
    return 4;
  }
  if (verdict === 'partial') {
    return 3;
  }
  return test ? 2 : 1;
}

/**
 * The root the pinning test runs in: `javascript`, `rust` or `none`.
 * @param {{test: string}} record
 * @returns {string}
 */
export function rootOf({ test }) {
  if (/\.m?js$/u.test(test)) {
    return 'javascript';
  }
  return /\.rs$/u.test(test) ? 'rust' : 'none';
}

/**
 * The plan page.
 * @param {Array<{id: string, shard: string, verdict: string, test: string}>} records
 * @returns {string}
 */
export function renderPlan(records) {
  const byLevel = new Map(LEVELS.map(([level]) => [level, []]));
  for (const record of records) {
    byLevel.get(levelOf(record)).push(record);
  }
  const roots = { javascript: 0, rust: 0, none: 0 };
  for (const record of records) {
    roots[rootOf(record)] += 1;
  }
  const open = ([level]) => level > 0 && level < 4 && byLevel.get(level).length > 0;
  const next = LEVELS.find(open);
  const listing = (level) => {
    const shards = new Map();
    for (const record of byLevel.get(level)) {
      shards.set(record.shard, [...(shards.get(record.shard) ?? []), record.id]);
    }
    return [...shards]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([shard, ids]) => `- \`${shard}\`: ${ids.sort((left, right) => left.localeCompare(right, 'en', { numeric: true })).join(', ')}`);
  };
  return [
    '# Progressive plan',
    '',
    '<!-- Generated by `node scripts/render-progressive-plan.mjs --write` from data/meta/requirement-status-ledger/. Do not edit by hand. -->',
    '',
    'The progressive JPEG method ([docs/progressive-delivery.md](progressive-delivery.md), R1188-U28): every',
    'requirement is on a resolution level, and the next pass raises the lowest level first.',
    '',
    '| Level | Meaning | Requirements |',
    '| ---: | --- | ---: |',
    ...LEVELS.map(([level, name, meaning]) => `| ${level} ${name} | ${meaning} | ${byLevel.get(level).length} |`),
    `| | **all** | **${records.length}** |`,
    '',
    '## JavaScript first',
    '',
    'The root the test that pins each requirement runs in (R1188-U29: the JavaScript requirements pass first).',
    '',
    '| Pinned by | Requirements |',
    '| --- | ---: |',
    `| a JavaScript test | ${roots.javascript} |`,
    `| a Rust test only | ${roots.rust} |`,
    `| no test | ${roots.none} |`,
    '',
    '## Next pass',
    '',
    next
      ? `Level ${next[0]} (${next[1]}): ${byLevel.get(next[0]).length} requirement(s) to raise before any level above it is refined.`
      : 'Every requirement is implemented; the next pass refines measured quality.',
    '',
    ...LEVELS.filter(open).flatMap(([level, name]) => [
      `### Level ${level}: ${name}`,
      '',
      ...listing(level),
      '',
    ]),
  ].join('\n');
}

/**
 * The measured values the ratchet holds: the requirement count, the count on
 * each open level and the count pinned only by a Rust test.
 * @param {Array<{verdict: string, test: string}>} records
 * @returns {Record<string, number>}
 */
export function measure(records) {
  const measured = { requirements: records.length, 'rust-only-ceiling': 0 };
  for (const [level, name] of OPEN_LEVELS) {
    measured[`${name}-ceiling`] = records.filter((record) => levelOf(record) === level).length;
  }
  measured['rust-only-ceiling'] = records.filter((record) => rootOf(record) === 'rust').length;
  return measured;
}

/**
 * Hold the measured values to the ratchet (R1188-U28, R1188-U29). An open
 * level may grow only by the requirements recorded since the ratchet was
 * written and by the rows that rose out of the open levels below it, so a pass
 * that refines a high level while a lower one grows fails; the Rust-only count
 * never grows. The next ratchet lowers every ceiling that fell and never raises
 * one past its allowance.
 * @param {Record<string, number>} measured
 * @param {Record<string, number>} ratchet
 * @returns {{grown: Array<string>, next: Record<string, number>}}
 */
export function holdRatchet(measured, ratchet) {
  const added = Math.max(0, measured.requirements - ratchet.requirements);
  const grown = [];
  const next = { requirements: measured.requirements };
  let risen = 0;
  for (const [level, name] of [...OPEN_LEVELS, [null, 'rust-only']]) {
    const key = `${name}-ceiling`;
    const allowance = ratchet[key] + (level === null ? 0 : added + risen);
    if (level !== null) {
      risen += Math.max(0, allowance - measured[key]);
    }
    if (measured[key] > allowance) {
      grown.push(
        level === null
          ? `${measured[key] - allowance} more requirement(s) pinned only by a Rust test (R1188-U29: JavaScript first); pin them with a JavaScript test.`
          : `level ${level} (${name}) grew by ${measured[key] - allowance} beyond the requirements recorded since the ratchet and the rows risen from below (R1188-U28: raise the lowest level first); raise those rows before refining a higher level.`,
      );
    }
    next[key] = Math.min(measured[key], allowance);
  }
  return { grown, next };
}

/**
 * The ratchet values of a ratchet file.
 * @param {string} text
 * @returns {Record<string, number>}
 */
export function ratchetValues(text) {
  return Object.fromEntries([...text.matchAll(/^\s+([a-z-]+)\s+(\d+)\s*$/gmu)].map((match) => [match[1], Number(match[2])]));
}

/**
 * The ratchet file for `values`.
 * @param {Record<string, number>} values
 * @returns {string}
 */
export function renderRatchet(values) {
  return [
    '# Generated by `node scripts/render-progressive-plan.mjs --write`, which only lowers a ceiling.',
    '# The progressive plan\'s ratchet (R1188-U28, R1188-U29; gate check-progressive-plan).',
    '# An open level (recorded, measured, partial) may grow only by the requirements recorded',
    '# since `requirements`, so a pass never refines a high level while a lower one grows; the',
    '# requirements pinned only by a Rust test never grow (JavaScript first).',
    'progressive-plan-ratchet',
    ...Object.entries(values).map(([key, value]) => `  ${key} ${value}`),
    '',
  ].join('\n');
}

function main(argv) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const records = readdirSync(join(root, LEDGER))
    .filter((name) => name.endsWith('.lino'))
    .sort()
    .flatMap((name) => ledgerRecords(readFileSync(join(root, LEDGER, name), 'utf8')))
    .filter((record) => record.id);
  const page = renderPlan(records);
  const ratchetText = readFileSync(join(root, RATCHET), 'utf8');
  const measured = measure(records);
  const { grown, next } = holdRatchet(measured, ratchetValues(ratchetText));
  const problems = grown.map((problem) => `::error file=${RATCHET}::${problem}`);
  if (argv.includes('--write')) {
    writeFileSync(join(root, PLAN), page);
    writeFileSync(join(root, RATCHET), renderRatchet(next));
    console.log(`wrote ${PLAN} and ${RATCHET}: ${records.length} requirements`);
  } else {
    let current = '';
    try {
      current = readFileSync(join(root, PLAN), 'utf8');
    } catch {
      current = '';
    }
    if (current !== page) {
      problems.push(`::error file=${PLAN}::${PLAN} is stale; run node scripts/render-progressive-plan.mjs --write`);
    }
    if (grown.length === 0 && ratchetText !== renderRatchet(next)) {
      problems.push(`::error file=${RATCHET}::a ceiling fell or requirements were recorded; run node scripts/render-progressive-plan.mjs --write to lower the ratchet in this commit.`);
    }
  }
  for (const problem of problems) {
    console.error(problem);
  }
  console.log(
    `progressive plan: ${records.length} requirements; ` +
      OPEN_LEVELS.map(([, name]) => `${name} ${measured[`${name}-ceiling`]}`).join(', ') +
      `; ${measured['rust-only-ceiling']} pinned only by Rust`,
  );
  return problems.length ? 1 : 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
