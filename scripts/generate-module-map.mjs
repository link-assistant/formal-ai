#!/usr/bin/env node
// JavaScript twin of scripts/generate-module-map.rs (issue #954, E102): the
// generated "Module map" section of docs/architecture/module-map.md, one row
// per `pub mod` in rust/src/lib.rs.
//
// Issue #1191: the Rust script and the `issue_954_module_map` unit test ran
// only on main, so the pull request that added `standing_scope` (#1559) was
// green and main then failed (run 43730270231). This twin runs the same
// `--check` in the fast pull-request inventory without compiling Rust. It
// reads the override and section tables out of the Rust script itself, so
// the two cannot disagree on data, only on code, which the parity gate pins.
//
// Usage:
//   node scripts/generate-module-map.mjs            # print the section
//   node scripts/generate-module-map.mjs --check    # the map lists exactly lib.rs's modules
//   node scripts/generate-module-map.mjs --write    # replace the section in the doc

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LIB = 'rust/src/lib.rs';
const ARCHITECTURE = 'docs/architecture/module-map.md';
const SCRIPT = 'scripts/generate-module-map.rs';
export const BEGIN = '<!-- module-map:begin (generated by scripts/generate-module-map.rs) -->';
export const END = '<!-- module-map:end -->';

const read = (root, relative) => readFileSync(join(root, relative), 'utf8');

/** The text of the Rust constant `name`, from its declaration to its closing `];`. */
function rustConstant(source, name) {
  const start = source.indexOf(`const ${name}:`);
  if (start < 0) throw new Error(`${SCRIPT} declares ${name}`);
  const end = source.indexOf('\n];', start);
  return source.slice(start, end);
}

const literals = text => [...text.matchAll(/"((?:[^"\\]|\\.)*)"/gu)].map(match => JSON.parse(`"${match[1]}"`));

/** OVERRIDES and SECTION_RULES, parsed from the Rust script. */
export function tables(rustSource) {
  const overrideBody = rustConstant(rustSource, 'OVERRIDES');
  const flat = literals(overrideBody.slice(overrideBody.indexOf('= &[')));
  if (flat.length % 2 !== 0) throw new Error('OVERRIDES holds (name, sentence) pairs');
  const overrides = new Map();
  for (let index = 0; index < flat.length; index += 2) overrides.set(flat[index], flat[index + 1]);
  const ruleBody = rustConstant(rustSource, 'SECTION_RULES');
  const rules = [...ruleBody.matchAll(/\(\s*&\[([^\]]*)\]\s*,\s*"([^"]+)"\s*,\s*(true|false)\s*,?\s*\)/gu)]
    .map(([, needles, section, prefix]) => ({ needles: literals(needles), section, prefix: prefix === 'true' }));
  if (rules.length === 0) throw new Error('SECTION_RULES parsed to no rules');
  return { overrides, rules };
}

export function sectionFor(name, rules) {
  for (const { needles, section, prefix } of rules) {
    if (needles.some(needle => (prefix ? name.startsWith(needle) : name.includes(needle)))) return section;
  }
  return '2';
}

// The module's own `//!` first line, or the opening of its block-comment header.
export function headerDoc(root, name) {
  for (const candidate of [`rust/src/${name}.rs`, `rust/src/${name}/mod.rs`]) {
    if (!existsSync(join(root, candidate))) continue;
    let first = '';
    for (const line of read(root, candidate).split('\n')) {
      const trimmed = line.trim();
      if (trimmed === '') continue;
      if (trimmed.startsWith('//!')) {
        const rest = trimmed.slice(3).trim();
        if (rest !== '' && first === '') first = rest;
        break;
      }
      if (trimmed.startsWith('/*') || trimmed.startsWith('*')) {
        const body = trimmed.replace(/^(?:\/\*)+/u, '').replace(/(?:\*\/)+$/u, '').trim();
        if (body !== '') first = `${first}${body}`;
        if (trimmed.endsWith('*/')) break;
        continue;
      }
      if (trimmed.startsWith('//')) continue;
      break;
    }
    return first === '' ? null : first;
  }
  return null;
}

const TAILS = [' and', ' the', ' of', ' to', ' a', ' an', ' in', ' for', ' with', ' by', ' —', '—', '*how*'];

export function tidy(source) {
  let doc = source.split(/\s+/u).filter(Boolean).join(' ');
  while (doc.endsWith('.')) doc = doc.slice(0, -1).trimEnd();
  if ([...doc].length > 108) {
    doc = [...doc].slice(0, 105).join('');
    const cut = doc.lastIndexOf(' ');
    if (cut >= 0) doc = doc.slice(0, cut);
  }
  for (const tail of TAILS) {
    if (doc.endsWith(tail)) doc = doc.slice(0, doc.length - tail.length).trimEnd();
  }
  return `${doc}.`;
}

export function rows(root = ROOT) {
  const { overrides, rules } = tables(read(root, SCRIPT));
  const result = [];
  for (const line of read(root, LIB).split('\n')) {
    const match = /^pub mod (.*);$/u.exec(line.replace(/\r$/u, ''));
    if (!match) continue;
    const name = match[1];
    result.push({ name, responsibility: tidy(overrides.get(name) ?? headerDoc(root, name) ?? ''), section: sectionFor(name, rules) });
  }
  const number = section => Number.isNaN(Number.parseFloat(section)) ? 2 : Number.parseFloat(section);
  return result.sort((left, right) => number(left.section) - number(right.section)
    || (left.name < right.name ? -1 : left.name > right.name ? 1 : 0));
}

export function rendered(root = ROOT) {
  return `${BEGIN}\n`
    + 'One row per module declared in `rust/src/lib.rs`. Regenerate with\n'
    + '`rust-script scripts/generate-module-map.rs --write`; the module list is\n'
    + 'pinned by `rust/tests/unit/issue_954_module_map.rs` (and `--check`), so a\n'
    + 'new module fails CI until this map documents it.\n\n'
    + '| Module | Responsibility | Owning section |\n|---|---|---|\n'
    + rows(root).map(row => `| \`${row.name}\` | ${row.responsibility} | §${row.section} |\n`).join('')
    + END;
}

/** The first column of every table row whose first cell is a bare `` `name` ``. */
export function mappedNames(section) {
  const names = [];
  for (const line of section.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('|')) continue;
    const rest = trimmed.slice(1).trim();
    if (rest.startsWith('---') || rest.startsWith('Module |')) continue;
    const bar = rest.indexOf('|');
    if (bar < 0) continue;
    const name = rest.slice(0, bar).trim().replace(/^`+|`+$/gu, '');
    if (name !== '' && /^[A-Za-z0-9_]+$/u.test(name)) names.push(name);
  }
  return names;
}

export function committedSection(architecture) {
  const begin = architecture.indexOf(BEGIN);
  const end = architecture.indexOf(END);
  if (begin < 0) throw new Error(`${ARCHITECTURE} carries the module-map begin marker`);
  if (end < 0) throw new Error(`${ARCHITECTURE} carries the module-map end marker`);
  return architecture.slice(begin, end + END.length);
}

/** Modules declared but unmapped, and rows naming no declared module. */
export function coverage(root = ROOT) {
  const declared = rows(root).map(row => row.name);
  const mapped = mappedNames(committedSection(read(root, ARCHITECTURE)));
  return {
    declared,
    missing: declared.filter(name => !mapped.includes(name)),
    stale: mapped.filter(name => !declared.includes(name)),
  };
}

const debugList = values => `[${values.map(value => JSON.stringify(value)).join(', ')}]`;

export function main(argv = process.argv.slice(2), root = ROOT) {
  const architecture = read(root, ARCHITECTURE);
  if (argv.includes('--check')) {
    const { declared, missing, stale } = coverage(root);
    if (missing.length > 0 || stale.length > 0) {
      process.stderr.write(`generate-module-map: the ${ARCHITECTURE} module map is out of sync with ${LIB} -- missing ${debugList(missing)}, stale ${debugList(stale)}; run --write\n`);
      return 1;
    }
    process.stdout.write(`module map covers all ${declared.length} declared modules\n`);
    return 0;
  }
  if (argv.includes('--write')) {
    const updated = architecture.slice(0, architecture.indexOf(BEGIN)) + rendered(root)
      + architecture.slice(architecture.indexOf(END) + END.length);
    writeFileSync(join(root, ARCHITECTURE), updated);
    process.stdout.write(`rewrote the module map section in ${ARCHITECTURE}\n`);
    return 0;
  }
  process.stdout.write(rendered(root));
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.exitCode = main();
