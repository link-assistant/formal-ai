// Generated renderer assets travel separately from the selected Git source and WASM.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {copyFileSync,lstatSync,mkdirSync,readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

export const WEB_FILES=Object.freeze([
  'app.js','mermaid.bundle.js','ocr.bundle.js','precache-manifest.js',
  'seed-files.js','service-worker.js','vendor.bundle.js',
  'web-search-component.bundle.js','worker-bootstrap-responses.js',
]);
const RECEIPT='web-receipt.json';
const MAX_FILE=32*1024*1024;
const MAX_TOTAL=64*1024*1024;
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');

function ordinary(directory,name) {
  const path=join(directory,name);
  assert(lstatSync(directory).isDirectory()&&!lstatSync(directory).isSymbolicLink(),'symlink directory');
  const stat=lstatSync(path);
  assert(stat.isFile()&&!stat.isSymbolicLink(),'ordinary web file required');
  assert(stat.size>0&&stat.size<=MAX_FILE,'web file byte budget exceeded');
  return path;
}

function identity(selectionBytes,context) {
  const selection=JSON.parse(selectionBytes);
  assert.equal(selection.version,1);
  assert.match(selection.source_commit,/^[a-f0-9]{40}$/u);
  assert.match(selection.source_tree,/^[a-f0-9]{40}$/u);
  assert.equal(selection.source_commit,context.commit);
  assert.equal(selection.source_tree,context.tree);
  assert.equal(selection.producer_run,String(context.run));
  assert.equal(typeof selection.package_version,'string');
  assert(selection.package_version.length>0);
  return {
    source_commit:selection.source_commit,source_tree:selection.source_tree,
    package_version:selection.package_version,producer_run:selection.producer_run,
    selection_sha256:digest(selectionBytes),
  };
}

/** Seal only real generated bytes; this function never builds or substitutes UI. */
export function sealWeb(root,directory,selectionBytes,context) {
  const bound=identity(selectionBytes,context);
  mkdirSync(directory,{recursive:true});
  assert.deepEqual(readdirSync(directory),[],'web output must start empty');
  let total=0;
  const files=WEB_FILES.map(name=>{
    const source=ordinary(join(root,'js'),name);
    const bytes=readFileSync(source);
    total+=bytes.length;
    assert(total<=MAX_TOTAL,'total web byte budget exceeded');
    copyFileSync(source,join(directory,name));
    return {name,bytes:bytes.length,sha256:digest(bytes)};
  });
  const receipt={schema:'formal-ai-release-web-v1',...bound,files};
  writeFileSync(join(directory,RECEIPT),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
  return receipt;
}

/** Validate the entire finite payload before installing a single renderer file. */
export function importWeb(root,directory,selectionBytes,context) {
  const expected=identity(selectionBytes,context);
  assert.deepEqual(readdirSync(directory).sort(),[...WEB_FILES,RECEIPT].sort());
  const receiptPath=ordinary(directory,RECEIPT);
  assert(lstatSync(receiptPath).size<=16384,'web receipt byte budget exceeded');
  const receipt=JSON.parse(readFileSync(receiptPath,'utf8'));
  const {schema,files,...bound}=receipt;
  assert.equal(schema,'formal-ai-release-web-v1');
  assert.deepEqual(bound,expected);
  assert.equal(files.length,WEB_FILES.length);
  let total=0;
  for(let index=0;index<WEB_FILES.length;index++) {
    const entry=files[index],name=WEB_FILES[index];
    assert.deepEqual(Object.keys(entry).sort(),['bytes','name','sha256']);
    assert.equal(entry.name,name);
    const path=ordinary(directory,name),size=lstatSync(path).size;
    total+=size;
    assert(total<=MAX_TOTAL,'total web byte budget exceeded');
    assert.equal(size,entry.bytes);
    assert.equal(digest(readFileSync(path)),entry.sha256);
  }
  const destination=join(root,'js');
  assert(lstatSync(destination).isDirectory()&&!lstatSync(destination).isSymbolicLink(),'symlink destination');
  for(const name of WEB_FILES) {
    // Existing generated outputs must not redirect writes outside the checkout.
    try {
      assert(!lstatSync(join(destination,name)).isSymbolicLink(),'symlink output');
    } catch(error) {
      if(error.code!=='ENOENT')throw error;
    }
  }
  for(const name of WEB_FILES)copyFileSync(join(directory,name),join(destination,name));
  return receipt;
}

if(import.meta.url===pathToFileURL(process.argv[1]??'').href) {
  assert.equal(process.env.CI,'true','release web handoff is CI only');
  assert.equal(process.env.GITHUB_ACTIONS,'true');
  const [mode,selectionPath,directory]=process.argv.slice(2);
  assert(['seal','import'].includes(mode));
  assert(selectionPath&&directory);
  const root=process.cwd();
  const git=args=>execFileSync('git',args,{cwd:root,encoding:'utf8',timeout:10000}).trim();
  const context={commit:git(['rev-parse','HEAD']),tree:git(['rev-parse','HEAD^{tree}']),
    run:process.env.GITHUB_RUN_ID};
  const operation=mode==='seal'?sealWeb:importWeb;
  const receipt=operation(root,resolve(directory),readFileSync(selectionPath),context);
  console.log(JSON.stringify({schema:receipt.schema,source_commit:receipt.source_commit,
    files:receipt.files.length,mode}));
}
