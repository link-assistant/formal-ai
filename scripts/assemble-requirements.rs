#!/usr/bin/env rust-script
//! Assemble `REQUIREMENTS.md` from one shard per issue.
//!
//! Issue #991: `REQUIREMENTS.md` was the repository's worst append-only
//! document. Every issue adds a `## Issue #N ...` section, every branch adds it
//! at the end of the same file, and so two unrelated issues collide on the same
//! end-of-file region. `scripts/analyze-merge-conflicts.py` counted 64 manual
//! resolutions in this one file.
//!
//! The fix is to give each section its own file under `docs/requirements/` and
//! make `REQUIREMENTS.md` a derived artifact. Two branches writing requirements
//! for two different issues now create two different files and cannot conflict.
//!
//! Shards are assembled in a total order read entirely from the file name, so
//! there is no shared index file to conflict on either:
//!
//! | prefix      | position | sorted by                             |
//! | ----------- | -------- | ------------------------------------- |
//! | `preamble-` | first    | file name                             |
//! | `issue-`    | middle   | zero-padded issue number, then slug    |
//! | `doctrine-` | last     | file name                             |
//!
//! Usage:
//!   rust-script scripts/assemble-requirements.rs           # check REQUIREMENTS.md is current
//!   rust-script scripts/assemble-requirements.rs --write   # rebuild REQUIREMENTS.md
//!   rust-script scripts/assemble-requirements.rs --split   # re-shard REQUIREMENTS.md
//!
//! ```cargo
//! [dependencies]
//! ```

use std::fs;
use std::path::{Path, PathBuf};

#[cfg(not(test))]
const DOCUMENT: &str = "REQUIREMENTS.md";
const SHARDS: &str = "docs/requirements";
const BANNER: &str = "<!-- Generated by `rust-script scripts/assemble-requirements.rs --write` from `docs/requirements/`. Edit the shard for your issue, never this file: see `data/meta/merge-conflict-policy.lino`. -->";

/// Where a shard sits in the assembled document, read from its file name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Group {
    Preamble,
    Issue(u32),
    Doctrine,
}

/// The total order of a shard: group first, then the file name inside it.
fn shard_order(file_name: &str) -> Option<(Group, String)> {
    let stem = file_name.strip_suffix(".md")?;
    let group = if let Some(rest) = stem.strip_prefix("issue-") {
        let digits: String = rest.chars().take_while(char::is_ascii_digit).collect();
        Group::Issue(digits.parse().ok()?)
    } else if stem.starts_with("preamble-") {
        Group::Preamble
    } else if stem.starts_with("doctrine-") {
        Group::Doctrine
    } else {
        return None;
    };
    Some((group, stem.to_string()))
}

/// The issue number a section heading claims, if it names one.
fn heading_issue(heading: &str) -> Option<u32> {
    let rest = heading.split_once("Issue #")?.1;
    let digits: String = rest.chars().take_while(char::is_ascii_digit).collect();
    digits.parse().ok()
}

/// A file-name-safe slug for a section heading.
fn slug(heading: &str) -> String {
    let mut slug = String::new();
    for character in heading.chars() {
        if character.is_ascii_alphanumeric() {
            slug.push(character.to_ascii_lowercase());
        } else if !slug.ends_with('-') {
            slug.push('-');
        }
    }
    slug.trim_matches('-').to_string()
}

/// Split a document into its leading preamble and its `## ` sections.
fn sections(document: &str) -> (String, Vec<String>) {
    let mut preamble = String::new();
    let mut sections: Vec<String> = Vec::new();
    for line in document.lines() {
        if line.starts_with("## ") {
            sections.push(String::new());
        }
        let target = sections.last_mut().unwrap_or(&mut preamble);
        target.push_str(line);
        target.push('\n');
    }
    (preamble, sections)
}

/// The shard file name for a section, derived from its heading.
fn shard_name(heading: &str) -> String {
    let title = heading.trim_start_matches('#').trim();
    match heading_issue(heading) {
        Some(issue) => {
            let subject = title
                .strip_prefix(&format!("Issue #{issue}"))
                .unwrap_or(title);
            format!("issue-{issue:04}-{}.md", slug(subject))
        }
        None => format!("doctrine-{}.md", slug(title)),
    }
}

/// Read the shard directory in assembly order.
fn ordered_shards(directory: &Path) -> Result<Vec<PathBuf>, String> {
    let mut shards: Vec<(Group, String, PathBuf)> = Vec::new();
    let entries =
        fs::read_dir(directory).map_err(|error| format!("cannot read {SHARDS}: {error}"))?;
    for entry in entries {
        let path = entry.map_err(|error| error.to_string())?.path();
        let Some(file_name) = path.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        if !file_name.ends_with(".md") || file_name == "README.md" {
            continue;
        }
        let (group, key) = shard_order(file_name).ok_or_else(|| {
            format!(
                "{SHARDS}/{file_name} must start with `preamble-`, `issue-NNNN-` or `doctrine-`"
            )
        })?;
        shards.push((group, key, path));
    }
    shards.sort();
    Ok(shards.into_iter().map(|(_, _, path)| path).collect())
}

/// The document the shards currently describe.
fn assemble(shards: &[PathBuf]) -> Result<String, String> {
    let mut document = format!("{BANNER}\n\n");
    for (index, shard) in shards.iter().enumerate() {
        let body = fs::read_to_string(shard)
            .map_err(|error| format!("cannot read {}: {error}", shard.display()))?;
        let body = body.trim_end_matches('\n');
        if index > 0 {
            document.push('\n');
        }
        document.push_str(body);
        document.push('\n');
    }
    Ok(document)
}

/// Every rule a shard directory has to satisfy.
fn shard_violations(shards: &[PathBuf], read: &dyn Fn(&Path) -> String) -> Vec<String> {
    let mut failures = Vec::new();
    for shard in shards {
        let name = shard
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or_default();
        let body = read(shard);
        let heading = body.lines().next().unwrap_or_default();
        let Some(issue) = heading_issue(heading) else {
            continue;
        };
        if !heading.starts_with("## ") {
            continue;
        }
        if !name.starts_with(&format!("issue-{issue:04}-")) {
            failures.push(format!(
                "{SHARDS}/{name} starts with the heading `{heading}`, so it must be named \
                 `issue-{issue:04}-<slug>.md`"
            ));
        }
    }
    failures
}

/// Write the current document out as one file per section.
#[cfg(not(test))]
fn split(root: &Path) -> Result<usize, String> {
    let document = fs::read_to_string(root.join(DOCUMENT))
        .map_err(|error| format!("cannot read {DOCUMENT}: {error}"))?;
    let document = document.strip_prefix(BANNER).unwrap_or(&document);
    let (preamble, sections) = sections(document.trim_start());
    let directory = root.join(SHARDS);
    fs::create_dir_all(&directory).map_err(|error| error.to_string())?;

    let mut written = 0;
    let title = preamble.lines().next().unwrap_or("# Requirements");
    let name = format!("preamble-{}.md", slug(title));
    write_shard(&directory.join(&name), &preamble)?;
    written += 1;

    for section in &sections {
        let heading = section.lines().next().unwrap_or_default();
        write_shard(&directory.join(shard_name(heading)), section)?;
        written += 1;
    }
    Ok(written)
}

#[cfg(not(test))]
fn write_shard(path: &Path, body: &str) -> Result<(), String> {
    if path.exists() {
        return Err(format!(
            "{} already exists; two sections produced the same shard name",
            path.display()
        ));
    }
    let body = format!("{}\n", body.trim_end_matches('\n'));
    fs::write(path, body).map_err(|error| format!("cannot write {}: {error}", path.display()))
}

#[cfg(not(test))]
fn main() {
    let root = std::env::current_dir().expect("Failed to get current directory");
    let mode = std::env::args().nth(1).unwrap_or_default();

    if mode == "--split" {
        match split(&root) {
            Ok(written) => {
                println!("\nWrote {written} shard(s) to {SHARDS}/.\n");
                return;
            }
            Err(error) => {
                println!("::error::{error}");
                std::process::exit(1);
            }
        }
    }

    let shards = ordered_shards(&root.join(SHARDS)).unwrap_or_else(|error| {
        println!("::error::{error}");
        std::process::exit(1);
    });
    let read = |path: &Path| fs::read_to_string(path).unwrap_or_default();
    let failures = shard_violations(&shards, &read);
    if !failures.is_empty() {
        for failure in &failures {
            println!("::error::{failure}");
        }
        std::process::exit(1);
    }

    let assembled = assemble(&shards).unwrap_or_else(|error| {
        println!("::error::{error}");
        std::process::exit(1);
    });
    let document = root.join(DOCUMENT);
    let current = fs::read_to_string(&document).unwrap_or_default();

    if mode == "--write" {
        if current == assembled {
            println!("\n{DOCUMENT} is already current ({} shards).\n", shards.len());
        } else {
            fs::write(&document, &assembled).expect("Failed to write REQUIREMENTS.md");
            println!("\nRebuilt {DOCUMENT} from {} shards.\n", shards.len());
        }
        return;
    }

    println!("\nChecking {DOCUMENT} against {SHARDS}/ ({} shards)...\n", shards.len());
    if current == assembled {
        println!("{DOCUMENT} matches its shards.\n");
        return;
    }
    println!("::error::{DOCUMENT} does not match {SHARDS}/.");
    println!("\nRun: rust-script scripts/assemble-requirements.rs --write\n");
    std::process::exit(1);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_preamble_sorts_first_then_issues_by_number_then_doctrine() {
        let mut names = vec![
            "doctrine-compiled-logic.md",
            "issue-0991-how-to-synthesis.md",
            "preamble-requirements-for-issue-1.md",
            "issue-0016-multilingual.md",
            "issue-0016-follow-up.md",
        ];
        names.sort_by_key(|name| shard_order(name).expect("named correctly"));
        assert_eq!(
            names,
            [
                "preamble-requirements-for-issue-1.md",
                "issue-0016-follow-up.md",
                "issue-0016-multilingual.md",
                "issue-0991-how-to-synthesis.md",
                "doctrine-compiled-logic.md",
            ]
        );
    }

    #[test]
    fn issue_numbers_order_numerically_not_lexicographically() {
        assert!(shard_order("issue-0016-a.md") < shard_order("issue-0117-a.md"));
        assert!(shard_order("issue-0991-a.md") < shard_order("issue-1000-a.md"));
    }

    #[test]
    fn an_unprefixed_shard_name_is_rejected() {
        assert_eq!(shard_order("current-scope-boundary.md"), None);
        assert_eq!(shard_order("issue-0991-notes.txt"), None);
    }

    #[test]
    fn a_heading_names_the_first_issue_it_mentions() {
        assert_eq!(
            heading_issue("## Issue #16 Follow-Up: Universal Data/Seed (PR #17 reopen)"),
            Some(16)
        );
        assert_eq!(
            heading_issue("## Issue #398 PR Review Standards (comment 4663407299)"),
            Some(398)
        );
        assert_eq!(heading_issue("## Current Scope Boundary"), None);
    }

    #[test]
    fn a_shard_name_is_derived_from_its_heading() {
        assert_eq!(
            shard_name("## Issue #991 Dynamic Multi-Source How-To Synthesis"),
            "issue-0991-dynamic-multi-source-how-to-synthesis.md"
        );
        assert_eq!(
            shard_name("## Standing Doctrine: Compiled Logic (2026-08-04)"),
            "doctrine-standing-doctrine-compiled-logic-2026-08-04.md"
        );
    }

    #[test]
    fn splitting_keeps_the_preamble_apart_from_the_sections() {
        let (preamble, sections) = sections("# Title\n\nIntro.\n\n## One\n\na\n\n## Two\n\nb\n");
        assert_eq!(preamble, "# Title\n\nIntro.\n\n");
        assert_eq!(sections, ["## One\n\na\n\n", "## Two\n\nb\n"]);
    }

    #[test]
    fn assembly_separates_sections_by_exactly_one_blank_line() {
        let directory = std::env::temp_dir().join("assemble-requirements-blank-lines");
        let _ = fs::remove_dir_all(&directory);
        fs::create_dir_all(&directory).expect("temp dir");
        fs::write(directory.join("preamble-a.md"), "# Title\n\nIntro.\n").expect("write");
        fs::write(directory.join("issue-0002-b.md"), "## Issue #2\n\nb\n\n\n").expect("write");
        let shards = ordered_shards(&directory).expect("ordered");
        assert_eq!(
            assemble(&shards).expect("assembled"),
            format!("{BANNER}\n\n# Title\n\nIntro.\n\n## Issue #2\n\nb\n")
        );
        let _ = fs::remove_dir_all(&directory);
    }

    #[test]
    fn a_shard_named_for_the_wrong_issue_fails() {
        let shards = [PathBuf::from("docs/requirements/issue-0991-copy.md")];
        let read = |_path: &Path| "## Issue #709 Multi-Source Search Fusion\n".to_string();
        let failures = shard_violations(&shards, &read);
        assert!(
            failures.iter().any(|failure| failure.contains("issue-0709-")),
            "{failures:?}"
        );
    }

    #[test]
    fn a_shard_named_for_its_own_issue_passes() {
        let shards = [PathBuf::from("docs/requirements/issue-0709-fusion.md")];
        let read = |_path: &Path| "## Issue #709 Multi-Source Search Fusion\n".to_string();
        assert!(shard_violations(&shards, &read).is_empty());
    }
}
