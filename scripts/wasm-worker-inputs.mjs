#!/usr/bin/env node
// The inputs the committed browser worker was compiled from (issue #1569).
//
// Gate check-wasm-worker-current rebuilds js/formal_ai_worker.wasm and diffs it
// against the commit, but only on main: pull requests skip the production
// build. On 2026-11-14/15 three merged commits (c50eedf30, 0bb8317e0,
// 29a8be67e) edited rust/src/language.rs and its seed, passed their pull
// requests, and turned main red. Separately, the hosted runners moved from
// rustc 1.99.1 to 1.100.0, which compiles the same sources to different bytes.
//
// `--write` compiles the worker with the operands of js/wasm-worker/build.sh
// (wasmCompilerArguments) and records the compiler's dependency closure, the
// digest of every input, the digest of the binary and the compiler in
// data/meta/wasm-worker-inputs.lino.
// `--check` needs no compiler, so the fast pull-request tier runs it: a pull
// request that edits a worker input without rebuilding fails there.
// `--explain` runs where the gate fails, after a rebuild: it names which of the
// two causes moved, the inputs or the compiler.
//
// Usage:
//   node scripts/wasm-worker-inputs.mjs --write | --check | --explain [--repository <path>]
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, posix, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

import {dependencyPaths, wasmCompilerArguments} from './build-selected-wasm.mjs';

export const MANIFEST = 'data/meta/wasm-worker-inputs.lino';
export const WORKER = 'js/formal_ai_worker.wasm';
const REBUILD = 'node scripts/wasm-worker-inputs.mjs --write';

const HEADER = `# The inputs js/formal_ai_worker.wasm was compiled from (issue #1569).
#
# Generated by \`node scripts/wasm-worker-inputs.mjs --write\`, which compiles
# the worker with the operands of js/wasm-worker/build.sh and records the
# compiler's dependency closure; never edited by hand. The fast pull-request
# tier runs \`--check\`, which needs no compiler: a pull request that edits a
# file below without rebuilding the worker fails there instead of on main
# (gate check-wasm-worker-current). The compiler is recorded so that a main
# failure with unchanged inputs names the toolchain that moved.
`;

const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const quoted = value => '"' + value.replace(/\\/gu, '\\\\').replace(/"/gu, '\\"') + '"';
const unquoted = value => value.startsWith('"') ? value.slice(1, -1).replace(/\\(.)/gu, '$1') : value;

/** The manifest text for a worker binary, its compiler and its inputs. */
export function renderManifest({worker, compiler, inputs}) {
  const lines = [HEADER.trimEnd(), 'wasm-worker-inputs', '  worker ' + WORKER, '  bytes ' + worker.bytes,
    '  sha256 ' + worker.sha256, '  compiler ' + quoted(compiler.release), '  compiler-commit ' + compiler.commit];
  for (const input of inputs) {
    if (/\s|"/u.test(input.path)) throw Error('an input path with whitespace or quotes needs a quoting rule: ' + input.path);
    lines.push('input ' + input.path, '  sha256 ' + input.sha256);
  }
  return lines.join('\n') + '\n';
}

/** The record `renderManifest` wrote. */
export function parseManifest(text) {
  const manifest = {worker: {}, compiler: {}, inputs: []};
  let current = null;
  for (const line of text.split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const nested = line.startsWith('  ');
    const [key, ...rest] = line.trim().split(' ');
    const value = unquoted(rest.join(' '));
    if (!nested && key === 'wasm-worker-inputs') current = manifest.worker;
    else if (!nested && key === 'input') manifest.inputs.push(current = {path: value});
    else if (nested && current === manifest.worker && key === 'compiler') manifest.compiler.release = value;
    else if (nested && current === manifest.worker && key === 'compiler-commit') manifest.compiler.commit = value;
    else if (nested && current === manifest.worker && key === 'bytes') manifest.worker.bytes = Number(value);
    else if (nested && current !== null && (key === 'sha256' || key === 'worker')) current[key === 'worker' ? 'path' : key] = value;
    else throw Error(MANIFEST + ': unexpected line ' + JSON.stringify(line));
  }
  if (manifest.worker.path !== WORKER || !manifest.worker.sha256 || manifest.inputs.length === 0)
    throw Error(MANIFEST + ': no worker record or no inputs');
  return manifest;
}

/** The release line and commit of `rustc -vV`. */
export function compilerIdentity(verbose) {
  const release = /^rustc [^\n]+/mu.exec(verbose)?.[0];
  const commit = /^commit-hash: ([a-f0-9]{40})$/mu.exec(verbose)?.[1];
  if (!release || !commit) throw Error('rustc -vV did not report a release and a commit hash');
  return {release, commit};
}

/**
 * Every way the tree differs from the manifest, without a compiler: an input
 * whose bytes moved or that disappeared, and a binary whose bytes moved.
 */
export function compareInputs(root, manifest, {read = path => readFileSync(join(root, path))} = {}) {
  const findings = [];
  for (const input of manifest.inputs) {
    let bytes;
    try {
      bytes = read(input.path);
    } catch {
      findings.push({kind: 'input', path: input.path, detail: 'is missing'});
      continue;
    }
    if (digest(bytes) !== input.sha256) findings.push({kind: 'input', path: input.path, detail: 'changed since the worker was built'});
  }
  const worker = read(WORKER);
  if (worker.length !== manifest.worker.bytes || digest(worker) !== manifest.worker.sha256)
    findings.push({kind: 'worker', path: WORKER, detail: 'is not the binary the manifest records'});
  return findings;
}

/** Compile the worker and return the manifest record of what was compiled. */
export function buildRecord(root, {run = (command, args) => execFileSync(command, args, {cwd: root, timeout: 300000, maxBuffer: 32 * 1024 * 1024})} = {}) {
  const directory = mkdtempSync(join(tmpdir(), 'wasm-worker-inputs-'));
  try {
    const dependencyFile = join(directory, 'formal_ai_worker.d');
    const before = compilerIdentity(run('rustc', ['-vV']).toString('utf8'));
    run('rustc', wasmCompilerArguments(dependencyFile));
    const compiler = compilerIdentity(run('rustc', ['-vV']).toString('utf8'));
    if (compiler.commit !== before.commit) throw Error('the compiler changed during the build');
    const paths = dependencyPaths(readFileSync(dependencyFile, 'utf8')).map(path => posix.normalize(path.split('\\').join('/'))).sort();
    const inputs = paths.map(path => ({path, sha256: digest(readFileSync(join(root, path)))}));
    const bytes = readFileSync(join(root, WORKER));
    return {worker: {bytes: bytes.length, sha256: digest(bytes)}, compiler, inputs};
  } finally {
    rmSync(directory, {recursive: true, force: true});
  }
}

/**
 * Why the rebuilt worker differs from the committed one, as lines for the job
 * log. `committed` is the manifest at HEAD and `verbose` the runner's `rustc -vV`.
 */
export function explainDrift(root, committed, verbose, {read} = {}) {
  const lines = [];
  const findings = compareInputs(root, committed, {read});
  for (const finding of findings) lines.push(`${finding.path} ${finding.detail}`);
  const inputs = findings.filter(finding => finding.kind === 'input');
  if (findings.some(finding => finding.kind === 'worker'))
    lines.push(`::error title=WASM worker manifest is stale::the committed worker is not the binary ${MANIFEST} records; run \`${REBUILD}\` and commit both files.`);
  if (inputs.length > 0)
    lines.push(`::error title=WASM worker inputs changed::${inputs.length} worker input(s) changed without a rebuild; run \`${REBUILD}\` and commit both files.`);
  const compiler = compilerIdentity(verbose);
  if (compiler.commit !== committed.compiler.commit)
    lines.push(`::error title=WASM worker compiler changed::the worker was built by ${committed.compiler.release} and this runner has ${compiler.release}; ` +
      `the same sources compile to different bytes. The daily dependencies-latest pull request carries the rebuilt worker, or run \`${REBUILD}\` with ${compiler.release}.`);
  if (lines.length === 0) lines.push(`::error title=WASM worker differs::the inputs and the compiler match ${MANIFEST}, yet the bytes differ; the build is not reproducible here.`);
  return lines;
}

// `log` receives every job-log line; tests pass a collector so the commands they provoke are asserted, not annotated.
export function main(argv, log = console.log) {
  let root = '.';
  const modes = [];
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--repository') root = argv[++index] ?? '';
    else modes.push(argv[index]);
  }
  root = resolve(root);
  const manifestPath = join(root, MANIFEST);
  const mode = modes.length === 1 ? modes[0] : '';
  if (mode === '--write') {
    const record = buildRecord(root);
    writeFileSync(manifestPath, renderManifest(record));
    log(`${MANIFEST}: ${record.inputs.length} inputs, worker sha256 ${record.worker.sha256}, ${record.compiler.release}`);
    return 0;
  }
  if (mode !== '--check' && mode !== '--explain') {
    process.stderr.write('usage: node scripts/wasm-worker-inputs.mjs --write | --check | --explain [--repository <path>]\n');
    return 2;
  }
  if (!existsSync(manifestPath)) {
    log(`::error::${MANIFEST} is missing; run \`${REBUILD}\`.`);
    return 1;
  }
  const manifest = parseManifest(readFileSync(manifestPath, 'utf8'));
  if (mode === '--explain') {
    // The rebuilt binary is in the working tree; the manifest describes the committed one.
    const committedWorker = execFileSync('git', ['-C', root, 'show', 'HEAD:' + WORKER], {maxBuffer: 32 * 1024 * 1024});
    const read = path => path === WORKER ? committedWorker : readFileSync(join(root, path));
    for (const line of explainDrift(root, manifest, execFileSync('rustc', ['-vV'], {cwd: root}).toString('utf8'), {read})) log(line);
    return 0;
  }
  const findings = compareInputs(root, manifest);
  for (const finding of findings) log(`${finding.path} ${finding.detail}`);
  if (findings.length === 0) {
    log(`${MANIFEST}: the committed worker matches its ${manifest.inputs.length} inputs (${manifest.compiler.release})`);
    return 0;
  }
  log(`::error title=WASM worker is stale::${findings.length} difference(s) from ${MANIFEST}; main's check-wasm-worker-current would fail. Run \`${REBUILD}\` and commit both files.`);
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) process.exitCode = main(process.argv.slice(2));
