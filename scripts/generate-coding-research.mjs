#!/usr/bin/env node
// Exact canonical JavaScript -> checked Links IR -> generated production Rust.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { toMeta, fromMeta } from './self-translation/envelope.mjs';
import { fromLino } from './self-translation/ir.mjs';
import { translateJsToTs } from './translate-es.mjs';
export const SOURCE = 'js/agentic/portable/coding_research_kernel.mjs';
export const META = 'data/meta/coding-research-kernel.lino';
export const RUST = 'rust/src/coding_research_kernel.rs';
export const TYPESCRIPT = 'ts/agentic/portable/coding_research_kernel.mts';
export function generateCodingResearch(source) {
  const meta = toMeta(source, 'JavaScript');
  assert(!meta.includes('(carried '), 'UnsupportedCanonicalResearchConstruct');
  const items = fromLino(meta);
  assert(items.length > 0, 'EmptyCanonicalResearchProgram');
  const digest = value => createHash('sha256').update(value).digest('hex');
  return {
    [META]: meta,
    [RUST]: '// Generated by scripts/generate-coding-research.mjs; do not edit.\n'
      + '// source-sha256 ' + digest(source) + '; meta-sha256 ' + digest(meta) + '\n'
      + fromMeta(items, 'Rust'),
    [TYPESCRIPT]: translateJsToTs(source),
  };
}
export function checkCodingResearch(directory, write = false) {
  const source = fs.readFileSync(path.join(directory, SOURCE), 'utf8');
  const drift = [];
  for (const [relative, expected] of Object.entries(generateCodingResearch(source))) {
    const target = path.join(directory, relative);
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) {
      drift.push(relative);
      if (write) {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, expected);
      }
    }
  }
  return drift;
}
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const directory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const mode = process.argv[2] ?? '--check';
  assert(['--check', '--write'].includes(mode));
  const drift = checkCodingResearch(directory, mode === '--write');
  if (drift.length && mode === '--check') {
    console.error('Coding research generation drift: ' + drift.join(', '));
    process.exitCode = 1;
  } else console.log('Coding research kernel matches canonical source');
}
