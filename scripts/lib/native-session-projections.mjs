/** Finite projection of the maintained Rust serializer; unsupported expressions refuse. */
export function sessionSchema(source) {
  assert.equal(typeof source,'string');
  const body=/pub fn session_json\(&self\) -> Value \{([\s\S]*?)\n    \}\n\}/u.exec(source)?.[1];
  assert.ok(body,'maintained session serializer source required');
  const root=[...body.matchAll(/^ {12}"([A-Za-z_][A-Za-z_0-9]*)": (.*)$/gmu)];
  const steps=[...body.matchAll(/^ {16}"([A-Za-z_][A-Za-z_0-9]*)": (.*)$/gmu)];
  assert.ok(root.length>0 && steps.length>0,'complete serializer field inventory required');
  assert.equal(new Set(root.map(row=>row[1])).size,root.length);
  assert.equal(new Set(steps.map(row=>row[1])).size,steps.length);
  function fieldType(struct,field) {
    const declaration=new RegExp('pub struct '+struct+' \\{([\\s\\S]*?)\\n\\}','u').exec(source)?.[1];
    assert.ok(declaration,'source-owned record type required');
    return new RegExp('pub '+field+': ([^,\\n]+),','u').exec(declaration)?.[1];
  }
  function rule(expression,owner,struct) {
    const literal=/^("(?:[^"\\]|\\.)*"),?$/u.exec(expression);
    if(literal) return {kind:'literal',value:JSON.parse(literal[1])};
    const field=new RegExp('^'+owner+'\\.([A-Za-z_][A-Za-z_0-9]*),?$','u').exec(expression)?.[1];
    if(field) {
      const type=fieldType(struct,field);
      if(type==='String') return {kind:'string'};
      if(type==='usize') return {kind:'integer'};
      if(type==='bool') return {kind:'boolean'};
      if(type==='Vec<String>') return {kind:'string-array'};
    }
    if(owner==='self' && expression==='self.steps.iter().map(|step| json!({') return {kind:'steps'};
    if(owner==='step' && expression==='serde_json::from_str::<Value>(&step.arguments)' && body.includes('.unwrap_or_else(|_| Value::String(step.arguments.clone()))')) return {kind:'json'};
    assert.fail('unsupported maintained session serializer expression: '+expression);
  }
  return {root:Object.fromEntries(root.map(row=>[row[1],rule(row[2],'self','DriverOutcome')])),steps:Object.fromEntries(steps.map(row=>[row[1],rule(row[2],'step','DriverToolStep')]))};
}
export function validateSessionShape(value,schema) {
  function object(value,rules) {
    assert.ok(value && typeof value==='object' && !Array.isArray(value),'session record required');
    assert.deepEqual(Object.keys(value).sort(),Object.keys(rules).sort(),'source-derived serializer keys differ');
    for(const [field,rule] of Object.entries(rules)) {
      const observed=value[field];
      if(rule.kind==='literal') assert.equal(observed,rule.value,'source-owned serializer literal differs');
      else if(rule.kind==='string') assert.equal(typeof observed,'string');
      else if(rule.kind==='boolean') assert.equal(typeof observed,'boolean');
      else if(rule.kind==='integer') assert.ok(Number.isSafeInteger(observed) && observed>=0,'native unsigned integer required');
      else if(rule.kind==='string-array') assert.ok(Array.isArray(observed) && observed.every(item=>typeof item==='string'));
      else if(rule.kind==='steps') {assert.ok(Array.isArray(observed));observed.forEach(step=>object(step,schema.steps));}
      else assert.equal(rule.kind,'json','unsupported session shape rule');
    }
  }
  object(value,schema.root);return value;
}
