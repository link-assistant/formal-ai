export const digest = bytes => createHash('sha256').update(bytes).digest('hex');
export function projectionRegistry(source) {
  assert.equal(typeof source, 'string');
  const count = /let sessions: \[\(&str, &str\); (\d+)\]/u.exec(source);
  assert.ok(count, 'source-owned finite session registry required');
  const paths = [...source.matchAll(/"(docs\/case-studies\/[A-Za-z0-9_./-]+\.json)"/gu)].map(match => match[1]);
  assert.equal(paths.length, Number(count[1]), 'registry inventory is incomplete');
  assert.ok(paths.length > 0 && paths.length <= 512);
  assert.equal(new Set(paths.map(path => path.toLowerCase())).size, paths.length);
  for (const path of paths) assert.ok(path.split('/').every(part => part && part !== '.' && part !== '..'), 'unsafe registry path');
  return Object.freeze([...paths].sort());
}
export function projectionInputs(cwd, paths) {
  return paths.map(path => {
    const file=join(cwd,path); assert.ok(lstatSync(file).isFile(), 'regular pinned input required');
    const bytes=readFileSync(file); assert.ok(bytes.length <= 32*1024*1024);
    const value=JSON.parse(bytes); assert.equal(typeof value.task,'string');
    assert.ok(Array.isArray(value.tools_advertised) && value.tools_advertised.length > 0);
    assert.ok(value.tools_advertised.every(tool=>typeof tool==='string'));
    assert.equal(new Set(value.tools_advertised).size,value.tools_advertised.length);
    return {path,sha256:digest(bytes),task:value.task,tools:value.tools_advertised};
  });
}
export function verifyProjectionDirectory(directory, inputs, schema) {
  const paths=[];
  function visit(relative='') {
    for(const entry of readdirSync(join(directory,relative),{withFileTypes:true})) {
      const path=relative ? relative+'/'+entry.name : entry.name;
      assert.ok(!entry.isSymbolicLink(),'generated symlink refused');
      if(entry.isDirectory()) visit(path); else {assert.ok(entry.isFile(),'nonregular output refused');paths.push(path);}
    }
  }
  visit(); assert.deepEqual(paths.sort(),inputs.map(input=>input.path).sort(),'generated membership differs');
  let total=0;
  return inputs.map(input=>{
    const bytes=readFileSync(join(directory,input.path));total+=bytes.length;
    assert.ok(bytes.length <= 32*1024*1024 && total <= 64*1024*1024,'generated byte budget exceeded');
    const value=validateSessionShape(JSON.parse(bytes),schema);
    assert.equal(value.task,input.task,'producer task differs from pinned task');
    assert.deepEqual(value.tools_advertised,input.tools,'producer advertised tools differ');
    assert.equal(value.hit_turn_cap,false,'producer reached turn cap');
    assert.ok(Array.isArray(value.steps)); assert.equal(typeof value.final_answer,'string');
    assert.ok(bytes.at(-1)===10,'canonical terminal newline required');
    return {path:input.path,bytes:bytes.length,sha256:digest(bytes)};
  });
}

