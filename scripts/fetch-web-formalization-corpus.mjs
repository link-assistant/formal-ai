#!/usr/bin/env node
// R1188-U18: fetch and cache the page formalization corpus.
//
// data/benchmarks/web-formalization/topics.lino names a few encyclopedia
// topics by their English Wikipedia title. For every topic this script follows
// the interlanguage links to the same page in each listed language, and keeps
// only the intro section of each page as plain text, with its source URL and
// revision id. Each language gets one file next to the topic list:
//
//   web-formalization-page
//     language en
//     title Moon
//     source-url "https://en.wikipedia.org/wiki/Moon"
//     revision-id 1234567890
//     paragraph "The Moon is ..."
//
// The cache is small on purpose (intro sections only). The measurement
// (scripts/measure-web-formalization.mjs) reads it offline; only this script
// touches the network, and only with --write.
//
// Usage:
//   node scripts/fetch-web-formalization-corpus.mjs --write   fetch and rewrite the cache
//   node scripts/fetch-web-formalization-corpus.mjs           list what would be fetched

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { formatLinoValueVerbatim } from '../js/agentic/crate/links_format.mjs';
import { REPO_ROOT, childrenNamed, childValue, parseLino, readRepoFile } from '../js/server/lino.mjs';

export const CORPUS_DIRECTORY = 'data/benchmarks/web-formalization';
const TOPICS_FILE = `${CORPUS_DIRECTORY}/topics.lino`;
const USER_AGENT = 'formal-ai (https://github.com/link-assistant/formal-ai; benchmark corpus)';

/** Script variants the API is asked to render a page in, by language. */
const VARIANTS = new Map([['zh', 'zh-cn']]);

/** The topic list: `{sourceLanguage, languages, topics}`. */
export function readTopics() {
  const root = parseLino(readRepoFile(TOPICS_FILE));
  const record = root.name === 'web-formalization-topics' ? root : childrenNamed(root, 'web-formalization-topics')[0];
  return {
    sourceLanguage: childValue(record, 'source-language'),
    languages: childValue(record, 'languages').split(/\s+/u).filter(Boolean),
    topics: childrenNamed(record, 'topic').map((node) => node.value),
  };
}

async function query(language, parameters) {
  const url = new URL(`https://${language}.wikipedia.org/w/api.php`);
  const all = { action: 'query', format: 'json', formatversion: '2', ...parameters };
  for (const [key, value] of Object.entries(all)) url.searchParams.set(key, value);
  const response = await fetch(url, { headers: { 'user-agent': USER_AGENT } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

/** The title of `title` (in `sourceLanguage`) in `language`, or null. */
async function linkedTitle(sourceLanguage, title, language) {
  if (language === sourceLanguage) return title;
  const answer = await query(sourceLanguage, { prop: 'langlinks', titles: title, lllang: language, redirects: '1' });
  const links = answer.query?.pages?.[0]?.langlinks ?? [];
  return links.length > 0 ? links[0].title : null;
}

/** The intro of one page: `{title, url, revision, paragraphs}`, or null. */
async function intro(language, title) {
  const parameters = {
    prop: 'extracts|revisions|info',
    exintro: '1',
    explaintext: '1',
    rvprop: 'ids',
    inprop: 'url',
    titles: title,
    redirects: '1',
  };
  if (VARIANTS.has(language)) parameters.variant = VARIANTS.get(language);
  const page = (await query(language, parameters)).query?.pages?.[0];
  if (!page || page.missing || !page.extract) return null;
  const paragraphs = page.extract.split(/\n+/u).map((paragraph) => paragraph.replace(/\s+/gu, ' ').trim())
    .filter((paragraph) => paragraph !== '');
  return { title: page.title, url: page.fullurl, revision: page.revisions?.[0]?.revid ?? 0, paragraphs };
}

/** One cached page as a Links Notation record. */
export function pageRecord(language, page) {
  const lines = [
    'web-formalization-page',
    `  language ${language}`,
    `  title ${formatLinoValueVerbatim(page.title)}`,
    `  source-url ${formatLinoValueVerbatim(page.url)}`,
    `  revision-id ${page.revision}`,
  ];
  for (const paragraph of page.paragraphs) lines.push(`  paragraph ${formatLinoValueVerbatim(paragraph)}`);
  return lines.join('\n');
}

async function main() {
  const write = process.argv.includes('--write');
  const { sourceLanguage, languages, topics } = readTopics();
  for (const language of languages) {
    const records = [`# Generated by scripts/fetch-web-formalization-corpus.mjs --write; intro sections only (R1188-U18).`];
    for (const topic of topics) {
      const title = await linkedTitle(sourceLanguage, topic, language);
      if (title === null) {
        console.log(`${language}: ${topic} has no linked page`);
        continue;
      }
      if (!write) {
        console.log(`${language}: ${topic} -> ${title}`);
        continue;
      }
      const page = await intro(language, title);
      if (page === null) {
        console.log(`${language}: ${title} has no intro`);
        continue;
      }
      records.push(pageRecord(language, page));
      console.log(`${language}: ${page.title} r${page.revision}, ${page.paragraphs.length} paragraphs`);
    }
    if (write) writeFileSync(join(REPO_ROOT, CORPUS_DIRECTORY, `${language}.lino`), `${records.join('\n')}\n`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
