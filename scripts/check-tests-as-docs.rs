#!/usr/bin/env rust-script
//! Burn-down lint: behavioural tests must read like documentation.
//!
//! Issue #960 (R234-2, <https://github.com/link-assistant/formal-ai/pull/234#issuecomment-4528554549>):
//! "I don't see in tests exact examples of answers, only contains and not
//! contains. I need more detailed examples so tests are like docs, give exact
//! variations. So the answer should be one of multiple possibilities, and it
//! should be as explicit as possible, so it will be easy to understand how the
//! system works only by looking at each concrete test. ... I want the same style
//! to be demanded for all other tests, we need a test or CI/CD rule that will
//! guarantee it."
//!
//! A test that only asserts `response.answer.contains("formal AI")` documents a
//! substring, not an answer: a reader cannot tell what the system actually
//! says. This lint finds every test that asserts on an engine answer and
//! requires at least one **exact-answer** assertion alongside the loose ones:
//!
//!   * `assert_eq!(response.answer, "…")` — the single exact answer, or
//!   * membership in an explicit list of exact answers, e.g.
//!     `assert!(EXPECTED_ANSWERS.contains(&response.answer.as_str()), …)` —
//!     "one of multiple possibilities", spelled out.
//!
//! Loose `contains` / `!contains` assertions stay; the requirement is "in
//! addition to", not "instead of".
//!
//! Today's debt is inventoried in an explicit allowlist
//! (`scripts/tests-as-docs-allowlist.txt`), like the R379 hardcoded-language
//! burn-down. The check fails when:
//!   * a behavioural test without an exact-answer assertion is **not** in the
//!     allowlist (new loose-only tests are blocked immediately), or
//!   * an allowlist row no longer matches a loose-only test (stale rows must be
//!     pruned as tests are made explicit, so the debt only shrinks).
//!
//! Usage:
//!   rust-script scripts/check-tests-as-docs.rs           # check (CI/local)
//!   rust-script scripts/check-tests-as-docs.rs --write   # regenerate allowlist
//!
//! Run the inline unit tests with:
//!   rust-script --test scripts/check-tests-as-docs.rs
//!
//! ```cargo
//! [dependencies]
//! walkdir = "2"
//! ```

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;
#[cfg(not(test))]
use std::process::exit;
use walkdir::WalkDir;

/// Relative path of the committed allowlist, from the repository root.
#[cfg_attr(test, allow(dead_code))]
const ALLOWLIST_PATH: &str = "scripts/tests-as-docs-allowlist.txt";

/// Directory scanned for behavioural tests.
#[cfg_attr(test, allow(dead_code))]
const SCAN_DIR: &str = "tests";

/// `tests/source/` is a checked-in copy of `src/` used by the source-placement
/// guard, not a test suite of its own.
#[cfg_attr(test, allow(dead_code))]
const SKIP_PATH_FRAGMENTS: &[&str] = &["tests/source/", "tests/fixtures/", "tests/e2e/node_modules"];

const ALLOWLIST_HEADER: &str = "\
# Tests-as-docs allowlist (R234-2 burn-down).
#
# Generated by scripts/check-tests-as-docs.rs. Each row is a behavioural test
# that asserts on an engine answer using only loose assertions (contains /
# !contains) without ever showing the exact answer text a reader could learn
# the system's behaviour from.
#
# Format (tab-separated): <relative-path>\\t<test-fn-name>
#   * Rows are sorted for a stable, review-friendly diff.
#
# DO NOT add rows by hand to silence the check. Instead make the test explicit:
#   assert_eq!(response.answer, \"…\");                       // one exact answer
#   assert!(EXPECTED.contains(&response.answer.as_str()), …); // one of several
# and delete its row. Regenerate after a legitimate migration with:
#   rust-script scripts/check-tests-as-docs.rs --write
";

/// A behavioural test that never shows an exact answer.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
struct Entry {
    file: String,
    test: String,
}

impl Entry {
    fn to_row(&self) -> String {
        format!("{}\t{}", self.file, self.test)
    }

    fn from_row(row: &str) -> Option<Self> {
        let (file, test) = row.split_once('\t')?;
        if file.is_empty() || test.is_empty() {
            return None;
        }
        Some(Self {
            file: file.to_string(),
            test: test.to_string(),
        })
    }
}

/// One `#[test] fn` with its body text.
#[derive(Debug, Clone, PartialEq, Eq)]
struct TestFunction {
    name: String,
    body: String,
}

#[cfg_attr(test, allow(dead_code))]
fn normalized_path(path: &Path) -> String {
    path.to_string_lossy()
        .replace(std::path::MAIN_SEPARATOR, "/")
}

/// Extract every `#[test]`-annotated function together with its body.
///
/// Brace counting is deliberately simple: it is a lint over ordinary test code,
/// not a Rust parser. Braces inside string literals are ignored so a test that
/// asserts on JSON text does not truncate the body.
fn test_functions(source: &str) -> Vec<TestFunction> {
    let bytes: Vec<char> = source.chars().collect();
    let mut functions = Vec::new();
    let mut index = 0;

    while let Some(found) = source[index..].find("#[test]") {
        let attribute_at = index + found;
        let Some(fn_at) = source[attribute_at..].find("fn ") else {
            break;
        };
        let fn_at = attribute_at + fn_at + "fn ".len();
        let name: String = source[fn_at..]
            .chars()
            .take_while(|character| character.is_alphanumeric() || *character == '_')
            .collect();
        let Some(open_at) = source[fn_at..].find('{') else {
            break;
        };
        let open_at = fn_at + open_at;
        let start = source[..open_at].chars().count();
        let mut depth = 0_usize;
        let mut position = start;
        let mut in_string = false;
        let mut escaped = false;
        let mut end = bytes.len();

        while position < bytes.len() {
            let character = bytes[position];
            if in_string {
                if escaped {
                    escaped = false;
                } else if character == '\\' {
                    escaped = true;
                } else if character == '"' {
                    in_string = false;
                }
            } else if character == '"' {
                in_string = true;
            } else if character == '{' {
                depth += 1;
            } else if character == '}' {
                depth -= 1;
                if depth == 0 {
                    end = position;
                    break;
                }
            }
            position += 1;
        }

        let body: String = bytes[start..end.min(bytes.len())].iter().collect();
        index = attribute_at + "#[test]".len();
        if !name.is_empty() {
            index = index.max(fn_at + name.len());
            functions.push(TestFunction { name, body });
        }
    }

    functions
}

/// Strip `//` line comments so a commented-out `assert_eq!` never counts as
/// evidence and prose in a doc comment never triggers the lint.
fn strip_line_comments(body: &str) -> String {
    body.lines()
        .map(|line| match line.find("//") {
            Some(at) if line[..at].matches('"').count() % 2 == 0 => &line[..at],
            _ => line,
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Does this test assert on an engine answer at all?
fn asserts_on_answer(body: &str) -> bool {
    body.contains(".answer")
}

/// Does this test show the exact answer text a reader can learn from?
///
/// Two accepted forms, both from R234-2: a single exact answer
/// (`assert_eq!(response.answer, "…")`) or an explicit list of exact
/// possibilities the answer must be one of.
fn has_exact_answer_assertion(body: &str) -> bool {
    body.split("assert_eq!").skip(1).any(|argument| {
        let head = argument.split(");").next().unwrap_or(argument);
        head.contains(".answer")
    }) || body.split(".contains(").skip(1).any(|argument| {
        let head = argument.split(')').next().unwrap_or(argument);
        // `EXPECTED.contains(&response.answer …)` — membership of the whole
        // answer in an explicit list, not `answer.contains("substring")`.
        head.contains(".answer")
    })
}

fn scan_file(relative_path: &str, source: &str) -> Vec<Entry> {
    test_functions(source)
        .into_iter()
        .filter_map(|function| {
            let body = strip_line_comments(&function.body);
            (asserts_on_answer(&body) && !has_exact_answer_assertion(&body)).then(|| Entry {
                file: relative_path.to_string(),
                test: function.name,
            })
        })
        .collect()
}

#[cfg_attr(test, allow(dead_code))]
fn scan_directory(root: &Path) -> BTreeSet<Entry> {
    let mut entries = BTreeSet::new();

    for entry in WalkDir::new(root.join(SCAN_DIR))
        .into_iter()
        .filter_map(std::result::Result::ok)
        .filter(|entry| entry.file_type().is_file())
    {
        let path = entry.path();
        if path.extension().and_then(|extension| extension.to_str()) != Some("rs") {
            continue;
        }
        let relative = normalized_path(path.strip_prefix(root).unwrap_or(path));
        if SKIP_PATH_FRAGMENTS
            .iter()
            .any(|fragment| relative.contains(fragment))
        {
            continue;
        }
        let Ok(source) = fs::read_to_string(path) else {
            continue;
        };
        entries.extend(scan_file(&relative, &source));
    }

    entries
}

fn parse_allowlist(content: &str) -> BTreeSet<Entry> {
    content
        .lines()
        .map(str::trim_end)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .filter_map(Entry::from_row)
        .collect()
}

fn render_allowlist(entries: &BTreeSet<Entry>) -> String {
    let mut rendered = String::from(ALLOWLIST_HEADER);
    for entry in entries {
        rendered.push_str(&entry.to_row());
        rendered.push('\n');
    }
    rendered
}

#[derive(Debug, Default, PartialEq, Eq)]
struct Diff {
    /// Loose-only tests missing from the allowlist: new debt.
    added: Vec<Entry>,
    /// Allowlist rows with no matching loose-only test: stale debt.
    stale: Vec<Entry>,
}

impl Diff {
    const fn is_clean(&self) -> bool {
        self.added.is_empty() && self.stale.is_empty()
    }
}

fn diff(found: &BTreeSet<Entry>, allowlisted: &BTreeSet<Entry>) -> Diff {
    Diff {
        added: found.difference(allowlisted).cloned().collect(),
        stale: allowlisted.difference(found).cloned().collect(),
    }
}

#[cfg(not(test))]
fn main() {
    let root = std::env::current_dir().expect("Failed to get current directory");
    let write = std::env::args().any(|argument| argument == "--write");
    let found = scan_directory(&root);

    if write {
        fs::write(root.join(ALLOWLIST_PATH), render_allowlist(&found))
            .expect("allowlist should be writable");
        println!("Wrote {} rows to {ALLOWLIST_PATH}", found.len());
        exit(0);
    }

    println!("\nChecking behavioural tests show exact example answers (R234-2)...\n");

    let allowlisted = fs::read_to_string(root.join(ALLOWLIST_PATH))
        .map(|content| parse_allowlist(&content))
        .unwrap_or_default();
    let difference = diff(&found, &allowlisted);

    if !difference.added.is_empty() {
        println!("Behavioural tests asserting on an answer without showing it:\n");
        for entry in &difference.added {
            println!("  {}::{}", entry.file, entry.test);
        }
        println!(
            "\nTests are documentation: show the exact answer, or the explicit list of answers it\n\
             must be one of, in addition to any contains/!contains assertions.\n\
               assert_eq!(response.answer, \"…\");\n\
               assert!(EXPECTED.contains(&response.answer.as_str()), \"…\");\n"
        );
    }

    if !difference.stale.is_empty() {
        println!("Stale allowlist rows (these tests are explicit now — prune them):\n");
        for entry in &difference.stale {
            println!("  {}::{}", entry.file, entry.test);
        }
        println!("\nRegenerate with: rust-script scripts/check-tests-as-docs.rs --write\n");
    }

    if difference.is_clean() {
        println!(
            "All {} behavioural tests outside the burn-down allowlist show exact answers\n",
            found.len()
        );
        exit(0);
    }
    exit(1);
}

#[cfg(test)]
mod tests {
    use super::*;

    const LOOSE_TEST: &str = r#"
#[test]
fn reported_russian_name_question_is_answered() {
    let response = FormalAiEngine.answer("Как твое имя?");
    assert!(response.answer.contains("formal AI"));
    assert!(!response.answer.contains("Claude"));
}
"#;

    const EXACT_TEST: &str = r#"
#[test]
fn assistant_name_answer_is_shown_verbatim() {
    let response = FormalAiEngine.answer("What is your name?");
    assert_eq!(response.answer, "I am formal AI.");
    assert!(response.answer.contains("formal AI"));
}
"#;

    const ONE_OF_TEST: &str = r#"
#[test]
fn assistant_name_answer_is_one_of_the_documented_variations() {
    const EXPECTED: &[&str] = &["I am formal AI.", "My name is formal AI."];
    let response = FormalAiEngine.answer("What is your name?");
    assert!(
        EXPECTED.contains(&response.answer.as_str()),
        "got: {}",
        response.answer,
    );
}
"#;

    /// The exact failure R234-2 names: a test whose only evidence is a
    /// substring tells a reader nothing about what the system replies.
    #[test]
    fn loose_only_test_is_flagged() {
        assert_eq!(
            scan_file("tests/unit/assistant_name.rs", LOOSE_TEST),
            vec![Entry {
                file: "tests/unit/assistant_name.rs".to_string(),
                test: "reported_russian_name_question_is_answered".to_string(),
            }]
        );
    }

    #[test]
    fn exact_answer_assertion_passes() {
        assert_eq!(scan_file("tests/unit/assistant_name.rs", EXACT_TEST), vec![]);
    }

    /// "The answer should be one of multiple possibilities" — an explicit list
    /// of exact answers is as documentary as a single one.
    #[test]
    fn membership_in_an_explicit_answer_list_passes() {
        assert_eq!(
            scan_file("tests/unit/assistant_name.rs", ONE_OF_TEST),
            vec![]
        );
    }

    /// Tests that never touch an answer (data shape, parsing, CI wiring) are
    /// out of scope; this lint is about documented behaviour.
    #[test]
    fn tests_that_do_not_assert_on_answers_are_ignored() {
        let source = r#"
#[test]
fn roles_registry_is_sorted() {
    assert!(is_sorted(&roles()));
}
"#;

        assert_eq!(scan_file("tests/unit/roles.rs", source), vec![]);
    }

    #[test]
    fn commented_out_exact_assertion_does_not_count() {
        let source = r#"
#[test]
fn name_is_answered() {
    let response = engine.answer("hi");
    // assert_eq!(response.answer, "I am formal AI.");
    assert!(response.answer.contains("formal"));
}
"#;

        assert_eq!(
            scan_file("tests/unit/x.rs", source),
            vec![Entry {
                file: "tests/unit/x.rs".to_string(),
                test: "name_is_answered".to_string(),
            }]
        );
    }

    #[test]
    fn braces_inside_string_literals_do_not_truncate_a_body() {
        let source = r#"
#[test]
fn json_answer_is_exact() {
    let response = engine.answer("hi");
    let shape = "{\"answer\": 1}";
    assert_eq!(response.answer, shape);
}
"#;

        assert_eq!(scan_file("tests/unit/x.rs", source), vec![]);
    }

    #[test]
    fn all_test_functions_in_a_file_are_scanned() {
        let source = format!("{LOOSE_TEST}{EXACT_TEST}");

        let names: Vec<String> = test_functions(&source)
            .into_iter()
            .map(|function| function.name)
            .collect();

        assert_eq!(
            names,
            vec![
                "reported_russian_name_question_is_answered".to_string(),
                "assistant_name_answer_is_shown_verbatim".to_string(),
            ]
        );
    }

    #[test]
    fn new_debt_and_stale_rows_are_reported_separately() {
        let found: BTreeSet<Entry> = [Entry {
            file: "tests/unit/a.rs".to_string(),
            test: "loose".to_string(),
        }]
        .into_iter()
        .collect();
        let allowlisted: BTreeSet<Entry> = [Entry {
            file: "tests/unit/b.rs".to_string(),
            test: "fixed".to_string(),
        }]
        .into_iter()
        .collect();

        let difference = diff(&found, &allowlisted);

        assert_eq!(
            difference.added,
            vec![Entry {
                file: "tests/unit/a.rs".to_string(),
                test: "loose".to_string(),
            }]
        );
        assert_eq!(
            difference.stale,
            vec![Entry {
                file: "tests/unit/b.rs".to_string(),
                test: "fixed".to_string(),
            }]
        );
        assert!(!difference.is_clean());
    }

    #[test]
    fn allowlist_round_trips() {
        let entries: BTreeSet<Entry> = [Entry {
            file: "tests/unit/a.rs".to_string(),
            test: "loose".to_string(),
        }]
        .into_iter()
        .collect();

        assert_eq!(parse_allowlist(&render_allowlist(&entries)), entries);
    }
}
