#!/usr/bin/env rust-script
//! Issue #1182 (E147, R8): the in-repository duplication gate.
//!
//! A scan of every function of at most 22 lines under the roots (default
//! `rust/src`), bodies compared after stripping comments and whitespace:
//! a group of two or more identical bodies appearing across files fails
//! unless it is listed in the baseline. The baseline
//! (`data/meta/duplicate-functions-baseline.lino`) may only shrink -- a
//! group that disappeared from the code must be removed from it, a new
//! group must be deduplicated (or, once, baselined by the maintainer).
//! The baseline is never hand-edited: `--write-baseline` regenerates it
//! from the current tree.
//!
//! Usage:
//!   rust-script scripts/check-duplicate-functions.rs            # gate
//!   rust-script scripts/check-duplicate-functions.rs --write-baseline
//!   rust-script scripts/check-duplicate-functions.rs --json     # inventory
//!   rust-script scripts/check-duplicate-functions.rs --roots rust/src js ts
//!
//! ```cargo
//! [package]
//! edition = "2024"
//! ```

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

const DEFAULT_ROOTS: &[&str] = &["rust/src"];
const DEFAULT_BASELINE: &str = "data/meta/duplicate-functions-baseline.lino";
const DEFAULT_MAX_LINES: usize = 22;

struct Function {
    name: String,
    path: String,
    start_line: usize,
    body_lines: usize,
}

mod duplication_support;
use duplication_support::{functions, strip_comments};

fn walk(root: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(root) else {
        return;
    };
    for entry in entries.flatten() {
        if entry.file_type().is_ok_and(|kind| kind.is_symlink()) {
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            walk(&path, out);
        } else if path.extension().is_some_and(|it| it == "rs") {
            out.push(path);
        }
    }
}

struct Group {
    digest: String,
    names: Vec<String>,
    sites: Vec<(String, String, usize)>, // (path, fn name, start line)
    body_lines: usize,
}

fn scan(roots: &[String], max_lines: usize) -> Vec<Group> {
    let mut files = Vec::new();
    for root in roots {
        walk(Path::new(root), &mut files);
    }
    files.sort();
    let mut buckets: BTreeMap<String, Vec<Function>> = BTreeMap::new();
    let mut body_lines_of: BTreeMap<String, usize> = BTreeMap::new();
    for path in &files {
        let Ok(source) = fs::read_to_string(path) else {
            continue;
        };
        let clean = strip_comments(&source);
        for (name, normalized, body_lines, start_line) in functions(&clean) {
            if body_lines > max_lines || normalized.is_empty() {
                continue;
            }
            let digest = hex(&sha256_bytes(normalized.as_bytes()))[..16].to_string();
            body_lines_of.insert(digest.clone(), body_lines);
            buckets.entry(digest).or_default().push(Function {
                name,
                path: path.display().to_string(),
                start_line,
                body_lines,
            });
        }
    }
    let mut groups: Vec<Group> = buckets
        .into_iter()
        .filter(|(_, sites)| {
            sites
                .iter()
                .map(|site| &site.path)
                .collect::<std::collections::BTreeSet<_>>()
                .len()
                >= 2
        })
        .map(|(digest, sites)| {
            let mut names = sites
                .iter()
                .map(|site| site.name.clone())
                .collect::<Vec<_>>();
            names.sort();
            names.dedup();
            let body_lines = body_lines_of[&digest];
            Group {
                digest,
                names,
                sites: sites
                    .iter()
                    .map(|site| (site.path.clone(), site.name.clone(), site.start_line))
                    .collect(),
                body_lines,
            }
        })
        .collect();
    groups.sort_by(|left, right| {
        right
            .sites
            .len()
            .cmp(&left.sites.len())
            .then_with(|| left.digest.cmp(&right.digest))
    });
    groups
}

fn render_baseline(groups: &[Group], max_lines: usize) -> String {
    let mut out = String::new();
    out.push_str(
        "# Generated by `rust-script scripts/check-duplicate-functions.rs --write-baseline`.\n",
    );
    out.push_str("# Never hand-edit: the gate fails on a group missing from here (new\n");
    out.push_str("# duplication) and on an entry no longer present in the code (the list\n");
    out.push_str("# may only shrink -- remove improved groups with --write-baseline).\n");
    out.push_str("duplicate_functions_baseline\n");
    out.push_str(&format!("  max_lines {max_lines}\n"));
    out.push_str(&format!("  groups {}\n", groups.len()));
    for group in groups {
        out.push_str("  group\n");
        out.push_str(&format!("    digest \"{}\"\n", group.digest));
        out.push_str(&format!("    body_lines {}\n", group.body_lines));
        let names = group.names.join(", ");
        out.push_str(&format!("    names \"{names}\"\n"));
        for (path, name, start_line) in &group.sites {
            out.push_str(&format!("    site \"{path}:{start_line}\" fn {name}\n"));
        }
    }
    out
}

fn parse_baseline(source: &str) -> Vec<(String, usize)> {
    source
        .lines()
        .filter_map(|line| line.trim().strip_prefix("digest "))
        .map(|rest| (rest.trim().trim_matches('"').to_owned(), 0))
        .collect()
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let write_baseline = args.iter().any(|it| it == "--write-baseline");
    let json = args.iter().any(|it| it == "--json");
    let mut roots: Vec<String> = Vec::new();
    let mut baseline = DEFAULT_BASELINE.to_string();
    let mut max_lines = DEFAULT_MAX_LINES;
    let mut index = 0;
    while index < args.len() {
        match args[index].as_str() {
            "--roots" => {
                index += 1;
                while let Some(value) = args.get(index) {
                    if value.starts_with("--") {
                        break;
                    }
                    roots.push(value.clone());
                    index += 1;
                }
                continue;
            }
            "--baseline" => {
                index += 1;
                baseline = args.get(index).expect("--baseline needs a path").clone();
            }
            "--max-lines" => {
                index += 1;
                max_lines = args
                    .get(index)
                    .expect("--max-lines needs a number")
                    .parse()
                    .expect("a number");
            }
            _ => {}
        }
        index += 1;
    }
    if roots.is_empty() {
        roots = DEFAULT_ROOTS.iter().map(ToString::to_string).collect();
    }

    let groups = scan(&roots, max_lines);

    if json {
        println!("[");
        for (position, group) in groups.iter().enumerate() {
            println!(
                "  {{\"digest\": \"{}\", \"body_lines\": {}, \"names\": [{}], \"sites\": [{}]}{}",
                group.digest,
                group.body_lines,
                group
                    .names
                    .iter()
                    .map(|n| format!("\"{n}\""))
                    .collect::<Vec<_>>()
                    .join(", "),
                group
                    .sites
                    .iter()
                    .map(|(p, n, l)| format!("\"{p}:{l} fn {n}\""))
                    .collect::<Vec<_>>()
                    .join(", "),
                if position + 1 == groups.len() {
                    ""
                } else {
                    ","
                }
            );
        }
        println!("]");
        return;
    }

    if write_baseline {
        fs::write(&baseline, render_baseline(&groups, max_lines))
            .unwrap_or_else(|error| panic!("{} writable: {error}", baseline));
        println!(
            "wrote {} groups to {baseline} ({} sites total)",
            groups.len(),
            groups.iter().map(|g| g.sites.len()).sum::<usize>()
        );
        return;
    }

    println!(
        "scanned {} roots with the {}-line ceiling: {} cross-file duplicate groups",
        roots.len(),
        max_lines,
        groups.len()
    );
    for group in groups.iter().take(10) {
        println!(
            "  {} sites ~{}L {} -- {}",
            group.sites.len(),
            group.body_lines,
            group.names.join(","),
            group.digest
        );
    }
    if groups.len() > 10 {
        println!("  … and {} more", groups.len() - 10);
    }

    let committed = fs::read_to_string(&baseline).unwrap_or_else(|error| {
        eprintln!("missing or unreadable baseline {baseline}: {error}; initialize explicitly with --write-baseline");
        std::process::exit(2);
    });
    let baselined: Vec<String> = parse_baseline(&committed)
        .into_iter()
        .map(|(digest, _)| digest)
        .collect();
    let current: Vec<&String> = groups.iter().map(|g| &g.digest).collect();
    let fresh: Vec<&String> = current
        .iter()
        .copied()
        .filter(|digest| !baselined.contains(digest))
        .collect();
    let stale: Vec<&String> = baselined
        .iter()
        .filter(|digest| !current.contains(digest))
        .collect();
    if !fresh.is_empty() {
        eprintln!(
            "check-duplicate-functions: {} NEW cross-file duplicate group(s) {:?} -- deduplicate them (docs/duplicate-groups.md carries the plans) or, once, re-baseline with --write-baseline",
            fresh.len(),
            fresh
        );
    }
    if !stale.is_empty() {
        eprintln!(
            "check-duplicate-functions: {} baseline entr(ies) no longer in the code {:?} -- the list may only shrink: re-run --write-baseline",
            stale.len(),
            stale
        );
    }
    if !fresh.is_empty() || !stale.is_empty() {
        std::process::exit(1);
    }
    println!("baseline in sync: {} groups", baselined.len());
}

mod sha256 {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4,
        0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe,
        0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f,
        0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7,
        0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc,
        0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
        0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116,
        0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
        0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7,
        0xc67178f2,
    ];

    pub struct Sha256 {
        state: [u32; 8],
        buffer: [u8; 64],
        buffered: usize,
        length: u64,
    }

    impl Sha256 {
        pub fn new() -> Self {
            Self {
                state: [
                    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c,
                    0x1f83d9ab, 0x5be0cd19,
                ],
                buffer: [0; 64],
                buffered: 0,
                length: 0,
            }
        }

        pub fn update(&mut self, data: &[u8]) {
            self.length = self.length.wrapping_add(data.len() as u64);
            let mut offset = 0;
            while offset < data.len() {
                let take = (data.len() - offset).min(64 - self.buffered);
                self.buffer[self.buffered..self.buffered + take]
                    .copy_from_slice(&data[offset..offset + take]);
                self.buffered += take;
                offset += take;
                if self.buffered == 64 {
                    let block = self.buffer;
                    self.compress(&block);
                    self.buffered = 0;
                }
            }
        }

        pub fn finish(mut self) -> [u8; 32] {
            let bit_length = self.length.wrapping_mul(8);
            self.buffer[self.buffered] = 0x80;
            for byte in &mut self.buffer[self.buffered + 1..] {
                *byte = 0;
            }
            self.buffered += 1;
            if self.buffered > 56 {
                let block = self.buffer;
                self.compress(&block);
                self.buffer = [0; 64];
                self.buffered = 0;
            }
            self.buffer[56..64].copy_from_slice(&bit_length.to_be_bytes());
            let block = self.buffer;
            self.compress(&block);
            let mut out = [0u8; 32];
            for (index, word) in self.state.iter().enumerate() {
                out[index * 4..index * 4 + 4].copy_from_slice(&word.to_be_bytes());
            }
            out
        }

        fn compress(&mut self, block: &[u8; 64]) {
            let mut w = [0u32; 64];
            for index in 0..16 {
                w[index] = u32::from_be_bytes([
                    block[index * 4],
                    block[index * 4 + 1],
                    block[index * 4 + 2],
                    block[index * 4 + 3],
                ]);
            }
            for index in 16..64 {
                let s0 = w[index - 15].rotate_right(7)
                    ^ w[index - 15].rotate_right(18)
                    ^ (w[index - 15] >> 3);
                let s1 = w[index - 2].rotate_right(17)
                    ^ w[index - 2].rotate_right(19)
                    ^ (w[index - 2] >> 10);
                w[index] = w[index - 16]
                    .wrapping_add(s0)
                    .wrapping_add(w[index - 7])
                    .wrapping_add(s1);
            }
            let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut h] = self.state;
            for index in 0..64 {
                let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
                let ch = (e & f) ^ ((!e) & g);
                let temp1 = h
                    .wrapping_add(s1)
                    .wrapping_add(ch)
                    .wrapping_add(K[index])
                    .wrapping_add(w[index]);
                let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
                let maj = (a & b) ^ (a & c) ^ (b & c);
                let temp2 = s0.wrapping_add(maj);
                h = g;
                g = f;
                f = e;
                e = d.wrapping_add(temp1);
                d = c;
                c = b;
                b = a;
                a = temp1.wrapping_add(temp2);
            }
            self.state[0] = self.state[0].wrapping_add(a);
            self.state[1] = self.state[1].wrapping_add(b);
            self.state[2] = self.state[2].wrapping_add(c);
            self.state[3] = self.state[3].wrapping_add(d);
            self.state[4] = self.state[4].wrapping_add(e);
            self.state[5] = self.state[5].wrapping_add(f);
            self.state[6] = self.state[6].wrapping_add(g);
            self.state[7] = self.state[7].wrapping_add(h);
        }
    }
}

fn sha256_bytes(data: &[u8]) -> [u8; 32] {
    let mut hasher = sha256::Sha256::new();
    hasher.update(data);
    hasher.finish()
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const FIXTURE_ONE: &str = r#"
fn helper() -> u32 {
    // a comment, stripped
    let value = 1 + 2;
    value
}
"#;
    const FIXTURE_TWO: &str = r#"
fn other_name() -> u32 {
    let   value   =   1+2; /* also stripped */
    value
}
"#;
    const FIXTURE_DIFFERENT: &str = r#"
fn helper() -> u32 {
    let value = 1 + 3;
    value
}
"#;

    fn body_of(clean: &str) -> (String, usize, usize) {
        let all = functions(clean);
        assert!(!all.is_empty(), "the fixture has a function");
        let (name, normalized, lines, start) = &all[0];
        (format!("{name}:{normalized}"), *lines, *start)
    }

    #[test]
    fn whitespace_and_comments_do_not_hide_identity() {
        let one = body_of(&strip_comments(FIXTURE_ONE));
        let two = body_of(&strip_comments(FIXTURE_TWO));
        assert_eq!(one.0.split(':').nth(1), two.0.split(':').nth(1));
    }

    #[test]
    fn a_changed_body_is_a_different_group() {
        let one = body_of(&strip_comments(FIXTURE_ONE));
        let different = body_of(&strip_comments(FIXTURE_DIFFERENT));
        assert_ne!(one.0.split(':').nth(1), different.0.split(':').nth(1));
    }

    #[test]
    fn a_string_containing_braces_does_not_confuse_the_matcher() {
        let source = "fn render() -> &'static str {\n    \"a {b} c\"\n}\n";
        let all = functions(&strip_comments(source));
        assert_eq!(all.len(), 1);
        assert_eq!(all[0].1, "\"a {b} c\"");
    }

    #[test]
    fn the_baseline_round_trips_through_parse() {
        let groups = vec![Group {
            digest: "abc123".to_string(),
            names: vec!["helper".to_string()],
            sites: vec![("rust/src/a.rs".to_string(), "helper".to_string(), 7)],
            body_lines: 3,
        }];
        let rendered = render_baseline(&groups, 22);
        let parsed = parse_baseline(&rendered);
        assert_eq!(parsed.len(), 1);
        assert_eq!(parsed[0].0, "abc123");
    }

    #[test]
    fn sha256_matches_the_known_vector() {
        assert!(hex(&sha256_bytes(b"abc")).starts_with("ba7816bf8f01cfea414140de5dae2223"));
    }
}
