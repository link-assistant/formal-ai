export function renderWorkerPrerequisites(records) {
  const literal = JSON.stringify(records, null, 2);
  const expression = 'Object.freeze(' + literal + '.map(record => Object.freeze({...record,requires:Object.freeze(record.requires.map(item => Object.freeze(item)))})))';
  return {
    node: '// Generated by `node scripts/generate-worker-prerequisites.mjs --write`; do not edit.\nexport const workerScriptPrerequisites = ' + expression + ';\n',
    browser: '// Generated by `node scripts/generate-worker-prerequisites.mjs --write`; do not edit.\nconst formalAiWorkerScriptPrerequisites = ' + expression + ';\n' + browserWorkerRuntime
  };
}
export function generateWorkerPrerequisites({
  root,
  outputRoot = root,
  sourceManifestPath = null,
  write = false
}) {
  const parser = createRequire(path.join(root, 'package.json'))('@babel/parser');
  const profile = sourceManifestPath ? JSON.parse(fs.readFileSync(sourceManifestPath)) : null;
  const names = ['js/parser-cache-primordials.js', 'js/seed_loader.js', ...fs.readdirSync(path.join(root, 'js/worker')).filter(name => name.endsWith('.js')).map(name => 'js/worker/' + name)];
  const sources = names.map(owner => {
    const row = profile?.files.find(row => row.owner === owner);
    const filename = row?.afterPath ?? path.join(root, owner),
      text = fs.readFileSync(filename, 'utf8');
    if (row && digest(text) !== row.afterSha256) throw Error('ProjectedWorkerSourceDrift:' + owner);
    return {
      owner,
      text
    };
  });
  const records = dependencyRecords(sources, parser.parse),
    rendered = renderWorkerPrerequisites(records);
  const outputs = [['js/server/worker-script-prerequisites.mjs', rendered.node], ['js/worker-script-prerequisites.js', rendered.browser]];
  for (const [owner, text] of outputs) {
    const filename = path.join(outputRoot, owner);
    if (write) {
      fs.mkdirSync(path.dirname(filename), {
        recursive: true
      });
      fs.writeFileSync(filename, text);
    } else if (fs.readFileSync(filename, 'utf8') !== text) throw Error('StaleWorkerPrerequisites:' + owner);
  }
  return {
    records,
    inputs: sources.map(source => ({
      owner: source.owner,
      sha256: digest(source.text),
      bytes: Buffer.byteLength(source.text)
    })),
    outputs: outputs.map(([owner, text]) => ({
      owner,
      sha256: digest(text),
      bytes: Buffer.byteLength(text)
    }))
  };
}
