const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
export function dependencyRecords(sources, parse) {
  const scripts = new Map(sources.map(source => [source.owner, source]));
  if (scripts.size !== sources.length) throw Error('DuplicateWorkerSource');
  const records = [];
  for (const source of sources) {
    const ast = parse(source.text, {
      sourceType: 'script',
      allowReturnOutsideFunction: true
    });
    const requires = [];
    for (const comment of ast.comments ?? []) {
      const value = comment.value.trim();
      if (!value.startsWith('@worker-prerequisite')) continue;
      const match = comment.type === 'CommentLine' && /^@worker-prerequisite ([A-Za-z0-9_./-]+\.js)$/.exec(value);
      if (!match || path.posix.normalize(match[1]) !== match[1] || match[1].startsWith('../') || match[1].startsWith('/')) throw Error('MalformedWorkerPrerequisite:' + source.owner);
      const target = match[1];
      if (!scripts.has(target)) throw Error('UnknownWorkerPrerequisite:' + target);
      if (requires.includes(target)) throw Error('DuplicateWorkerPrerequisite:' + target);
      requires.push(target);
    }
    if (requires.length) records.push({
      script: source.owner,
      sourceSha256: digest(source.text),
      requires: requires.map(script => ({
        script,
        sourceSha256: digest(scripts.get(script).text)
      }))
    });
  }
  const edges = new Map(records.map(record => [record.script, record.requires.map(x => x.script)])),
    active = new Set(),
    done = new Set();
  function visit(script) {
    if (active.has(script)) throw Error('CyclicWorkerPrerequisite:' + script);
    if (done.has(script)) return;
    active.add(script);
    for (const target of edges.get(script) ?? []) visit(target);
    active.delete(script);
    done.add(script);
  }
  for (const script of edges.keys()) visit(script);
  return records.sort((a, b) => a.script.localeCompare(b.script));
}
