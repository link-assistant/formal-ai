#!/usr/bin/env node
// JavaScript twin of `scripts/assemble-requirements.rs` (PR #1188, SCRIPTS-A).
//
// Same flags, exit codes, stdout lines and written bytes as the Rust original,
// so the requirement pipeline runs without compiling Rust locally. CI runs both
// and fails when they disagree (`data/meta/ci-gates/check-assemble-requirements-js-twin.lino`).
// Read the Rust source for the reasoning behind each rule; the comments here
// only name what each function mirrors.
//
// Usage:
//   node scripts/assemble-requirements.mjs           # check the index and parts are current
//   node scripts/assemble-requirements.mjs --write   # rebuild the index and parts
//   node scripts/assemble-requirements.mjs --split   # re-shard the assembled parts
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

import {
  compareStrings, exists, fileName, ioErrorDisplay, isAsciiAlphanumeric, isWhitespace, joinPath,
  leadingDigits, lines, parent, parseUnsigned, readDirPaths, readOrEmpty, readToString, splitWhitespace, trim,
} from './lib/requirements-rust-compat.mjs';

const DOCUMENT = 'REQUIREMENTS.md';
export const SHARDS = 'docs/requirements';
export const PARTS = 'docs/requirements/assembled';
export const PART_LINE_LIMIT = 1400;
export const PART_HEADER_LINES = 4;
const BANNER = '<!-- Generated by `rust-script scripts/assemble-requirements.rs --write` from `docs/requirements/`. Edit the shard for your issue, never this file: see `data/meta/merge-conflict-policy.lino`. -->';

const PREAMBLE = 0;
const ISSUE = 1;
const DOCTRINE = 2;

/** Mirrors `fn shard_order`: `[group, issue, stem]`, or `null`. */
export function shardOrder(name) {
  if (!name.endsWith('.md')) return null;
  const stem = name.slice(0, -3);
  if (stem.startsWith('issue-')) {
    const issue = parseUnsigned(leadingDigits(stem.slice('issue-'.length)));
    return issue === null ? null : [ISSUE, issue, stem];
  }
  if (stem.startsWith('preamble-')) return [PREAMBLE, 0n, stem];
  if (stem.startsWith('doctrine-')) return [DOCTRINE, 0n, stem];
  return null;
}

function compareOrder(left, right) {
  if (left[0] !== right[0]) return left[0] < right[0] ? -1 : 1;
  if (left[1] !== right[1]) return left[1] < right[1] ? -1 : 1;
  return compareStrings(left[2], right[2]);
}

/** Mirrors `fn heading_issue`. */
export function headingIssue(heading) {
  const at = heading.indexOf('Issue #');
  if (at < 0) return null;
  const issue = parseUnsigned(leadingDigits(heading.slice(at + 'Issue #'.length)));
  return issue === null ? null : Number(issue);
}

/** Mirrors `fn slug`. */
export function slug(heading) {
  let out = '';
  for (const character of heading) {
    if (isAsciiAlphanumeric(character)) out += character.toLowerCase();
    else if (!out.endsWith('-')) out += '-';
  }
  return out.replace(/^-+|-+$/g, '');
}

/** Mirrors `fn sections`. */
export function sections(document) {
  let preamble = '';
  const found = [];
  for (const line of lines(document)) {
    if (line.startsWith('## ')) found.push('');
    if (found.length) found[found.length - 1] += `${line}\n`;
    else preamble += `${line}\n`;
  }
  return [preamble, found];
}

const pad4 = (number) => String(number).padStart(4, '0');

/** Mirrors `fn shard_name`. */
export function shardName(heading) {
  const title = trim(heading.replace(/^#+/, ''));
  const issue = headingIssue(heading);
  if (issue === null) return `doctrine-${slug(title)}.md`;
  const prefix = `Issue #${issue}`;
  const subject = title.startsWith(prefix) ? title.slice(prefix.length) : title;
  return `issue-${pad4(issue)}-${slug(subject)}.md`;
}

/** Mirrors `fn is_document_relative`. */
export function isDocumentRelative(target) {
  return !(target === '' || target.startsWith('#') || target.startsWith('/')
    || target.includes('://') || target.startsWith('mailto:'));
}

/** Mirrors `fn normalize`. */
export function normalize(path) {
  const parts = [];
  for (const part of path.split('/')) {
    if (part === '' || part === '.') continue;
    if (part === '..' && parts.length && parts.at(-1) !== '..') parts.pop();
    else parts.push(part);
  }
  return parts.join('/');
}

/** Mirrors `fn to_root_relative`. */
export const toRootRelative = (target) => (isDocumentRelative(target) ? normalize(`${SHARDS}/${target}`) : target);

/** Mirrors `fn relative_to`. */
export function relativeTo(base, target) {
  if (!isDocumentRelative(target)) return target;
  const baseParts = base.split('/');
  const parts = normalize(target).split('/');
  let shared = 0;
  while (shared < baseParts.length && shared < parts.length && baseParts[shared] === parts[shared]) shared += 1;
  const rebased = [...Array(baseParts.length - shared).fill('..'), ...parts.slice(shared)];
  return rebased.length ? rebased.join('/') : '.';
}

/** Mirrors `fn to_shard_relative`. */
export const toShardRelative = (target) => relativeTo(SHARDS, target);

/** Mirrors `fn shard_to_part_relative`. */
export const shardToPartRelative = (target) => (isDocumentRelative(target) ? relativeTo(PARTS, toRootRelative(target)) : target);

/** Mirrors `fn part_to_shard_relative`. */
export const partToShardRelative = (target) => (isDocumentRelative(target) ? toShardRelative(normalize(`${PARTS}/${target}`)) : target);

function splitOnceWhitespace(text) {
  for (let index = 0; index < text.length;) {
    const character = String.fromCodePoint(text.codePointAt(index));
    if (isWhitespace(character)) return [text.slice(0, index), text.slice(index + character.length)];
    index += character.length;
  }
  return null;
}

/** Mirrors `fn rewrite_links`. */
export function rewriteLinks(body, rebase) {
  let rewritten = '';
  let rest = body;
  for (let open = rest.indexOf(']('); open >= 0; open = rest.indexOf('](')) {
    const after = rest.slice(open + 2);
    const close = after.indexOf(')');
    if (close < 0) break;
    const split = splitOnceWhitespace(after.slice(0, close));
    const [target, title] = split ? [split[0], ` ${split[1]}`] : [after.slice(0, close), ''];
    rewritten += `${rest.slice(0, open + 2)}${rebase(target)}${title})`;
    rest = after.slice(close + 1);
  }
  return rewritten + rest;
}

/** Mirrors `fn ordered_shards`; throws the Rust error text. */
export function orderedShards(directory) {
  let paths;
  try {
    paths = readDirPaths(directory);
  } catch (error) {
    throw new Error(`cannot read ${SHARDS}: ${ioErrorDisplay(error)}`);
  }
  const shards = [];
  for (const path of paths) {
    const name = fileName(path);
    if (!name.endsWith('.md') || name === 'README.md') continue;
    const order = shardOrder(name);
    if (!order) throw new Error(`${SHARDS}/${name} must start with \`preamble-\`, \`issue-NNNN-\` or \`doctrine-\``);
    shards.push([order, path]);
  }
  shards.sort((left, right) => compareOrder(left[0], right[0]) || compareStrings(left[1], right[1]));
  return shards.map(([, path]) => path);
}

/** Mirrors `fn part_name`. */
export const partName = (number) => `part-${String(number).padStart(2, '0')}.md`;

/** Mirrors `fn part_header`. */
export const partHeader = (number, total) => `${BANNER}\n\nPart ${number} of ${total} of the assembled requirement register; [\`REQUIREMENTS.md\`](../../../REQUIREMENTS.md) lists every part.\n\n`;

/** Mirrors `fn pack`; throws the Rust error text. */
export function pack(sizes) {
  const parts = [];
  let count = 0;
  sizes.forEach(([name, size], index) => {
    if (PART_HEADER_LINES + size > PART_LINE_LIMIT) {
      throw new Error(`${SHARDS}/${name} has ${size} lines, but an assembled part holds at most ${PART_LINE_LIMIT - PART_HEADER_LINES} lines of shards; split the shard`);
    }
    if (parts.length && count + 1 + size <= PART_LINE_LIMIT) {
      parts.at(-1).push(index);
      count += 1 + size;
    } else {
      parts.push([index]);
      count = PART_HEADER_LINES + size;
    }
  });
  return parts;
}

/** Mirrors `fn section_title`. */
export function sectionTitle(body) {
  const heading = lines(body).find((line) => line.startsWith('#')) ?? '';
  return trim(heading.replace(/^#+/, ''));
}

/** Mirrors `fn index_document`. */
export function indexDocument(parts, titles) {
  let index = `${BANNER}\n\n# Requirements\n\n`
    + 'The requirement register is assembled from one shard per issue under\n'
    + '[`docs/requirements/`](docs/requirements/README.md). No maintained file may exceed\n'
    + '1500 lines, so the assembled register is split into ordered parts. Read them in\n'
    + 'order: together they are the whole register.\n';
  parts.forEach((part, at) => {
    const number = at + 1;
    index += `\n${number}. [Part ${number}](${PARTS}/${partName(number)})\n`;
    for (const section of part) index += `   - ${titles[section]}\n`;
  });
  return index;
}

/** Mirrors `fn assemble`: `{ index, parts: [[name, text]] }`. */
export function assemble(shards) {
  const bodies = [];
  const sizes = [];
  for (const shard of shards) {
    let body;
    try {
      body = readToString(shard);
    } catch (error) {
      throw new Error(`cannot read ${shard}: ${ioErrorDisplay(error)}`);
    }
    body = body.replace(/\n+$/, '');
    sizes.push([fileName(shard), lines(body).length]);
    bodies.push(body);
  }
  const packed = pack(sizes);
  const titles = bodies.map((body) => sectionTitle(rewriteLinks(body, toRootRelative)));
  const parts = packed.map((part, at) => {
    const text = `${partHeader(at + 1, packed.length)}${part.map((section) => rewriteLinks(bodies[section], shardToPartRelative)).join('\n\n')}\n`;
    return [partName(at + 1), text];
  });
  return { index: indexDocument(packed, titles), parts };
}

/** Mirrors `fn existing_parts`. */
export function existingParts(directory) {
  let paths;
  try {
    paths = readDirPaths(directory);
  } catch {
    return [];
  }
  return paths.filter((path) => {
    const name = fileName(path);
    return name.startsWith('part-') && name.endsWith('.md');
  }).sort(compareStrings);
}

/** Mirrors `fn drift`. */
export function drift(root, assembly) {
  const drifted = [];
  if (readOrEmpty(joinPath(root, DOCUMENT)) !== assembly.index) drifted.push(DOCUMENT);
  for (const [name, text] of assembly.parts) {
    if (readOrEmpty(joinPath(joinPath(root, PARTS), name)) !== text) drifted.push(`${PARTS}/${name}`);
  }
  for (const path of existingParts(joinPath(root, PARTS))) {
    const name = fileName(path);
    if (!assembly.parts.some(([part]) => part === name)) drifted.push(`${PARTS}/${name} (stale)`);
  }
  return drifted;
}

/** Mirrors `fn shard_violations`. */
export function shardViolations(shards, read) {
  const failures = [];
  for (const shard of shards) {
    const name = fileName(shard);
    const heading = lines(read(shard))[0] ?? '';
    const issue = headingIssue(heading);
    if (issue === null || !heading.startsWith('## ')) continue;
    if (!name.startsWith(`issue-${pad4(issue)}-`)) {
      failures.push(`${SHARDS}/${name} starts with the heading \`${heading}\`, so it must be named \`issue-${pad4(issue)}-<slug>.md\``);
    }
  }
  return failures;
}

/** Mirrors `fn document_relative_targets`. */
export function documentRelativeTargets(body) {
  const targets = [];
  let rest = body;
  for (let open = rest.indexOf(']('); open >= 0; open = rest.indexOf('](')) {
    const after = rest.slice(open + 2);
    const close = after.indexOf(')');
    if (close < 0) break;
    const first = splitWhitespace(after.slice(0, close))[0] ?? '';
    const target = first.split('#')[0];
    if (isDocumentRelative(target)) targets.push(target);
    rest = after.slice(close + 1);
  }
  return targets;
}

/** Mirrors `fn link_violations`. */
export function linkViolations(shards, read, pathExists) {
  const failures = [];
  for (const shard of shards) {
    const directory = parent(shard) || '.';
    const name = fileName(shard);
    for (const target of documentRelativeTargets(read(shard))) {
      if (!pathExists(joinPath(directory, target))) {
        failures.push(`${SHARDS}/${name} links to \`${target}\`, which does not exist relative to ${SHARDS}/. Write shard links relative to the shard; assembly rebases them to \`${toRootRelative(target)}\`.`);
      }
    }
  }
  return failures;
}

/** Mirrors `fn assembled_register`. */
function assembledRegister(root) {
  const parts = existingParts(joinPath(root, PARTS));
  if (!parts.length) throw new Error(`${PARTS}/ holds no part-NN.md files`);
  const found = parts.map((part) => {
    let text;
    try {
      text = readToString(part);
    } catch (error) {
      throw new Error(`cannot read ${part}: ${ioErrorDisplay(error)}`);
    }
    return lines(text).slice(PART_HEADER_LINES).join('\n');
  });
  return rewriteLinks(`${found.join('\n\n')}\n`, partToShardRelative);
}

/** Mirrors `fn write_shard`. */
function writeShard(path, body) {
  if (existsSync(path)) throw new Error(`${path} already exists; two sections produced the same shard name`);
  try {
    writeFileSync(path, `${body.replace(/\n+$/, '')}\n`);
  } catch (error) {
    throw new Error(`cannot write ${path}: ${ioErrorDisplay(error)}`);
  }
}

/** Mirrors `fn split`. */
function split(root) {
  const [preamble, found] = sections(assembledRegister(root));
  const directory = joinPath(root, SHARDS);
  try {
    mkdirSync(directory, { recursive: true });
  } catch (error) {
    throw new Error(ioErrorDisplay(error));
  }
  const title = lines(preamble)[0] ?? '# Requirements';
  writeShard(joinPath(directory, `preamble-${slug(title)}.md`), preamble);
  for (const section of found) writeShard(joinPath(directory, shardName(lines(section)[0] ?? '')), section);
  return found.length + 1;
}

/** Mirrors `fn main`: returns the exit code, printing what Rust prints. */
export function main(argv = process.argv.slice(2), root = process.cwd(), out = console.log) {
  const mode = argv[0] ?? '';
  if (mode === '--split') {
    try {
      out(`\nWrote ${split(root)} shard(s) to ${SHARDS}/.\n`);
      return 0;
    } catch (error) {
      out(`::error::${error.message}`);
      return 1;
    }
  }
  let shards;
  try {
    shards = orderedShards(joinPath(root, SHARDS));
  } catch (error) {
    out(`::error::${error.message}`);
    return 1;
  }
  const failures = [...shardViolations(shards, readOrEmpty), ...linkViolations(shards, readOrEmpty, exists)];
  if (failures.length) {
    for (const failure of failures) out(`::error::${failure}`);
    return 1;
  }
  let assembly;
  try {
    assembly = assemble(shards);
  } catch (error) {
    out(`::error::${error.message}`);
    return 1;
  }
  const drifted = drift(root, assembly);
  if (mode === '--write') {
    if (!drifted.length) {
      out(`\n${DOCUMENT} and ${assembly.parts.length} part(s) are already current (${shards.length} shards).\n`);
      return 0;
    }
    writeFileSync(joinPath(root, DOCUMENT), assembly.index);
    const parts = joinPath(root, PARTS);
    mkdirSync(parts, { recursive: true });
    for (const stale of existingParts(parts)) rmSync(stale);
    for (const [name, text] of assembly.parts) writeFileSync(joinPath(parts, name), text);
    out(`\nRebuilt ${DOCUMENT} and ${assembly.parts.length} part(s) in ${PARTS}/ from ${shards.length} shards.\n`);
    return 0;
  }
  out(`\nChecking ${DOCUMENT} and ${PARTS}/ against ${SHARDS}/ (${shards.length} shards)...\n`);
  if (!drifted.length) {
    out(`${DOCUMENT} and its ${assembly.parts.length} part(s) match the shards.\n`);
    return 0;
  }
  for (const path of drifted) out(`::error::${path} does not match ${SHARDS}/.`);
  out('\nRun: rust-script scripts/assemble-requirements.rs --write\n');
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main();
}
