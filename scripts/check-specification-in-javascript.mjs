#!/usr/bin/env node
// The Rust specification suite, asked of the browser worker (R1188-U29,
// R1188-U30).
//
// scripts/lib/rust-specification-cases.mjs reads every specification test of
// the simple shape (ask a prompt, assert on the answer, the intent or the
// evidence links) into a JavaScript case, and this script asks the browser
// worker each one. data/meta/specification-javascript-gaps.lino records how
// many cases are carried and pass, and lists every carried case the worker
// fails: the JavaScript root's parity debt against the native engine.
//
// `--check` (gate check-specification-in-javascript) fails when the measured
// state differs from the record. `--write` records it, but refuses when fewer
// cases pass than recorded: a case that passed in the worker never regresses.
//
// Usage: node scripts/check-specification-in-javascript.mjs [--check | --write] [--list]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { WorkerHost } from '../js/server/worker-host.mjs';
import { failingCases, specificationCases } from './lib/rust-specification-cases.mjs';

const RECORD = 'data/meta/specification-javascript-gaps.lino';

/**
 * The record file's counts and listed gaps.
 * @param {string} text
 * @returns {{carried: number, passing: number, gaps: Array<string>}}
 */
export function parseRecord(text) {
  const number = (key) => Number(new RegExp(`^\\s+${key} (\\d+)$`, 'mu').exec(text)?.[1] ?? 0);
  const gaps = [...text.matchAll(/^\s+gap "([^"]+)"$/gmu)].map((match) => match[1]);
  return { carried: number('carried'), passing: number('passing'), gaps };
}

/**
 * The record file for a measured state.
 * @param {{total: number, carried: number, passing: number, failing: Map<string, string>}} state
 * @returns {string}
 */
export function renderRecord({ total, carried, passing, failing }) {
  return [
    '# Generated by `node scripts/check-specification-in-javascript.mjs --write`.',
    '# The Rust specification tests of the simple shape, asked of the browser worker',
    '# (R1188-U29, R1188-U30): how many are carried to JavaScript and pass, and every',
    '# carried case the worker fails, with what it answered. `passing` never falls.',
    'specification-javascript-gaps',
    `  specification-tests ${total}`,
    `  carried ${carried}`,
    `  passing ${passing}`,
    ...[...failing].sort(([left], [right]) => left.localeCompare(right)).flatMap(([id, failure]) => [
      `  gap "${id}"`,
      `    failure ${JSON.stringify(failure.replaceAll('"', "'").slice(0, 200))}`,
    ]),
    '',
  ].join('\n');
}

async function main(argv) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const { total, cases } = specificationCases(root);
  const failing = await failingCases(new WorkerHost(), cases);
  const state = { total, carried: cases.length, passing: cases.length - failing.size, failing };
  const recorded = parseRecord(readFileSync(join(root, RECORD), 'utf8'));
  console.log(`specification in JavaScript: ${total} tests, ${state.carried} carried, ${state.passing} pass in the worker`);
  if (argv.includes('--list')) {
    for (const [id, failure] of failing) {
      console.log(`  ${id}: ${failure}`);
    }
  }
  if (state.passing < recorded.passing) {
    const regressed = recorded.gaps.length ? [...failing.keys()].filter((id) => !recorded.gaps.includes(id)) : [];
    console.error(
      `::error file=${RECORD}::${recorded.passing - state.passing} specification case(s) that passed in the worker ` +
        `fail now: ${regressed.join(', ')}. Fix the worker; a passing case never regresses.`,
    );
    return 1;
  }
  if (argv.includes('--write')) {
    writeFileSync(join(root, RECORD), renderRecord(state));
    console.log(`wrote ${RECORD}`);
    return 0;
  }
  const listed = new Set(recorded.gaps);
  const unlisted = [...failing.keys()].filter((id) => !listed.has(id));
  const fixed = recorded.gaps.filter((id) => !failing.has(id));
  const problems = [];
  if (unlisted.length) {
    problems.push(`carried cases fail in the worker and are not listed: ${unlisted.join(', ')}`);
  }
  if (fixed.length || state.carried !== recorded.carried || state.passing !== recorded.passing) {
    problems.push(`the record is stale (${fixed.length} listed gap(s) now pass); run --write`);
  }
  for (const problem of problems) {
    console.error(`::error file=${RECORD}::${problem}`);
  }
  return problems.length ? 1 : 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
