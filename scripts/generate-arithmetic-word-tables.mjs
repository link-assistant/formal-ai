#!/usr/bin/env node
// Materialize the no_std tables from the actual canonical worker lexicon.
// The original native seed comparison remains the independent CI verifier.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { WorkerHost, REPO_ROOT } from '../js/server/worker-host.mjs';

const INTRO = "// @generated by `node scripts/generate-arithmetic-word-tables.mjs --write`.\n// Native equivalent: `cargo run -p formal-ai --example issue_386_gen_arith_table`.\n// DO NOT EDIT BY HAND. Edit the cardinal/operator meanings in\n// data/seed/meanings-units.lino and data/seed/meanings-calculator.lino,\n// then regenerate. Parity with the live seed is enforced by the\n// `arithmetic_word_tables_match_seed` test in src/calculation.rs.\n//\n// These tables drive `normalize_expression` in src/arithmetic.rs, which is\n// compiled into the wasm worker and so must stay no_std + alloc only.\n\n";
const TOKENS_DOC = "// Single-word surfaces, mapped to the value surface of their meaning (a\n// spelled digit or operator word to its numeral/symbol). Applied after the\n// expression is split on whitespace. Sorted by surface for a stable diff.\n";
const PHRASES_DOC = "// Multi-word operator phrases, mapped to their operator symbol and applied\n// before tokenization. Longest first so a phrase is rewritten before any\n// shorter phrase it contains (\"разделить на\" before \"делить на\").\n";
const FILES = ['rust/src/arithmetic_word_tables.rs', 'rust/tests/source/arithmetic_word_tables.rs'];

export function rustStringLiteral(text) {
  const escapes = new Map([['"', '\\"'], ['\\', '\\\\'], ['\n', '\\n'], ['\r', '\\r'], ['\t', '\\t']]);
  return '"' + [...text].map(character => escapes.get(character)
    ?? (/\p{Cc}/u.test(character) ? '\\u{' + character.codePointAt(0).toString(16) + '}' : character)).join('') + '"';
}

export function renderArithmeticWordTables({ tokens, phrases }) {
  const emit = (doc, name, rows) => doc + `pub(crate) static ${name}: &[(&str, &str)] = &[\n`
    + rows.map(([surface, value]) => `    (${rustStringLiteral(surface)}, ${rustStringLiteral(value)}),\n`).join('') + '];\n';
  return INTRO + emit(TOKENS_DOC, 'WORD_VALUE_TOKENS', tokens) + '\n'
    + emit(PHRASES_DOC, 'WORD_VALUE_PHRASES', phrases);
}

async function main() {
  const mode = process.argv[2];
  if (!['--check', '--write'].includes(mode)) throw new Error('usage: generate-arithmetic-word-tables.mjs --check|--write');
  const host = new WorkerHost();
  const tables = await host.run('arithmeticNormalizationTables()');
  const rendered = renderArithmeticWordTables(tables);
  for (const relative of FILES) {
    const file = path.join(REPO_ROOT, relative);
    if (mode === '--write') writeFileSync(file, rendered);
    else if (readFileSync(file, 'utf8') !== rendered) throw new Error(`stale arithmetic table: ${relative}`);
  }
  console.log(`${mode}: ${tables.tokens.length} tokens, ${tables.phrases.length} phrases; both native inventories`);
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await main();
}
