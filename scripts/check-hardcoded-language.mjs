#!/usr/bin/env node
// JavaScript twin of `scripts/check-hardcoded-language.rs` (PR #1188, SCRIPTS-B).
//
// Burn-down lint for hardcoded user-facing natural language in Rust source
// (R379): scans `rust/src/**/*.rs` for prose string literals and compares them
// with `scripts/hardcoded-language-allowlist.txt`. Fails on a new literal and
// on a stale allowlist row. Same output, exit codes and `::error` annotations
// as the Rust original, and `--write` renders the same allowlist byte for
// byte; CI runs both and diffs them
// (`data/meta/ci-gates/check-hardcoded-language-js-twin.lino`). Read the Rust
// script's doc comments for why each heuristic exists.
//
// Usage:
//   node scripts/check-hardcoded-language.mjs           # check
//   node scripts/check-hardcoded-language.mjs --write   # regenerate the allowlist

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import {
  RustError, compareTuples, extension, ioErrorMessage, isWhitespace, lines, readToString, splitOnce,
  trim, trimEnd, trimStart, walkDir,
} from './lib/checks-rust-compat.mjs';

const ALLOWLIST_PATH = 'scripts/hardcoded-language-allowlist.txt';
const SCAN_DIR = 'rust/src';
const ALLOWLIST_HEADER = `# Hardcoded natural-language allowlist (R379 burn-down).
#
# Generated by scripts/check-hardcoded-language.rs. Each row is a user-facing
# prose string literal that still lives in rust/src/ instead of data/seed/*.lino.
#
# Format (tab-separated): <relative-path>\\t<canonical-literal-text>
#   * Control characters are escaped (\\n, \\t, \\r, \\\\); the whole row is one line.
#   * Rows are sorted for a stable, review-friendly diff.
#
# DO NOT add rows by hand to silence the check. Instead migrate the string into
# grounded meanings under data/seed/ (look it up via seed::response_for or a
# named vocabulary) and delete its row. Regenerate after a legitimate migration
# with: rust-script scripts/check-hardcoded-language.rs --write
`;

const ALPHABETIC = /\p{Alphabetic}/u;
const NUMERIC = /\p{N}/u;
const isAlphabetic = (ch) => ALPHABETIC.test(ch);
const isAlphanumeric = (ch) => ALPHABETIC.test(ch) || NUMERIC.test(ch);
const isAsciiAlphanumeric = (ch) => /^[A-Za-z0-9]$/.test(ch);

/** Whether the literal at `start` sits where Rust produces visible text. */
function isOutputPosition(chars, start) {
  const prefix = chars.slice(Math.max(0, start - 96), start).join('');
  const compact = Array.from(prefix).filter((ch) => !isWhitespace(ch)).join('');
  if (compact.endsWith('format!(') || compact.endsWith('.push_str(')) return true;
  const trimmed = trimEnd(prefix);
  if (!trimmed.endsWith('return')) return false;
  const before = Array.from(trimmed.slice(0, -'return'.length));
  const last = before.at(-1);
  return last === undefined || (!isAlphanumeric(last) && last !== '_');
}

/** Every string literal of a Rust source, comments skipped (`extract_literals`). */
export function extractLiterals(content) {
  const chars = Array.from(content);
  const n = chars.length;
  const out = [];
  let i = 0;
  while (i < n) {
    const c = chars[i];
    if (c === '/' && i + 1 < n && chars[i + 1] === '/') {
      while (i < n && chars[i] !== '\n') i += 1;
      continue;
    }
    if (c === '/' && i + 1 < n && chars[i + 1] === '*') {
      i += 2;
      while (i + 1 < n && !(chars[i] === '*' && chars[i + 1] === '/')) i += 1;
      i += 2;
      continue;
    }
    if (c === "'") {
      if (i + 2 < n && chars[i + 1] === '\\') {
        let j = i + 2;
        while (j < n && chars[j] !== "'") j += 1;
        i = j + 1;
        continue;
      }
      if (i + 2 < n && chars[i + 2] === "'") {
        i += 3;
        continue;
      }
      i += 1;
      continue;
    }
    if (c === 'r' && i + 1 < n && (chars[i + 1] === '"' || chars[i + 1] === '#')) {
      let j = i + 1;
      let hashes = 0;
      while (j < n && chars[j] === '#') {
        hashes += 1;
        j += 1;
      }
      if (j < n && chars[j] === '"') {
        j += 1;
        const start = j;
        let end = null;
        while (j < n) {
          if (chars[j] === '"') {
            let k = j + 1;
            let matched = 0;
            while (k < n && matched < hashes && chars[k] === '#') {
              matched += 1;
              k += 1;
            }
            if (matched === hashes) {
              end = [j, k];
              break;
            }
          }
          j += 1;
        }
        if (end) {
          out.push({ text: canonicalizeRaw(chars.slice(start, end[0]).join('')), outputPosition: isOutputPosition(chars, i) });
          i = end[1];
          continue;
        }
        break;
      }
    }
    if (c === '"') {
      let j = i + 1;
      let body = '';
      while (j < n) {
        const ch = chars[j];
        if (ch === '\\') {
          if (j + 1 < n) {
            body += `\\${chars[j + 1]}`;
            j += 2;
            continue;
          }
          j += 1;
          continue;
        }
        if (ch === '"') break;
        body += ch;
        j += 1;
      }
      out.push({ text: canonicalizeNormal(body), outputPosition: isOutputPosition(chars, i) });
      i = j + 1;
      continue;
    }
    i += 1;
  }
  return out;
}

function canonicalChar(ch) {
  switch (ch) {
    case '\n': return '\\n';
    case '\t': return '\\t';
    case '\r': return '\\r';
    case '\\': return '\\\\';
    default: return ch;
  }
}

export function canonicalizeRaw(body) {
  return escapeTrailingSpaces(Array.from(body).map(canonicalChar).join(''));
}

function escapeTrailingSpaces(text) {
  const kept = text.replace(/ +$/, '');
  return kept + '\\x20'.repeat(text.length - kept.length);
}

export function canonicalizeNormal(body) {
  const chars = Array.from(body);
  const n = chars.length;
  let out = '';
  let i = 0;
  while (i < n) {
    const ch = chars[i];
    if (ch === '\\' && i + 1 < n) {
      const next = chars[i + 1];
      if (next === '\n') {
        i += 2;
        while (i < n && (chars[i] === ' ' || chars[i] === '\t')) i += 1;
        continue;
      }
      out += `\\${next}`;
      i += 2;
      continue;
    }
    out += canonicalChar(ch);
    i += 1;
  }
  return escapeTrailingSpaces(out);
}

/** The canonical text with escapes rendered and named placeholders anonymised. */
function heuristicView(text) {
  const chars = Array.from(text);
  const n = chars.length;
  let out = '';
  let i = 0;
  while (i < n) {
    if (chars[i] === '{' && i + 1 < n && chars[i + 1] !== '{') {
      const length = chars.slice(i + 1).indexOf('}');
      if (length !== -1) {
        const inner = chars.slice(i + 1, i + 1 + length);
        const colon = inner.indexOf(':');
        const nameEnd = colon === -1 ? inner.length : colon;
        if (inner.slice(0, nameEnd).every((ch) => isAsciiAlphanumeric(ch) || ch === '_')) {
          out += '{}';
          i += length + 2;
          continue;
        }
      }
    }
    if (chars[i] === '\\' && i + 1 < n) {
      const next = chars[i + 1];
      out += next === 'n' || next === 't' || next === 'r' ? ' ' : next;
      i += 2;
      continue;
    }
    out += chars[i];
    i += 1;
  }
  return out;
}

export function isUserFacingProse(canonical) {
  const view = heuristicView(canonical);
  if (!view.includes(' ')) return false;
  const last = Array.from(trimEnd(view)).at(-1);
  if (!(last === '.' || last === '!' || last === '?')) return false;
  let words = 0;
  let current = 0;
  for (const ch of view) {
    if (isAlphabetic(ch)) {
      current += 1;
    } else {
      if (current >= 2) words += 1;
      current = 0;
    }
  }
  if (current >= 2) words += 1;
  return words >= 2;
}

export function isMultiWordPhrase(canonical) {
  const view = heuristicView(canonical);
  if (!Array.from(view).some(isWhitespace)) return false;
  const lower = trim(view).replace(/[A-Z]/g, (ch) => ch.toLowerCase());
  if (['fn ', 'let ', 'use ', 'pub ', 'impl ', 'struct '].some((prefix) => lower.startsWith(prefix))
    || view.includes('::') || view.includes('=>') || view.includes('```')) {
    return false;
  }
  const lengths = [];
  let current = 0;
  for (const ch of view) {
    if (isAlphabetic(ch)) {
      current += 1;
    } else {
      if (current >= 2) lengths.push(current);
      current = 0;
    }
  }
  if (current >= 2) lengths.push(current);
  return lengths.length >= 2 && lengths.some((length) => length >= 3);
}

export function isUserFacingLiteral(literal) {
  return isUserFacingProse(literal.text) || (literal.outputPosition && isMultiWordPhrase(literal.text));
}

/** A sorted, de-duplicated entry list (`BTreeSet<Entry>`). */
function entrySet(entries) {
  const unique = new Map(entries.map((entry) => [`${entry.file}\t${entry.text}`, entry]));
  return [...unique.values()].sort((a, b) => compareTuples([a.file, a.text], [b.file, b.text]));
}

/** Scan `<root>/rust/src/**\/*.rs` for prose literals. */
export function scan(root, warn = (line) => process.stderr.write(`${line}\n`)) {
  const found = [];
  for (const entry of walkDir(join(root, SCAN_DIR))) {
    if (entry.error || entry.type !== 'file' || extension(entry.path) !== 'rs') continue;
    let content;
    try {
      content = readToString(entry.path);
    } catch (error) {
      if (!(error instanceof RustError)) throw error;
      warn(`Warning: could not read ${entry.path}: ${error.message}`);
      continue;
    }
    const file = entry.path.startsWith(`${root}/`) ? entry.path.slice(root.length + 1) : entry.path;
    for (const literal of extractLiterals(content)) {
      if (isUserFacingLiteral(literal)) found.push({ file, text: literal.text });
    }
  }
  return entrySet(found);
}

export function parseAllowlist(content) {
  return entrySet(lines(content)
    .filter((line) => !trimStart(line).startsWith('#') && trim(line) !== '')
    .flatMap((line) => {
      const parts = splitOnce(line, '\t');
      return parts && parts[0] !== '' && parts[1] !== '' ? [{ file: parts[0], text: parts[1] }] : [];
    }));
}

export function renderAllowlist(entries) {
  return `${ALLOWLIST_HEADER}\n${entries.map((entry) => `${entry.file}\t${entry.text}\n`).join('')}`;
}

export function diff(detected, allowlist) {
  const key = (entry) => `${entry.file}\t${entry.text}`;
  const allowed = new Set(allowlist.map(key));
  const present = new Set(detected.map(key));
  return {
    newViolations: detected.filter((entry) => !allowed.has(key(entry))),
    staleEntries: allowlist.filter((entry) => !present.has(key(entry))),
  };
}

function annotation(entry) {
  const file = entry.file.replaceAll('%', '%25').replaceAll('\r', '%0D').replaceAll('\n', '%0A')
    .replaceAll(':', '%3A').replaceAll(',', '%2C');
  const message = `Hardcoded user-facing string: "${entry.text}". Move it into data/seed/ (R379).`
    .replaceAll('%', '%25').replaceAll('\r', '%0D').replaceAll('\n', '%0A');
  return `::error file=${file}::${message}`;
}

function writeMode(root, out, err) {
  const detected = scan(root);
  try {
    writeFileSync(join(root, ALLOWLIST_PATH), renderAllowlist(detected));
  } catch (error) {
    err(`Failed to write ${ALLOWLIST_PATH}: ${ioErrorMessage(error)}`);
    return 1;
  }
  out(`Wrote ${detected.length} entr${detected.length === 1 ? 'y' : 'ies'} to ${ALLOWLIST_PATH}`);
  return 0;
}

function checkMode(root, out, err) {
  out('\nChecking rust/src/ for hardcoded user-facing natural language (R379)...\n');
  const detected = scan(root);
  let allowlist;
  try {
    allowlist = parseAllowlist(readToString(join(root, ALLOWLIST_PATH)));
  } catch (error) {
    if (!(error instanceof RustError)) throw error;
    err(`::error::Could not read allowlist ${ALLOWLIST_PATH}: ${error.message}\nGenerate it with: rust-script scripts/check-hardcoded-language.rs --write`);
    return 1;
  }
  const result = diff(detected, allowlist);
  out(`Detected prose literals: ${detected.length} | allowlisted: ${allowlist.length}\n`);
  if (result.newViolations.length === 0 && result.staleEntries.length === 0) {
    out(`No new hardcoded natural language; allowlist is in sync (${allowlist.length} entries).\n`);
    return 0;
  }
  if (result.newViolations.length) {
    out('New hardcoded user-facing strings found in rust/src/ (not in the allowlist):\n');
    for (const entry of result.newViolations) {
      out(annotation(entry));
      out(`  ${entry.file}: "${entry.text}"`);
    }
    out('\nMove each string into grounded meanings under data/seed/ and look it\nup (e.g. via seed::response_for), or — only if it is genuinely part of\nthe existing debt — regenerate the allowlist with --write.\n');
  }
  if (result.staleEntries.length) {
    out('Stale allowlist rows (no longer present in rust/src/ — prune them):\n');
    for (const entry of result.staleEntries) out(`  ${entry.file}: "${entry.text}"`);
    out('\nThese strings were migrated or changed. Regenerate the allowlist with:\nrust-script scripts/check-hardcoded-language.rs --write\n');
  }
  return 1;
}

function main() {
  const out = (line) => process.stdout.write(`${line}\n`);
  const err = (line) => process.stderr.write(`${line}\n`);
  // `std::env::args()` includes the program name, so a lone `--write` anywhere matches.
  const write = process.argv.slice(1).some((arg) => arg === '--write' || arg === '--update');
  const root = process.cwd();
  process.exitCode = write ? writeMode(root, out, err) : checkMode(root, out, err);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
