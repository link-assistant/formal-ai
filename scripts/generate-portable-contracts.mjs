#!/usr/bin/env node
// Reproducible JS -> Links IR -> production Rust and ES -> TypeScript.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { stringProgramToMeta, assertCompleteStringIR, renderStringRust } from './self-translation/portable-string.mjs';
import { translateJsToTs } from './translate-es.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = 'js/agentic/portable/string_contracts.mjs';
export const META = 'data/meta/portable-string-contracts.lino';
export const RUST = 'rust/src/portable_string_contracts.rs';
export const TYPESCRIPT = 'ts/agentic/portable/string_contracts.mts';
export function generatePortableContracts(source) {
  const meta = stringProgramToMeta(source);
  assertCompleteStringIR(meta);
  const sha = value => {
    return createHash('sha256').update(value).digest('hex');
  };
  return {
    [META]: meta,
    [RUST]: '// Generated by scripts/generate-portable-contracts.mjs; do not edit.\n// source-sha256 ' + sha(source) + '; meta-sha256 ' + sha(meta) + '\n' + renderStringRust(meta),
    [TYPESCRIPT]: translateJsToTs(source)
  };
}
export function checkPortableContracts(directory = root, write = false) {
  const outputs = generatePortableContracts(fs.readFileSync(path.join(directory, SOURCE), 'utf8'));
  const drift = [];
  for (const [relative, expected] of Object.entries(outputs)) {
    const destination = path.join(directory, relative);
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== expected) {
      drift.push(relative);
      if (write) {
        fs.mkdirSync(path.dirname(destination), {
          recursive: true
        });
        fs.writeFileSync(destination, expected);
      }
    }
  }
  return drift;
}
if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const mode = process.argv[2] || '--check';
  assert.ok(['--check', '--write'].includes(mode));
  const drift = checkPortableContracts(root, mode === '--write');
  if (drift.length && mode === '--check') {
    console.error('Portable contract drift: ' + drift.join(', '));
    process.exitCode = 1;
  } else console.log('Portable string contracts ' + (mode === '--write' ? 'generated' : 'match source'));
}
