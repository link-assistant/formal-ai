#!/usr/bin/env rust-script
//! Refresh the committed open-issue snapshot through the authenticated GitHub CLI.
//!
//! This is deliberately an operator-run writer: it changes only the local
//! snapshot, which then travels through the repository's normal review path.
//!
//! ```cargo
//! [package]
//! edition = "2024"
//! ```

use std::process::Command;

const TARGET: &str = "data/meta/issue-state.lino";
const QUERY: &str = "repos/link-assistant/formal-ai/issues?state=open&per_page=100";
const FILTER: &str = ".[] | [.number, (if .pull_request then \"pull_request\" else \"issue\" end), .state, .updated_at, .html_url] | @tsv";

struct Item {
    number: u64,
    kind: String,
    state: String,
    updated_at: String,
    url: String,
}

fn fetch() -> Result<Vec<Item>, String> {
    let output = Command::new("gh")
        .args(["api", "--paginate", QUERY, "--jq", FILTER])
        .output()
        .map_err(|error| format!("cannot run gh api: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "gh api failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let stdout = String::from_utf8(output.stdout).map_err(|error| error.to_string())?;
    let mut items = Vec::new();
    for (index, line) in stdout.lines().enumerate() {
        let columns: Vec<&str> = line.split('\t').collect();
        if columns.len() != 5 {
            return Err(format!(
                "gh api row {} has {} columns",
                index + 1,
                columns.len()
            ));
        }
        items.push(Item {
            number: columns[0]
                .parse()
                .map_err(|error| format!("row {} number: {error}", index + 1))?,
            kind: columns[1].to_owned(),
            state: columns[2].to_owned(),
            updated_at: columns[3].to_owned(),
            url: columns[4].to_owned(),
        });
    }
    items.sort_by(|left, right| right.number.cmp(&left.number));
    Ok(items)
}

fn render(items: &[Item]) -> String {
    let collected_at = items
        .iter()
        .map(|item| item.updated_at.as_str())
        .max()
        .unwrap_or("unknown");
    let mut output = format!(
        "# Generated by `rust-script scripts/refresh-issue-state.rs --write`.\nissue_state_snapshot\n  repository \"link-assistant/formal-ai\"\n  collected_at \"{collected_at}\"\n  source \"https://api.github.com/{QUERY}\"\n  scope open\n"
    );
    for item in items {
        output.push_str(&format!(
            "  item {}\n    kind {}\n    state {}\n    updated_at \"{}\"\n    url \"{}\"\n",
            item.number, item.kind, item.state, item.updated_at, item.url
        ));
    }
    output
}

fn main() {
    if std::env::args().nth(1).as_deref() != Some("--write") {
        eprintln!("usage: rust-script scripts/refresh-issue-state.rs --write");
        std::process::exit(2);
    }
    let items = fetch().unwrap_or_else(|error| {
        eprintln!("refresh-issue-state: {error}");
        std::process::exit(1);
    });
    std::fs::write(TARGET, render(&items))
        .unwrap_or_else(|error| panic!("cannot write {TARGET}: {error}"));
    println!("wrote {TARGET} with {} open items", items.len());
}
