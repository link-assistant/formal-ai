#!/usr/bin/env python3
"""Refresh the Wikidata captures fact answers are derived from (issue #1172 R9).

`data/seed/fact-realization.lino` lists, per fact relation, the subjects whose
facts are kept as captures (its `subject` records); the relation's property is
the `grounded-in` of its `fact_relation` meaning in
`data/seed/meanings-facts.lino`. For every subject this script

  1. fetches `Special:EntityData/<Q-id>.json` (only when the capture is
     missing or was trimmed by an older shape, or with `--refresh`), trims it
     to the labels and aliases of the realization languages and their label
     variants, the realization languages' Wikipedia sitelinks, and the truthy
     claims of the relation property (the best rank present, deprecated never),
     and writes `data/cache/wikidata/fact-claims/<Q-id>.json`;
  2. reads the value item from the first truthy claim and captures it the same
     way, without claims;
  3. writes each capture's canonical Links Notation beside it through the port
     of the cache codec (`scripts/wikidata_lino_codec.py`, verified against the
     whole committed cache by `--verify` there);
  4. writes `data/seed/fact-captures.lino`, the projection both runtimes read:
     one `entity` record per capture (subject first, then its value item) with
     its labels, aliases, sitelinks and claims as quoted lists, so the seed
     carries the captured strings verbatim and no free token.

`--check` writes nothing and fails when any `.lino` or the seed projection is
not what the committed `.json` captures encode. Network is needed only for a
missing capture or `--refresh`.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from wikidata_lino_codec import json_cache_file  # noqa: E402

USER_AGENT = "formal-ai-grounding/1.0 (https://github.com/link-assistant/formal-ai)"
REALIZATION = Path("data/seed/fact-realization.lino")
MEANINGS = Path("data/seed/meanings-facts.lino")
CACHE_DIR = Path("data/cache/wikidata/fact-claims")
PROJECTION = Path("data/seed/fact-captures.lino")
RANKS = ("preferred", "normal")
PROJECTION_HEADER = """\
# Committed Wikidata captures the fact records are derived from (issue #1172
# R9). Generated by `python3 scripts/ground-fact-captures.py` from the
# captures in data/cache/wikidata/fact-claims, never edited by hand. One entity
# record per capture, a subject first and its value item after it. A label or
# sitelink is the list of its language or site and the text, an alias line
# lists a language and its aliases, and a claim lists the property, the value
# item and the rank. data/seed/fact-realization.lino says how a fact record is
# realized from them.
fact_captures
"""


def lino_records(path: Path) -> list:
    """`(indent, name, value)` for every non-comment line."""
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        name, _, value = stripped.partition(" ")
        records.append((len(line) - len(line.lstrip(" ")), name, value.strip()))
    return records


def unquote_list(value: str) -> list:
    inner = value.strip()
    if inner.startswith("(") and inner.endswith(")"):
        inner = inner[1:-1]
    items, current, quoted = [], "", False
    for character in inner:
        if character == '"':
            quoted = not quoted
            continue
        if character == " " and not quoted:
            if current:
                items.append(current)
            current = ""
            continue
        current += character
    if current:
        items.append(current)
    return items


def manifest() -> tuple:
    """`(languages, capture_languages, [(relation, subject)])` from the seed."""
    languages, variants, subjects, relation = [], [], [], None
    for indent, name, value in lino_records(REALIZATION):
        if indent == 2 and name == "languages":
            languages = unquote_list(value)
        elif indent == 2 and name == "label_variant":
            variants += [item for item in unquote_list(value.partition(" ")[2]) if item not in variants]
        elif indent == 2 and name == "relation":
            relation = value
        elif indent == 2:
            relation = None
        elif indent == 4 and name == "subject" and relation:
            subjects.append((relation, value))
    capture_languages = languages + [variant for variant in variants if variant not in languages]
    return languages, capture_languages, subjects


def relation_properties() -> dict:
    properties, meaning = {}, None
    for indent, name, value in lino_records(MEANINGS):
        if indent == 2:
            meaning = name
        elif indent == 4 and name == "grounded-in" and meaning:
            properties[meaning] = value
    return properties


def fetch(qid: str) -> dict:
    url = f"https://www.wikidata.org/wiki/Special:EntityData/{qid}.json"
    raw = subprocess.run(["curl", "-sfL", "-A", USER_AGENT, url], capture_output=True, check=True).stdout
    return json.loads(raw)["entities"][qid]


def truthy(entity: dict, prop: str) -> list:
    claims = [claim for claim in entity.get("claims", {}).get(prop, [])
              if claim.get("mainsnak", {}).get("snaktype") == "value"]
    for rank in RANKS:
        best = [claim for claim in claims if claim.get("rank", "normal") == rank]
        if best:
            return [{"mainsnak": claim["mainsnak"], "rank": rank} for claim in best]
    return []


def trim(entity: dict, qid: str, languages: list, capture_languages: list, prop: str | None) -> dict:
    def per_language(section: str) -> dict:
        return {lang: entity[section][lang] for lang in capture_languages if lang in entity.get(section, {})}

    trimmed = {
        "type": entity.get("type", "item"),
        "id": qid,
        "labels": per_language("labels"),
        "aliases": per_language("aliases"),
        "sitelinks": {
            f"{lang}wiki": {"site": f"{lang}wiki", "title": link["title"]}
            for lang in languages
            for link in [entity.get("sitelinks", {}).get(f"{lang}wiki")]
            if link
        },
    }
    if prop:
        claims = truthy(entity, prop)
        if claims:
            trimmed["claims"] = {prop: claims}
    return trimmed


def grounding(capture_languages: list, languages: list, prop: str | None) -> dict:
    return {
        "languages": capture_languages,
        "sites": [f"{lang}wiki" for lang in languages],
        "claims": [prop] if prop else [],
        "claim_ranks": "truthy",
    }


def capture(qid: str, languages: list, capture_languages: list, prop: str | None, mode: str) -> dict:
    path = CACHE_DIR / f"{qid}.json"
    shape = grounding(capture_languages, languages, prop)
    document = json.loads(path.read_text(encoding="utf-8")) if path.exists() else None
    if mode != "--check" and (document is None or document.get("grounding") != shape or mode == "--refresh"):
        document = {"entities": {qid: trim(fetch(qid), qid, languages, capture_languages, prop)},
                    "success": 1, "grounding": shape}
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if document is None:
        raise SystemExit(f"missing capture {path}; run without --check")
    return document


def value_of(document: dict, qid: str, prop: str) -> str | None:
    for claim in document["entities"][qid].get("claims", {}).get(prop, []):
        value = claim["mainsnak"].get("datavalue", {}).get("value")
        if isinstance(value, dict) and value.get("id"):
            return value["id"]
    return None


def quoted(items: list) -> str:
    return "(" + " ".join(json.dumps(item, ensure_ascii=False) for item in items) + ")"


def project(qid: str, entity: dict) -> str:
    """One capture as the seed's `entity` record (keys in byte order)."""
    order = lambda mapping: sorted(mapping.items(), key=lambda pair: pair[0].encode("utf-8"))
    lines = [f"  entity {qid}\n"]
    for language, label in order(entity.get("labels", {})):
        lines.append(f"    label {quoted([language, label['value']])}\n")
    for language, aliases in order(entity.get("aliases", {})):
        lines.append(f"    alias {quoted([language] + [alias['value'] for alias in aliases])}\n")
    for site, link in order(entity.get("sitelinks", {})):
        lines.append(f"    sitelink {quoted([site, link['title']])}\n")
    for prop, claims in order(entity.get("claims", {})):
        for claim in claims:
            value = claim["mainsnak"].get("datavalue", {}).get("value", {})
            if isinstance(value, dict) and value.get("id"):
                lines.append(f"    claim {quoted([prop, value['id'], claim.get('rank', 'normal')])}\n")
    return "".join(lines)


def main(argv: list) -> int:
    mode = argv[0] if argv else "--write"
    if mode not in ("--write", "--check", "--refresh"):
        print("usage: ground-fact-captures.py [--write|--check|--refresh]", file=sys.stderr)
        return 2
    languages, capture_languages, subjects = manifest()
    properties = relation_properties()
    ordered, drift = [], []
    for relation, subject in subjects:
        prop = properties.get(relation)
        if not prop:
            raise SystemExit(f"relation {relation} has no grounded-in property in {MEANINGS}")
        document = capture(subject, languages, capture_languages, prop, mode)
        ordered.append(subject)
        value = value_of(document, subject, prop)
        if value:
            capture(value, languages, capture_languages, None, mode)
            ordered.append(value)
    blocks = []
    for qid in ordered:
        document = json.loads((CACHE_DIR / f"{qid}.json").read_text(encoding="utf-8"))
        encoded = json_cache_file(qid, document)
        lino_path = CACHE_DIR / f"{qid}.lino"
        if not lino_path.exists() or lino_path.read_text(encoding="utf-8") != encoded:
            drift.append(str(lino_path))
            if mode != "--check":
                lino_path.write_text(encoded, encoding="utf-8")
        blocks.append(project(qid, document["entities"][qid]))
    projection = PROJECTION_HEADER + "".join(blocks)
    if not PROJECTION.exists() or PROJECTION.read_text(encoding="utf-8") != projection:
        drift.append(str(PROJECTION))
        if mode != "--check":
            PROJECTION.write_text(projection, encoding="utf-8")
    if mode == "--check" and drift:
        print("fact captures drifted (run python3 scripts/ground-fact-captures.py):", file=sys.stderr)
        for path in drift:
            print(f"  {path}", file=sys.stderr)
        return 1
    print(f"fact captures: {len(ordered)} entities, {len(drift)} file(s) {'drifted' if mode == '--check' else 'written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
