#!/usr/bin/env node
// Writes data/meta/response-language-parity-debt.lino from the seed: every
// response intent of every data/seed/multilingual-responses*.lino that lacks
// one of the target languages, grouped by the languages it lacks. The Rust
// test issue_1138_self_use_concept_lookup reads the same files and requires
// the ledger to match exactly, so a gap can neither appear nor hide unseen.
//
// Usage: node scripts/generate-response-parity-debt.mjs [--write | --check]
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const LEDGER = 'data/meta/response-language-parity-debt.lino';
const SEED_DIRECTORY = 'data/seed';
const SEED_PREFIX = 'multilingual-responses';
const SEED_SUFFIX = '.lino';
const LANGUAGES = ['en', 'ru', 'hi', 'zh', 'es'];
const MACHINE_AUDIENCE = 'audience machine';

const unquote = (raw) => {
  const trimmed = raw.trim();
  const inner = trimmed.startsWith('"') && trimmed.endsWith('"') && trimmed.length > 1 ? trimmed.slice(1, -1) : trimmed;
  return inner.replaceAll('""', '"');
};

export function seededResponseLanguages(root = '.') {
  const languagesByIntent = new Map();
  const names = readdirSync(`${root}/${SEED_DIRECTORY}`)
    .filter((name) => name.startsWith(SEED_PREFIX) && name.endsWith(SEED_SUFFIX))
    .sort();
  for (const name of names) {
    let intent = '';
    let language = '';
    for (const line of readFileSync(`${root}/${SEED_DIRECTORY}/${name}`, 'utf8').split('\n')) {
      const trimmed = line.trim();
      if (trimmed.startsWith('intent ')) intent = unquote(trimmed.slice('intent '.length));
      else if (trimmed.startsWith('language ') && intent !== '') {
        language = unquote(trimmed.slice('language '.length));
        if (!languagesByIntent.has(intent)) languagesByIntent.set(intent, new Set());
        languagesByIntent.get(intent).add(language);
      } else if (trimmed === MACHINE_AUDIENCE && intent !== '') {
        // A row read by a program (a code template, a log line) is not a
        // reply to a person, so its language owes no translation.
        languagesByIntent.get(intent)?.delete(language);
      }
    }
  }
  return languagesByIntent;
}

const byteOrder = (left, right) => (left < right ? -1 : left > right ? 1 : 0);

export function renderLedger(languagesByIntent, measuredOn) {
  const intentsByMissing = new Map();
  for (const [intent, languages] of languagesByIntent) {
    // An intent with no target-language row at all is a code template
    // (`language rust`) or a row marked `audience machine`, not a reply to a
    // person, so it owes no translation.
    if (!LANGUAGES.some((language) => languages.has(language))) continue;
    const missing = LANGUAGES.filter((language) => !languages.has(language)).join(',');
    if (missing === '') continue;
    if (!intentsByMissing.has(missing)) intentsByMissing.set(missing, []);
    intentsByMissing.get(missing).push(intent);
  }
  const gapCount = [...intentsByMissing.values()].reduce((sum, intents) => sum + intents.length, 0);
  const rows = [...intentsByMissing.keys()].sort(byteOrder).map((missing) =>
    `  uncovered_behavior missing_languages "${missing}" observed_on "${measuredOn}" response_intents "${intentsByMissing.get(missing).sort(byteOrder).join(',')}"`);
  return [
    '# Generated by `node scripts/generate-response-parity-debt.mjs --write`; do not edit by hand.',
    'response_language_parity_debt',
    '  record_type "response_language_parity_debt"',
    `  measured_on "${measuredOn}"`,
    `  ceiling ${gapCount}`,
    `  target_languages "${LANGUAGES.join(',')}"`,
    `  source "${SEED_DIRECTORY}/${SEED_PREFIX}*${SEED_SUFFIX}"`,
    ...rows,
    '',
  ].join('\n');
}

function main() {
  const mode = process.argv[2] ?? '--check';
  const current = readFileSync(LEDGER, 'utf8');
  const keptDate = current.match(/measured_on "([^"]+)"/)?.[1];
  const languagesByIntent = seededResponseLanguages();
  const sameGaps = renderLedger(languagesByIntent, keptDate ?? '') === current;
  const measuredOn = sameGaps && keptDate ? keptDate : new Date().toISOString().slice(0, 10);
  const rendered = renderLedger(languagesByIntent, measuredOn);
  if (mode === '--write') {
    writeFileSync(LEDGER, rendered);
    console.log(`${LEDGER}: ${rendered.match(/ceiling (\d+)/)[1]} response intents lack a target language`);
    return;
  }
  if (!sameGaps) {
    console.error(`::error file=${LEDGER}::${LEDGER} does not match the seed; run node scripts/generate-response-parity-debt.mjs --write`);
    process.exit(1);
  }
  console.log(`${LEDGER} is current`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
