#!/usr/bin/env node
// Renders docs/architecture/principles.md from data/meta/architecture-principles.lino
// (R1188-U2): how this repository applies each universal principle of
// link-foundation/code-architecture-principles, which gate enforces it, and
// which requirement row tracks what is missing.
//
// Usage:
//   node scripts/render-architecture-principles.mjs --write   regenerate the page
//   node scripts/render-architecture-principles.mjs --check   fail on a stale page,
//       a gate that does not exist under data/meta/ci-gates/, or a requirement row
//       no docs/requirements shard defines

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'data/meta/architecture-principles.lino';
const PAGE = 'docs/architecture/principles.md';
const GATES = 'data/meta/ci-gates';
const REQUIREMENTS = 'docs/requirements';

const unquote = (text) => (text.startsWith('"') && text.endsWith('"') ? text.slice(1, -1) : text);

/** The principles map: its source, commit and groups of principles. */
export function parsePrinciples(text) {
  const map = { source: '', commit: '', groups: [] };
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('#')) continue;
    const space = trimmed.indexOf(' ');
    const key = space < 0 ? trimmed : trimmed.slice(0, space);
    const value = space < 0 ? '' : unquote(trimmed.slice(space + 1));
    const group = map.groups.at(-1);
    const principle = group?.principles.at(-1);
    if (key === 'source' || key === 'commit') map[key] = value;
    else if (key === 'group') map.groups.push({ name: value, principles: [] });
    else if (key === 'principle') group.principles.push({ name: value, practice: '', gates: [], gaps: [] });
    else if (key === 'practice') principle.practice = value;
    else if (key === 'enforced-by') principle.gates.push(value);
    else if (key === 'gap') principle.gaps.push(value);
  }
  return map;
}

/** The Markdown page for the principles map. */
export function renderPage(map) {
  const lines = [
    '<!-- Generated by `node scripts/render-architecture-principles.mjs --write` from data/meta/architecture-principles.lino; do not edit by hand. -->',
    '',
    '# Architecture principles',
    '',
    `This repository follows the universal principles of [code-architecture-principles](${map.source}) (pinned at \`${map.commit.slice(0, 12)}\`, R1188-U2).`,
    'Each principle below says how it is applied here, which CI gate fails a pull request that breaks it, and which requirement row tracks what is still missing.',
    'A principle with neither a gate nor a gap is a convention the repository follows without a gate yet.',
    '',
    '## Review checklist',
    '',
    'Before asking for review, check the change against each group below: the gates run in CI, and the gaps name what a reviewer still checks by hand.',
    '',
  ];
  for (const group of map.groups) {
    lines.push(`## ${group.name}`, '', '| Principle | How this repository applies it | Enforced by | Still missing |', '| --- | --- | --- | --- |');
    for (const principle of group.principles) {
      const gates = principle.gates.map((gate) => `[\`${gate}\`](../../${GATES}/${gate}.lino)`).join(', ') || '—';
      const gaps = principle.gaps.join(', ') || '—';
      lines.push(`| ${principle.name} | ${principle.practice} | ${gates} | ${gaps} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

/** Requirement ids defined by the rows of every requirement shard. */
function requirementIds(root) {
  const ids = new Set();
  for (const name of readdirSync(join(root, REQUIREMENTS)).filter((file) => file.endsWith('.md'))) {
    for (const match of readFileSync(join(root, REQUIREMENTS, name), 'utf8').matchAll(/^\| (R[\w-]+) \|/gmu)) ids.add(match[1]);
  }
  return ids;
}

/** What is wrong with the map: unknown gates, unknown requirement rows, empty practices. */
export function problems(map, root = ROOT) {
  const found = [];
  const ids = requirementIds(root);
  for (const group of map.groups) {
    for (const principle of group.principles) {
      if (principle.practice === '') found.push(`${principle.name}: no practice`);
      for (const gate of principle.gates) {
        if (!existsSync(join(root, GATES, `${gate}.lino`))) found.push(`${principle.name}: no gate ${GATES}/${gate}.lino`);
      }
      for (const gap of principle.gaps) {
        if (!ids.has(gap)) found.push(`${principle.name}: no requirement row ${gap}`);
      }
    }
  }
  return found;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const map = parsePrinciples(readFileSync(join(ROOT, SOURCE), 'utf8'));
  const page = renderPage(map);
  const found = problems(map);
  for (const problem of found) console.error(`${SOURCE}: ${problem}`);
  if (process.argv.includes('--write')) {
    writeFileSync(join(ROOT, PAGE), page);
    console.log(`wrote ${PAGE}`);
  } else if (process.argv.includes('--check')) {
    const current = existsSync(join(ROOT, PAGE)) ? readFileSync(join(ROOT, PAGE), 'utf8') : '';
    if (current !== page) {
      console.error(`${PAGE} is stale; run node scripts/render-architecture-principles.mjs --write`);
      process.exit(1);
    }
  }
  if (found.length > 0) process.exit(1);
  const principles = map.groups.reduce((sum, group) => sum + group.principles.length, 0);
  console.log(`${principles} principles in ${map.groups.length} groups`);
}
