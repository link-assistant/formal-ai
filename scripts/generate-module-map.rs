#!/usr/bin/env rust-script
//! Issue #954 (E102): the generated "Module map" section of ARCHITECTURE.md.
//!
//! One row per `pub mod` declared in `rust/src/lib.rs`: the module name,
//! a one-sentence responsibility (the module file's own `//!` first line,
//! with an override table for the modules whose file starts with code),
//! and the ARCHITECTURE.md section that owns it.
//!
//! Usage:
//!   rust-script scripts/generate-module-map.rs            # print the section
//!   rust-script scripts/generate-module-map.rs --check     # pin: the
//!           ARCHITECTURE.md module list equals lib.rs's mod list
//!   rust-script scripts/generate-module-map.rs --write     # replace the
//!           section between the markers in ARCHITECTURE.md
//!
//! The pinned property is coverage, not prose: `--check` (and the
//! `issue_954_module_map` unit test, which reads the same files) fails when
//! a module is declared in lib.rs but missing from the map, or when a map
//! row names a module that no longer exists -- so a new module fails CI
//! until documented, exactly as the issue requires.
//!
//! ```cargo
//! [package]
//! edition = "2024"
//! ```

