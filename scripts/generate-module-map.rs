struct Row {
    name: String,
    responsibility: String,
    section: String,
}

fn section_for(name: &str) -> &'static str {
    for (needles, section, prefix) in SECTION_RULES {
        for needle in *needles {
            let hit = if *prefix {
                name.starts_with(needle)
            } else {
                name.contains(needle)
            };
            if hit {
                return section;
            }
        }
    }
    "2"
}

/// The module's own `//!` first line, or its `/* … */` header's opening
/// sentence for the files that start with a block comment.
fn header_doc(name: &str) -> Option<String> {
    for candidate in [
        format!("rust/src/{name}.rs"),
        format!("rust/src/{name}/mod.rs"),
    ] {
        let Ok(source) = fs::read_to_string(repo_path(&candidate)) else {
            continue;
        };
        let mut first = String::new();
        for line in source.lines() {
            let trimmed = line.trim();
            if trimmed.is_empty() {
                continue;
            }
            if let Some(rest) = trimmed.strip_prefix("//!") {
                let rest = rest.trim();
                if !rest.is_empty() && first.is_empty() {
                    first = rest.to_string();
                }
                break;
            }
            if trimmed.starts_with("/*") || trimmed.starts_with('*') {
                let body = trimmed
                    .trim_start_matches("/*")
                    .trim_end_matches("*/")
                    .trim();
                if !body.is_empty() {
                    first = format!("{first}{body}");
                }
                if trimmed.ends_with("*/") {
                    break;
                }
                continue;
            }
            if trimmed.starts_with("//") {
                continue;
            }
            break;
        }
        if !first.is_empty() {
            return Some(first);
        }
        return None;
    }
    None
}

fn tidy(source: &str) -> String {
    let mut doc: String = source.split_whitespace().collect::<Vec<_>>().join(" ");
    while doc.ends_with('.') {
        doc.pop();
        doc = doc.trim_end().to_string();
    }
    if doc.chars().count() > 108 {
        doc = doc.chars().take(105).collect::<String>();
        if let Some(cut) = doc.rfind(' ') {
            doc.truncate(cut);
        }
    }
    for tail in [
        " and", " the", " of", " to", " a", " an", " in", " for", " with", " by", " —", "—",
        "*how*",
    ] {
        if doc.ends_with(tail) {
            doc.truncate(doc.len() - tail.len());
            doc = doc.trim_end().to_string();
        }
    }
    format!("{doc}.")
}

fn rows() -> Vec<Row> {
    let lib = fs::read_to_string(repo_path(LIB)).expect("rust/src/lib.rs readable");
    let mut rows = Vec::new();
    for line in lib.lines() {
        let Some(name) = line
            .strip_prefix("pub mod ")
            .and_then(|rest| rest.strip_suffix(';'))
        else {
            continue;
        };
        let responsibility = OVERRIDES
            .iter()
            .find(|(candidate, _)| *candidate == name)
            .map(|(_, sentence)| sentence.to_string())
            .or_else(|| header_doc(name))
            .unwrap_or_default();
        rows.push(Row {
            name: name.to_string(),
            responsibility: tidy(&responsibility),
            section: section_for(name).to_string(),
        });
    }
    rows.sort_by(|left, right| {
        left.section
            .parse::<f32>()
            .unwrap_or(2.0)
            .partial_cmp(&right.section.parse::<f32>().unwrap_or(2.0))
            .unwrap()
            .then_with(|| left.name.cmp(&right.name))
    });
    rows
}

fn rendered() -> String {
    let mut out = String::new();
    out.push_str(BEGIN);
    out.push('\n');
    out.push_str("One row per module declared in `rust/src/lib.rs`. Regenerate with\n");
    out.push_str("`rust-script scripts/generate-module-map.rs --write`; the module list is\n");
    out.push_str("pinned by `rust/tests/unit/issue_954_module_map.rs` (and `--check`), so a\n");
    out.push_str("new module fails CI until this map documents it.\n\n");
    out.push_str("| Module | Responsibility | Owning section |\n");
    out.push_str("|---|---|---|\n");
    for row in rows() {
        out.push_str(&format!(
            "| `{}` | {} | §{} |\n",
            row.name, row.responsibility, row.section
        ));
    }
    out.push_str(END);
    out
}

/// The map's first column, read back out of a rendered section: every line
/// shaped like a table row whose first cell is a bare `` `name` ``.
fn mapped_names(section: &str) -> Vec<String> {
    let mut names = Vec::new();
    for line in section.lines() {
        let rest = line.trim().strip_prefix('|').map(|rest| rest.trim());
        let Some(rest) = rest else { continue };
        if rest.starts_with("---") || rest.starts_with("Module |") {
            continue;
        }
        let Some((name, _)) = rest.split_once('|') else {
            continue;
        };
        let name = name.trim().trim_matches('`');
        if !name.is_empty()
            && name
                .chars()
                .all(|character| character.is_ascii_alphanumeric() || character == '_')
        {
            names.push(name.to_string());
        }
    }
    names
}

/// The generated section currently inside ARCHITECTURE.md, markers
/// included; the pin compares its name column against lib.rs.
fn committed_section(architecture: &str) -> String {
    let begin = architecture
        .find(BEGIN)
        .unwrap_or_else(|| panic!("{ARCHITECTURE} carries the module-map begin marker"));
    let end = architecture
        .find(END)
        .unwrap_or_else(|| panic!("{ARCHITECTURE} carries the module-map end marker"));
    architecture[begin..end + END.len()].to_string()
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let check = args.iter().any(|argument| argument == "--check");
    let write = args.iter().any(|argument| argument == "--write");

    let architecture =
        fs::read_to_string(repo_path(ARCHITECTURE)).expect("ARCHITECTURE.md readable");
    let section = committed_section(&architecture);

    if check {
        let declared: Vec<String> = rows().into_iter().map(|row| row.name).collect();
        let mapped = mapped_names(&section);
        let missing: Vec<&String> = declared
            .iter()
            .filter(|name| !mapped.contains(name))
            .collect();
        let stale: Vec<&String> = mapped
            .iter()
            .filter(|name| !declared.contains(name))
            .collect();
        if !missing.is_empty() || !stale.is_empty() {
            eprintln!(
                "generate-module-map: the ARCHITECTURE.md module map is out of sync with {LIB} -- missing {:?}, stale {:?}; run --write",
                missing, stale
            );
            std::process::exit(1);
        }
        println!("module map covers all {} declared modules", declared.len());
        return;
    }

    if write {
        let updated = format!(
            "{}{}{}",
            &architecture[..architecture.find(BEGIN).expect("begin marker")],
            rendered(),
            &architecture[architecture.find(END).expect("end marker") + END.len()..]
        );
        fs::write(ARCHITECTURE, updated).expect("ARCHITECTURE.md writable");
        println!("rewrote the module map section in {ARCHITECTURE}");
        return;
    }

    print!("{}", rendered());
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_map_covers_every_declared_module_with_a_sentence() {
        let all = rows();
        assert!(all.len() >= 150, "lib.rs declares {} modules", all.len());
        assert!(
            all.iter().all(|row| !row.responsibility.is_empty()),
            "every module carries a one-sentence responsibility"
        );
    }

    #[test]
    fn the_owning_sections_are_the_documents_own_numbers() {
        for row in rows() {
            let number: f32 = row.section.parse().expect("a section number");
            assert!(
                (2.0..=15.0).contains(&number),
                "{} -> {}",
                row.name,
                row.section
            );
        }
    }

    #[test]
    fn tidy_truncates_without_dangling_words() {
        let sentence = tidy(
            "rethinking *how* to solve the general failure-to-repair classifier when the meta algorithm and the",
        );
        assert!(sentence.chars().count() < 120);
        assert!(!sentence.ends_with(" and"));
        assert!(sentence.ends_with('.'));
    }

    #[test]
    fn mapped_names_reads_the_first_column_back() {
        let names = mapped_names(
            "| Module | Responsibility | Owning section |\n|---|---|---|\n| `solver` | The universal problem solver. | §7 |\n| not a row\n",
        );
        assert_eq!(names, vec!["solver".to_string()]);
    }
}
