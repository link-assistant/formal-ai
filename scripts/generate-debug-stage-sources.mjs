#!/usr/bin/env node
// Generate data/meta/debug-stage-sources.lino (issue #667, R383): for every
// solver event kind that becomes a stage of a turn (js/server/solver-trace.mjs
// `thinkingStepsFromEvents`, the port of rust/src/event_log.rs
// `thinking_steps_for_answer`), the functions that append it in the Rust
// solver and in the JavaScript server's solver chain. The step-through debug
// session reads the table to name the code behind each stage
// (js/server/debug-stage-sources.mjs, rust/src/server/debug_stage_sources.rs).
//
// An append site is a call that names its kind as a string literal, or as a
// string constant of the same file:
//   - Rust: `<log>.append("<kind>", …)`;
//   - JavaScript: `solverEvent("<kind>", …)` and `<log>.push({ kind: "<kind>", … })`.
// Its function is the nearest enclosing definition (`fn` / `function`) that is
// less indented than the call. Sites are listed once per function, sorted.
//
// Usage:
//   node scripts/generate-debug-stage-sources.mjs --write   regenerate the table
//   node scripts/generate-debug-stage-sources.mjs --check   fail when the committed
//                                                           table drifts (CI gate)

import { writeFileSync } from 'node:fs';
import path from 'node:path';

import { STAGE_SOURCES, definedName, readText, treeFiles } from '../js/server/debug-stage-sources.mjs';
import { REPO_ROOT } from '../js/server/lino.mjs';
import { thinkingStepsFromEvents } from '../js/server/solver-trace.mjs';

/** The runtimes: where their solver code lives and where a solve starts. */
const RUNTIMES = [
  {
    name: 'rust',
    keyword: 'fn',
    trees: [{ path: 'rust/src', extension: '.rs' }],
    // Every protocol turn is solved here (`solve_with_history`).
    entries: [{ path: 'rust/src/solver.rs', symbol: 'solve_with_history_probability_store_and_intent_cache' }],
    sites: [/\.append\(\s*("[^"\\]*"|[A-Z][A-Z0-9_]*)\s*,/g],
    constant: /^\s*(?:pub(?:\([a-z]+\))?\s+)?const ([A-Z][A-Z0-9_]*): &str = ("[^"\\]*");/,
  },
  {
    name: 'js',
    keyword: 'function',
    trees: [
      { path: 'js/worker', extension: '.js' },
      { path: 'js/agentic/crate', extension: '.mjs' },
      { path: 'js/server', extension: '.mjs' },
    ],
    // Raw worker events are recorded before the server projects their native order.
    entries: [
      { path: 'js/worker/formal_ai_worker_solver_events.js', symbol: 'recordSolverEventLog' },
      { path: 'js/server/solver-log.mjs', symbol: 'nativeSolverLog' },
    ],
    sites: [
      /solverEvent\(\s*("[^"\\]*"|'[^'\\]*'|[A-Z][A-Z0-9_]*)\s*,/g,
      /\.push\(\s*\{\s*kind:\s*("[^"\\]*"|'[^'\\]*'|[A-Z][A-Z0-9_]*)\s*,/g,
    ],
    constant: /^\s*(?:export\s+)?const ([A-Z][A-Z0-9_]*) = ("[^"\\]*"|'[^'\\]*');/,
  },
];

const HEADER = `# Which functions emit each stage of a debugged turn (issue #667, R383).
#
# Generated by scripts/generate-debug-stage-sources.mjs from the source tree;
# do not edit by hand (CI runs it with --check). For every solver event kind
# that becomes a thinking step (\`step\`), the functions that append it in each
# runtime, and each runtime's source trees and solver entry. The step-through
# debug session (js/server/debug-stage-sources.mjs, Rust twin
# rust/src/server/debug_stage_sources.rs) picks one per stage: the only one,
# else the one fewest calls from the turn's routed handler, else from the entry.
`;

const unquote = (token) => token.replace(/^["'](.*)["']$/, '$1');

/** The line index of character `offset` in `text`. */
const lineAt = (text, offset) => text.slice(0, offset).split('\n').length - 1;

/** The nearest enclosing definition of line `index`: less indented, at or above it. */
function enclosing(lines, index, keyword) {
  const indent = lines[index].length - lines[index].trimStart().length;
  for (let at = index; at >= 0; at -= 1) {
    const name = definedName(lines[at], keyword);
    if (name && lines[at].length - lines[at].trimStart().length < indent) return name;
  }
  return null;
}

/** Every `(kind, path, symbol)` append site of one runtime. */
function appendSites(runtime) {
  const sites = [];
  for (const tree of runtime.trees) {
    for (const file of treeFiles(REPO_ROOT, tree.path, tree.extension)) {
      const text = readText(REPO_ROOT, file) ?? '';
      const lines = text.split('\n');
      const constants = new Map();
      for (const line of lines) {
        const match = runtime.constant.exec(line);
        if (match) constants.set(match[1], unquote(match[2]));
      }
      for (const pattern of runtime.sites) {
        for (const match of text.matchAll(pattern)) {
          const kind = /^["']/.test(match[1]) ? unquote(match[1]) : constants.get(match[1]);
          const symbol = kind ? enclosing(lines, lineAt(text, match.index), runtime.keyword) : null;
          if (symbol) sites.push({ kind, path: file, symbol });
        }
      }
    }
  }
  return sites;
}

/** The thinking step an event kind becomes, or null when curation drops it. */
function stepFor(kind) {
  const steps = thinkingStepsFromEvents([{ kind, payload: kind }], kind);
  return steps.find((step) => step.source_event === kind)?.step ?? null;
}

export function renderStageSources() {
  const out = [HEADER.trimEnd(), 'debug_stage_sources'];
  const events = new Map();
  for (const runtime of RUNTIMES) {
    out.push(`  runtime ${runtime.name}`, `    keyword ${runtime.keyword}`);
    for (const tree of runtime.trees) out.push(`    tree "${tree.path}" "${tree.extension}"`);
    for (const entry of runtime.entries) out.push(`    entry "${entry.path}" ${entry.symbol}`);
    for (const site of appendSites(runtime)) {
      if (!events.has(site.kind)) events.set(site.kind, new Map());
      const rows = events.get(site.kind);
      if (!rows.has(runtime.name)) rows.set(runtime.name, new Set());
      rows.get(runtime.name).add(`"${site.path}" ${site.symbol}`);
    }
  }
  for (const kind of [...events.keys()].sort()) {
    const step = stepFor(kind);
    if (!step) continue;
    out.push(`  event "${kind}"`, `    step ${step}`);
    for (const runtime of RUNTIMES) {
      for (const row of [...(events.get(kind).get(runtime.name) ?? [])].sort()) out.push(`    ${runtime.name} ${row}`);
    }
  }
  return `${out.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const mode = process.argv[2];
  if (mode !== '--write' && mode !== '--check') {
    console.error('usage: node scripts/generate-debug-stage-sources.mjs --write|--check');
    process.exit(2);
  }
  const text = renderStageSources();
  if (readText(REPO_ROOT, STAGE_SOURCES) !== text) {
    if (mode === '--write') {
      writeFileSync(path.join(REPO_ROOT, STAGE_SOURCES), text);
      console.log(`${STAGE_SOURCES} written`);
    } else {
      console.error(`::error file=${STAGE_SOURCES}::${STAGE_SOURCES} drifted from the source tree; run node scripts/generate-debug-stage-sources.mjs --write`);
      process.exit(1);
    }
  } else {
    console.log(`${STAGE_SOURCES} is current`);
  }
}
