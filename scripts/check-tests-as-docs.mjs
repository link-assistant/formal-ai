#!/usr/bin/env node
// JavaScript twin of `scripts/check-tests-as-docs.rs` (issue #1191).
//
// Burn-down lint (R234-2): every behavioural test that asserts on an engine
// answer must also show that answer exactly, either with
// `assert_eq!(response.answer, "…")` or as membership in an explicit list of
// exact answers. Loose-only tests are tracked in
// `scripts/tests-as-docs-allowlist.txt`, and the debt may only shrink.
//
// The Rust original runs only in the main-branch `stage rust` gates, because
// it compiles `syn`. Main "CI/CD Pipeline" run 43710854562 at 686367d20
// therefore failed on a loose-only test that its green pull request never
// checked. This twin parses the same files with the vendored tree-sitter Rust
// grammar (js/vendor/tree-sitter), so the fast pull-request lint rejects that
// change before merge. It prints the same report with the same exit code, and
// `data/meta/ci-gates/check-tests-as-documentation-javascript-twin.lino` compares the two on
// main. The rules are the Rust script's; its doc comments explain each one.
//
// Usage:
//   node scripts/check-tests-as-docs.mjs           # check (CI/local)
//   node scripts/check-tests-as-docs.mjs --write   # regenerate allowlist

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ALLOWLIST_PATH = 'scripts/tests-as-docs-allowlist.txt';
const SCAN_DIR = 'rust/tests';
const SKIP_PATH_FRAGMENTS = ['tests/source/', 'tests/fixtures/', 'tests/e2e/node_modules'];
const ASSERTIONS = new Set(['assert', 'debug_assert', 'assert_eq', 'debug_assert_eq', 'assert_ne', 'debug_assert_ne']);
const EQUALITIES = new Set(['assert_eq', 'debug_assert_eq']);

export const ALLOWLIST_HEADER = `# Tests-as-docs allowlist (R234-2 burn-down).
#
# Generated by scripts/check-tests-as-docs.rs. Each row is a behavioural test
# that asserts on an engine answer using only loose assertions (contains /
# !contains) without ever showing the exact answer text a reader could learn
# the system's behaviour from.
#
# Format (tab-separated): <relative-path>\\t<test-fn-name>
#   * Rows are sorted for a stable, review-friendly diff.
#
# DO NOT add rows by hand to silence the check. Instead make the test explicit:
#   assert_eq!(response.answer, "…");                       // one exact answer
#   assert!(EXPECTED.contains(&response.answer.as_str()), …); // one of several
# and delete its row. Regenerate after a legitimate migration with:
#   rust-script scripts/check-tests-as-docs.rs --write
`;

const COMMENTS = new Set(['line_comment', 'block_comment']);
// Subtrees that never hold an expression path in syn's AST: macro bodies are
// unparsed tokens (assertions are classified separately), and the rest are
// paths with several segments, attributes, imports, labels, types and patterns.
const NOT_EXPRESSIONS = new Set([
  'macro_invocation', 'scoped_identifier', 'attribute_item', 'inner_attribute_item', 'use_declaration',
  'label', 'lifetime', 'closure_parameters', 'parameters', 'type_arguments', 'type_parameters', ...COMMENTS,
]);
const NOT_EXPRESSION_FIELDS = new Set(['type', 'return_type', 'type_parameters', 'trait', 'name', 'pattern', 'parameters']);

/** Load the vendored tree-sitter Rust grammar; the caller deletes the parser. */
export async function loadRustParser(root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')) {
  const runtime = await import(pathToFileURL(path.join(root, 'js/vendor/tree-sitter/web-tree-sitter.mjs')).href);
  await runtime.Parser.init();
  const parser = new runtime.Parser();
  parser.setLanguage(await runtime.Language.load(path.join(root, 'js/vendor/tree-sitter/tree-sitter-rust.wasm')));
  return parser;
}

const meaningful = node => node.namedChildren.filter(child => !COMMENTS.has(child.type));

/** The receiver of `receiver.method(…)` or `receiver.method::<T>(…)` when the call is a method call. */
function methodCallee(call) {
  const callee = call.childForFieldName('function');
  if (callee?.type === 'field_expression') return callee;
  const generic = callee?.type === 'generic_function' ? callee.childForFieldName('function') : null;
  return generic?.type === 'field_expression' ? generic : null;
}

/** syn's `refers_to_answer`: an `.answer` field or a local alias of one, outside macros. */
export function refersToAnswer(node, aliases) {
  if (NOT_EXPRESSIONS.has(node.type)) return false;
  switch (node.type) {
    case 'field_expression':
      // Only a field named `answer` is answer text; other projections are metadata.
      return node.childForFieldName('field')?.text === 'answer';
    case 'identifier':
      return aliases.has(node.text);
    case 'shorthand_field_initializer':
      return meaningful(node).some(child => refersToAnswer(child, aliases));
    case 'call_expression': {
      const method = methodCallee(node);
      if (method) {
        const receiver = method.childForFieldName('value');
        return refersToAnswer(receiver, aliases) || refersToAnswer(node.childForFieldName('arguments'), aliases);
      }
      break;
    }
    case 'let_condition':
      return refersToAnswer(node.childForFieldName('value'), aliases);
    case 'match_pattern': {
      const guard = node.childForFieldName('condition');
      return guard ? refersToAnswer(guard, aliases) : false;
    }
    default:
      break;
  }
  for (let index = 0; index < node.childCount; index += 1) {
    if (NOT_EXPRESSION_FIELDS.has(node.fieldNameForChild(index))) continue;
    const child = node.child(index);
    if (child.isNamed && refersToAnswer(child, aliases)) return true;
  }
  return false;
}

/** syn's `exact_membership`: `EXPECTED.contains(answer)` or `answer == expected`, possibly negated or parenthesized. */
export function exactMembership(node, aliases) {
  switch (node.type) {
    case 'call_expression': {
      const method = methodCallee(node);
      if (method?.childForFieldName('field')?.text !== 'contains') return false;
      return !refersToAnswer(method.childForFieldName('value'), aliases) &&
        meaningful(node.childForFieldName('arguments')).some(argument => refersToAnswer(argument, aliases));
    }
    case 'parenthesized_expression':
    case 'unary_expression':
      return meaningful(node).some(inner => exactMembership(inner, aliases));
    case 'binary_expression':
      return node.childForFieldName('operator')?.text === '==' &&
        refersToAnswer(node.childForFieldName('left'), aliases) !== refersToAnswer(node.childForFieldName('right'), aliases);
    default:
      return false;
  }
}

/** syn's `pattern_names`: the bindings a `let` pattern introduces. */
export function patternNames(pattern, names) {
  if (!pattern) return;
  switch (pattern.type) {
    case 'identifier':
      names.add(pattern.text);
      break;
    case 'captured_pattern': {
      const [binding] = meaningful(pattern);
      if (binding?.type === 'identifier') names.add(binding.text);
      break;
    }
    case 'mut_pattern':
    case 'ref_pattern':
    case 'reference_pattern':
    case 'slice_pattern':
      for (const child of meaningful(pattern)) patternNames(child, names);
      break;
    case 'tuple_pattern': {
      const elements = meaningful(pattern);
      // `(x)` is syn's Pat::Paren, whose bindings syn's pattern_names skips.
      const parenthesized = elements.length === 1 && !pattern.children.some(child => child.type === ',');
      if (!parenthesized) for (const element of elements) patternNames(element, names);
      break;
    }
    case 'tuple_struct_pattern':
      for (let index = 0; index < pattern.childCount; index += 1) {
        const child = pattern.child(index);
        if (child.isNamed && pattern.fieldNameForChild(index) !== 'type') patternNames(child, names);
      }
      break;
    case 'struct_pattern':
      for (const field of meaningful(pattern).filter(child => child.type === 'field_pattern')) {
        const shorthand = field.namedChildren.find(child => child.type === 'shorthand_field_identifier');
        if (shorthand) names.add(shorthand.text);
        else patternNames(field.childForFieldName('pattern'), names);
      }
      break;
    default:
      break;
  }
}

function macroName(invocation) {
  const path = invocation.childForFieldName('macro');
  if (path?.type === 'scoped_identifier') return path.childForFieldName('name')?.text ?? null;
  return path?.text ?? null;
}

class AnswerAudit {
  constructor(parser) {
    this.parser = parser;
    this.aliases = new Set();
    this.asserted = false;
    this.exact = false;
  }

  /** Parse an assertion's tokens as comma-separated expressions, as syn's `Punctuated::<Expr, Token![,]>` does. */
  withArguments(invocation, use) {
    const tokens = invocation.namedChildren.find(child => child.type === 'token_tree');
    if (!tokens || tokens.childCount < 2) return;
    const inner = tokens.text.slice(tokens.child(0).text.length, tokens.text.length - tokens.child(tokens.childCount - 1).text.length);
    const tree = this.parser.parse(`fn __formal_ai_tests_as_docs() { __formal_ai_arguments(${inner}\n); }`);
    try {
      if (tree.rootNode.hasError) return;
      const call = tree.rootNode.descendantsOfType('call_expression')[0];
      use(meaningful(call.childForFieldName('arguments')));
    } finally {
      tree.delete();
    }
  }

  auditAssertion(invocation) {
    const name = macroName(invocation);
    if (!ASSERTIONS.has(name)) return;
    this.withArguments(invocation, ([first, second]) => {
      if (!first) return;
      if (name === 'assert' || name === 'debug_assert') {
        if (refersToAnswer(first, this.aliases)) {
          this.asserted = true;
          this.exact ||= exactMembership(first, this.aliases);
        }
        return;
      }
      if (!second) return;
      const firstIsAnswer = refersToAnswer(first, this.aliases);
      const secondIsAnswer = refersToAnswer(second, this.aliases);
      if (firstIsAnswer || secondIsAnswer) {
        this.asserted = true;
        if (EQUALITIES.has(name)) this.exact ||= firstIsAnswer !== secondIsAnswer;
      }
    });
  }

  visit(node) {
    if (!node) return;
    switch (node.type) {
      case 'macro_invocation':
        this.auditAssertion(node);
        return;
      case 'attribute_item':
      case 'inner_attribute_item':
        return;
      case 'let_declaration': {
        const value = node.childForFieldName('value');
        if (!value) return;
        const answerValue = refersToAnswer(value, this.aliases);
        this.visit(value);
        if (answerValue) patternNames(node.childForFieldName('pattern'), this.aliases);
        this.visit(node.childForFieldName('alternative'));
        return;
      }
      default:
        for (const child of node.namedChildren) this.visit(child);
    }
  }
}

/** Whether the outer attributes before `item` include exactly `#[test]`. */
function isTest(item) {
  for (let sibling = item.previousNamedSibling; sibling; sibling = sibling.previousNamedSibling) {
    if (COMMENTS.has(sibling.type)) continue;
    if (sibling.type !== 'attribute_item') return false;
    const attribute = sibling.namedChildren.find(child => child.type === 'attribute');
    if (attribute?.namedChildren[0]?.type === 'identifier' && attribute.namedChildren[0].text === 'test') return true;
  }
  return false;
}

function collectTestEntries(relativePath, items, parser, entries) {
  for (const item of items.namedChildren) {
    if (item.type === 'function_item' && isTest(item)) {
      const audit = new AnswerAudit(parser);
      audit.visit(item.childForFieldName('body'));
      if (audit.asserted && !audit.exact) entries.push({ file: relativePath, test: item.childForFieldName('name').text });
    } else if (item.type === 'mod_item') {
      const body = item.childForFieldName('body');
      if (body) collectTestEntries(relativePath, body, parser, entries);
    }
  }
}

/** The loose-only behavioural tests of one Rust source, in source order. */
export function scanFile(relativePath, source, parser) {
  const tree = parser.parse(source);
  try {
    if (tree.rootNode.hasError) {
      process.stderr.write(`${relativePath} must parse as Rust: tree-sitter reported a syntax error\n`);
      process.exit(101);
    }
    const entries = [];
    collectTestEntries(relativePath, tree.rootNode, parser, entries);
    return entries;
  } finally {
    tree.delete();
  }
}

const rowOf = entry => `${entry.file}\t${entry.test}`;
// Rust's BTreeSet<Entry> orders by (file, test) as UTF-8 bytes.
const byBytes = (left, right) => Buffer.compare(Buffer.from(left), Buffer.from(right));
const compareEntries = (left, right) => byBytes(left.file, right.file) || byBytes(left.test, right.test);

function sortedUnique(entries) {
  const unique = new Map(entries.map(entry => [rowOf(entry), entry]));
  return [...unique.values()].sort(compareEntries);
}

export function scanDirectory(root, parser) {
  const entries = [];
  const decoder = new TextDecoder('utf-8', { fatal: true });
  for (const dirent of readdirSync(path.join(root, SCAN_DIR), { recursive: true, withFileTypes: true })) {
    if (!dirent.isFile() || path.extname(dirent.name) !== '.rs') continue;
    const absolute = path.join(dirent.parentPath, dirent.name);
    const relative = path.relative(root, absolute).split(path.sep).join('/');
    if (SKIP_PATH_FRAGMENTS.some(fragment => relative.includes(fragment))) continue;
    let source;
    try {
      source = decoder.decode(readFileSync(absolute));
    } catch {
      continue;
    }
    entries.push(...scanFile(relative, source, parser));
  }
  return sortedUnique(entries);
}

export function parseAllowlist(content) {
  const entries = [];
  for (const line of content.split('\n')) {
    const row = line.trimEnd();
    if (!row || row.startsWith('#')) continue;
    const tab = row.indexOf('\t');
    if (tab <= 0 || tab === row.length - 1) continue;
    entries.push({ file: row.slice(0, tab), test: row.slice(tab + 1) });
  }
  return sortedUnique(entries);
}

export const renderAllowlist = entries => ALLOWLIST_HEADER + entries.map(entry => `${rowOf(entry)}\n`).join('');

export function diff(found, allowlisted) {
  const foundRows = new Set(found.map(rowOf));
  const allowedRows = new Set(allowlisted.map(rowOf));
  return {
    added: found.filter(entry => !allowedRows.has(rowOf(entry))),
    stale: allowlisted.filter(entry => !foundRows.has(rowOf(entry))),
  };
}

async function main() {
  const root = process.cwd();
  const write = process.argv.slice(2).includes('--write');
  const parser = await loadRustParser();
  let found;
  try {
    found = scanDirectory(root, parser);
  } finally {
    parser.delete();
  }
  const out = text => process.stdout.write(`${text}\n`);

  if (write) {
    writeFileSync(path.join(root, ALLOWLIST_PATH), renderAllowlist(found));
    out(`Wrote ${found.length} rows to ${ALLOWLIST_PATH}`);
    return;
  }

  out('\nChecking behavioural tests show exact example answers (R234-2)...\n');
  let allowlisted = [];
  try {
    allowlisted = parseAllowlist(readFileSync(path.join(root, ALLOWLIST_PATH), 'utf8'));
  } catch {
    allowlisted = [];
  }
  const difference = diff(found, allowlisted);

  if (difference.added.length > 0) {
    out('Behavioural tests asserting on an answer without showing it:\n');
    for (const entry of difference.added) out(`  ${entry.file}::${entry.test}`);
    out('\nTests are documentation: show the exact answer, or the explicit list of answers it\n' +
      'must be one of, in addition to any contains/!contains assertions.\n' +
      'assert_eq!(response.answer, "…");\n' +
      'assert!(EXPECTED.contains(&response.answer.as_str()), "…");\n');
  }
  if (difference.stale.length > 0) {
    out('Stale allowlist rows (these tests are explicit now — prune them):\n');
    for (const entry of difference.stale) out(`  ${entry.file}::${entry.test}`);
    out('\nRegenerate with: rust-script scripts/check-tests-as-docs.rs --write\n');
  }
  if (difference.added.length === 0 && difference.stale.length === 0) {
    out(`All loose-only behavioural tests are tracked in the ${found.length}-row burn-down allowlist; every other answer assertion is exact\n`);
    return;
  }
  process.exitCode = 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
