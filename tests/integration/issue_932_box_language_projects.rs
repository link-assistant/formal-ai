//! Issue #932: run a Formal-AI-generated project inside the link-foundation/box
//! image that matches its language, with the language's own init commands.
//!
//! This is the container half of the harness — the same
//! `scripts/verify-box-language-projects.sh` CI runs, driven from `cargo test`
//! so a developer gets the check without reading the workflow. Like
//! `scripts/verify-docker-runtime.sh` it skips gracefully when Docker is
//! missing, and it only runs languages whose image is already on the machine:
//! a laptop should not silently pull several gigabytes from a unit-test run.
//! Set `FORMAL_AI_BOX_LANGUAGES=all` to pull and run every language, or name
//! them (`FORMAL_AI_BOX_LANGUAGES=rust,go`) to force a subset.
//!
//! The contract-shape and solver-output halves, which need no Docker, are in
//! `tests/unit/issue_932_box_language_projects.rs`.

use std::path::Path;
use std::process::{Command, Stdio};

use formal_ai::box_language_projects::{BoxLanguageContract, box_language_contract};

fn repository_root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
}

fn docker_is_available() -> bool {
    Command::new("docker")
        .arg("info")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .is_ok_and(|status| status.success())
}

/// Images already pulled on this machine, so the default run costs no download.
fn local_images() -> Vec<String> {
    let output = Command::new("docker")
        .args(["image", "ls", "--format", "{{.Repository}}:{{.Tag}}"])
        .output()
        .expect("docker image ls must run once the daemon answered");
    String::from_utf8_lossy(&output.stdout)
        .lines()
        .map(str::to_owned)
        .collect()
}

/// The languages to exercise, and whether the harness may pull their image.
fn selection(contract: &BoxLanguageContract) -> (Vec<String>, bool) {
    let requested = std::env::var("FORMAL_AI_BOX_LANGUAGES").unwrap_or_default();
    if requested == "all" {
        let all = contract
            .projects
            .iter()
            .map(|project| project.language.clone())
            .collect();
        return (all, true);
    }
    if !requested.is_empty() {
        let named = requested
            .split(',')
            .map(|language| language.trim().to_owned())
            .filter(|language| !language.is_empty())
            .collect();
        return (named, true);
    }

    let present = local_images();
    let already_pulled = contract
        .projects
        .iter()
        .filter(|project| present.contains(&contract.image_reference(project)))
        .map(|project| project.language.clone())
        .collect();
    (already_pulled, false)
}

/// Issue #932's acceptance check: for each selected language, generate the
/// project from solver answers and build and run it inside its own box image.
#[test]
fn generated_projects_build_and_run_in_their_box_images() {
    if !docker_is_available() {
        eprintln!("skipping: the docker daemon is not reachable");
        return;
    }

    let contract = box_language_contract();
    let (languages, may_pull) = selection(&contract);
    if languages.is_empty() {
        eprintln!(
            "skipping: no box image is present locally; set FORMAL_AI_BOX_LANGUAGES=all to pull them"
        );
        return;
    }
    eprintln!(
        "running box language projects for: {}",
        languages.join(", ")
    );

    let output = Command::new("bash")
        .arg(repository_root().join(&contract.verify_script))
        .args(&languages)
        .current_dir(repository_root())
        // The just-built test binary's sibling, so the corpus is generated by
        // the working tree under test rather than by whatever is on PATH.
        .env("FORMAL_AI_BIN", env!("CARGO_BIN_EXE_formal-ai"))
        .env("STRICT", "1")
        .env("PULL", if may_pull { "1" } else { "0" })
        .output()
        .expect("the verifier must run");

    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        output.status.success(),
        "box language projects failed\n--- stdout ---\n{stdout}\n--- stderr ---\n{stderr}"
    );
    for language in &languages {
        assert!(
            stdout.contains(&format!("ok: {language}")),
            "{language} never reported a successful run:\n{stdout}"
        );
    }
    assert!(
        stdout.contains(&contract.expected_output),
        "the container output must carry the program's own line:\n{stdout}"
    );
}
