fn assert_generated_source(task: &str, path: &str, expected: &str) {
    let outcome = run_agentic_task(task).expect("isolated agent workspace");
    assert!(
        !outcome.hit_turn_cap,
        "agent loop must terminate: {outcome:?}"
    );

    let write = outcome
        .steps
        .iter()
        .find(|step| {
            step.tool == "write_file"
                && serde_json::from_str::<serde_json::Value>(&step.arguments)
                    .ok()
                    .and_then(|arguments| arguments["path"].as_str().map(str::to_owned))
                    .is_some_and(|written| written == path)
        })
        .unwrap_or_else(|| panic!("requested file was not written: {outcome:?}"));
    let arguments: serde_json::Value =
        serde_json::from_str(&write.arguments).expect("write arguments are JSON");
    assert_eq!(arguments["content"], expected, "generated source: {task}");
    assert!(
        outcome.steps.iter().any(|step| {
            step.tool == "run_command"
                && step.arguments.contains(&format!("cat {path}"))
                && step.result == expected
        }),
        "verification must observe the generated bytes: {outcome:?}"
    );
}

#[track_caller]
fn only_call(plan: Option<AgenticPlan>) -> formal_ai::agentic_coding::PlannedToolCall {
    match plan {
        Some(AgenticPlan::ToolCalls(mut calls)) => {
            assert_eq!(calls.len(), 1);
            calls.remove(0)
        }
        other => panic!("expected one tool call, got {other:?}"),
    }
}

fn json_arguments(arguments: &str) -> serde_json::Value {
    serde_json::from_str(arguments).expect("tool arguments are JSON")
}

fn push_result(
    messages: &mut Vec<ChatMessage>,
    id: &str,
    call: &formal_ai::agentic_coding::PlannedToolCall,
    result: &str,
) {
    messages.push(ChatMessage::assistant_tool_calls(vec![ToolCall::function(
        id.to_owned(),
        call.tool.clone(),
        call.arguments.clone(),
    )]));
    messages.push(ChatMessage::tool_result(
        id.to_owned(),
        call.tool.clone(),
        result.to_owned(),
    ));
}
