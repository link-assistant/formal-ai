#[test]
fn multilingual_rust_function_requests_generate_source() {
    for (task, path, name) in [
        (
            "Создай файл src/ladder_ru.rs с одной публичной функцией на Rust с именем \
             ladder_ru, которая возвращает число 1.",
            "src/ladder_ru.rs",
            "ladder_ru",
        ),
        (
            "在这个仓库中创建文件 src/ladder_zh.rs，其中包含一个名为 ladder_zh 的公共 Rust \
             函数，返回数字 1。",
            "src/ladder_zh.rs",
            "ladder_zh",
        ),
        (
            "इस रिपॉजिटरी में src/ladder_hi.rs फ़ाइल बनाएँ जिसमें ladder_hi नाम का एक सार्वजनिक \
             Rust फ़ंक्शन हो जो 1 लौटाता है।",
            "src/ladder_hi.rs",
            "ladder_hi",
        ),
    ] {
        assert_generated_source(
            task,
            path,
            &format!("pub fn {name}() -> i64 {{\n    1\n}}\n"),
        );
    }
}

#[test]
fn repository_searches_use_the_named_code_subject() {
    for (task, expected) in [
        (
            "In this repository, find where the string example.org is emitted as evidence and \
             tell me the file name.",
            "example.org",
        ),
        (
            "In this repository, find where the function stable_id is defined and tell me the \
             file name.",
            "stable_id",
        ),
        (
            "In this repository, find where the function dialog_id is defined and tell me the \
             file name.",
            "dialog_id",
        ),
        (
            "In this repository, find where the excluded_folders array is defined and tell me \
             the file name.",
            "excluded_folders",
        ),
        (
            "In this repository, find where reciprocalRankFusion is implemented in JavaScript \
             and tell me the file name.",
            "reciprocalRankFusion",
        ),
        (
            "In this repository, find where the Context struct for world models is defined and \
             tell me the file name.",
            "Context",
        ),
        (
            "In this repository, find where the summarize function is defined and tell me the \
             file name.",
            "summarize",
        ),
    ] {
        let AgenticPlan::ToolCalls(calls) =
            plan_chat_step(&[ChatMessage::user(task)], &["grep"]).expect("grep plan")
        else {
            panic!("repository search must call grep: {task}");
        };
        assert_eq!(calls.len(), 1, "one focused grep: {task}");
        let arguments: serde_json::Value =
            serde_json::from_str(&calls[0].arguments).expect("grep arguments");
        assert_eq!(arguments["query"], expected, "focused query: {task}");
        assert_eq!(arguments["pattern"], expected, "focused pattern: {task}");
    }
}

fn assert_generated_source(task: &str, path: &str, expected: &str) {
    let outcome = run_agentic_task(task).expect("isolated agent workspace");
    assert!(
        !outcome.hit_turn_cap,
        "agent loop must terminate: {outcome:?}"
    );

    let write = outcome
        .steps
        .iter()
        .find(|step| {
            step.tool == "write_file"
                && serde_json::from_str::<serde_json::Value>(&step.arguments)
                    .ok()
                    .and_then(|arguments| arguments["path"].as_str().map(str::to_owned))
                    .is_some_and(|written| written == path)
        })
        .unwrap_or_else(|| panic!("requested file was not written: {outcome:?}"));
    let arguments: serde_json::Value =
        serde_json::from_str(&write.arguments).expect("write arguments are JSON");
    assert_eq!(arguments["content"], expected, "generated source: {task}");
    assert!(
        outcome.steps.iter().any(|step| {
            step.tool == "run_command"
                && step.arguments.contains(&format!("cat {path}"))
                && step.result == expected
        }),
        "verification must observe the generated bytes: {outcome:?}"
    );
}
