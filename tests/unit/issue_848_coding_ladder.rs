#[test]
fn identifier_refactor_accepts_agent_cli_absolute_tool_paths() {
    const TASK: &str = "In this repository, in src/web_search_core.rs, rename the constant \
        WEB_SEARCH_RRF_K to WEB_SEARCH_FUSION_K everywhere it appears in this file.";
    const AFTER: &str = "pub const WEB_SEARCH_FUSION_K: f64 = 60.0;\n\
        pub fn score(rank: f64) -> f64 { WEB_SEARCH_FUSION_K + rank }\n";
    const AGENT_READ_RESULT: &str = concat!(
        "<file>\n",
        "00001| pub const WEB_SEARCH_RRF_K: f64 = 60.0;\n",
        "00002| pub fn score(rank: f64) -> f64 { WEB_SEARCH_RRF_K + rank }\n",
        "00003| \n\n",
        "(End of file - total 3 lines)\n",
        "</file>",
    );
    const ABSOLUTE_PATH: &str = "/tmp/agent-workspace/src/web_search_core.rs";
    let tools = ["read", "edit", "write", "bash"];
    let mut messages = vec![ChatMessage::user(TASK)];

    let read = only_call(plan_chat_step(&messages, &tools));
    assert_eq!(read.tool, "read");
    messages.push(ChatMessage::assistant_tool_calls(vec![ToolCall::function(
        "agent_read",
        "read",
        serde_json::json!({"filePath": ABSOLUTE_PATH}).to_string(),
    )]));
    messages.push(ChatMessage::tool_result(
        "agent_read",
        "read",
        AGENT_READ_RESULT,
    ));

    let rewrite = only_call(plan_chat_step(&messages, &tools));
    assert_eq!(
        rewrite.tool, "bash",
        "a repeated identifier needs one bounded replace-all operation"
    );
    assert_eq!(
        json_arguments(&rewrite.arguments)["command"],
        "sed -i 's/\\bWEB_SEARCH_RRF_K\\b/WEB_SEARCH_FUSION_K/g' -- src/web_search_core.rs",
        "the operation must be derived only from validated identifiers and path, \
         and scoped to whole words so a longer name containing this one survives"
    );
    push_result(&mut messages, "agent_rewrite", &rewrite, "");

    let verify = only_call(plan_chat_step(&messages, &tools));
    assert_eq!(
        verify.tool, "bash",
        "the bounded rewrite result must advance"
    );
    assert_eq!(
        json_arguments(&verify.arguments)["command"],
        "sha256sum -- src/web_search_core.rs",
        "verification must not return the whole large source through Agent"
    );
    let digest = formal_ai::sha256_hex(AFTER.as_bytes());
    push_result(
        &mut messages,
        "agent_verify",
        &verify,
        &format!("{digest}  src/web_search_core.rs\n"),
    );

    let Some(AgenticPlan::Final(answer)) = plan_chat_step(&messages, &tools) else {
        panic!("the compact Agent rewrite must finish");
    };
    assert!(answer.contains("observed"), "{answer}");
}

