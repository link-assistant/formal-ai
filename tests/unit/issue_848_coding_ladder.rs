//! Regression coverage for issue #848's coding-task ladder.
//!
//! A passing response is not evidence of a code change. These tests inspect the
//! bytes that the real offline Agent CLI loop writes and then reads back.

use formal_ai::agentic_coding::{plan_chat_step, run_agentic_task, AgenticPlan};
use formal_ai::protocol::{ChatMessage, ToolCall};

const CREATE_RUST_FUNCTION: &str = "Create a new file src/si_units.rs in this repository \
    containing a single public Rust function millimetres_to_metres that takes an f64 and \
    returns it divided by 1000.0.";

#[test]
fn rust_function_request_writes_executable_source_and_observes_it() {
    let outcome = run_agentic_task(CREATE_RUST_FUNCTION).expect("isolated agent workspace");
    assert!(
        !outcome.hit_turn_cap,
        "agent loop must terminate: {outcome:?}"
    );

    let target = outcome
        .steps
        .iter()
        .find(|step| {
            if step.tool != "write_file" {
                return false;
            }
            serde_json::from_str::<serde_json::Value>(&step.arguments)
                .ok()
                .and_then(|arguments| arguments["path"].as_str().map(str::to_owned))
                .is_some_and(|path| path == "src/si_units.rs")
        })
        .unwrap_or_else(|| panic!("the requested Rust file was not written: {outcome:?}"));
    let arguments: serde_json::Value =
        serde_json::from_str(&target.arguments).expect("write arguments are JSON");
    let source = arguments["content"].as_str().expect("written source bytes");

    assert_eq!(
        source,
        "pub fn millimetres_to_metres(value: f64) -> f64 {\n    value / 1000.0\n}\n"
    );
    assert!(
        outcome.steps.iter().any(|step| {
            step.tool == "run_command"
                && step.arguments.contains("cat src/si_units.rs")
                && step.result == source
        }),
        "verification must observe the generated bytes: {outcome:?}"
    );
}

