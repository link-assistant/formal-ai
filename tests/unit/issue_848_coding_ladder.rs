#[test]
fn collection_edit_reads_transforms_writes_and_observes_workspace_bytes() {
    const TASK: &str = "In this repository, in scripts/detect-code-changes.rs, add \
        \"dev/log/\" to the excluded_folders array.";
    const BEFORE: &str = "fn is_excluded(file_path: &str) -> bool {\n    \
        let excluded_folders = [\"changelog.d/\", \"docs/\", \"examples/\"];\n    \
        excluded_folders.iter().any(|folder| file_path.starts_with(folder))\n}\n";
    const AFTER: &str = "fn is_excluded(file_path: &str) -> bool {\n    \
        let excluded_folders = [\"changelog.d/\", \"docs/\", \"examples/\", \"dev/log/\"];\n    \
        excluded_folders.iter().any(|folder| file_path.starts_with(folder))\n}\n";
    let tools = ["read_file", "write_file", "run_command"];
    let mut messages = vec![ChatMessage::user(TASK)];

    let read = only_call(plan_chat_step(&messages, &tools));
    assert_eq!(read.tool, "read_file");
    assert_eq!(
        json_arguments(&read.arguments)["path"],
        "scripts/detect-code-changes.rs"
    );
    push_result(&mut messages, "read_1", &read, BEFORE);

    let write = only_call(plan_chat_step(&messages, &tools));
    assert_eq!(write.tool, "write_file");
    let arguments = json_arguments(&write.arguments);
    assert_eq!(arguments["path"], "scripts/detect-code-changes.rs");
    assert_eq!(arguments["content"], AFTER);
    push_result(&mut messages, "write_1", &write, "updated");

    let verify = only_call(plan_chat_step(&messages, &tools));
    assert_eq!(verify.tool, "run_command");
    assert_eq!(
        json_arguments(&verify.arguments)["command"],
        "cat scripts/detect-code-changes.rs"
    );
    push_result(&mut messages, "run_1", &verify, AFTER);

    let Some(AgenticPlan::Final(answer)) = plan_chat_step(&messages, &tools) else {
        panic!("an observed edit must finish");
    };
    assert!(answer.contains("observed"), "{answer}");
}

