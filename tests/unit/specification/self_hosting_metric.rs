fn git(repo: &Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .arg("-C")
        .arg(repo)
        .args(args)
        .output()
        .expect("git must run in the metric fixture");
    assert!(
        output.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout)
        .expect("git output must be UTF-8")
        .trim()
        .to_owned()
}

/// `git` with extra environment, for the dates a commit records.
///
/// `--date` only moves the author date, and the release cycle's age is measured
/// from the committer date, so a fixture that needs an old commit must set both.
fn git_with_env(repo: &Path, args: &[&str], env: &[(&str, &str)]) -> String {
    let mut command = Command::new("git");
    command.arg("-C").arg(repo).args(args);
    for (key, value) in env {
        command.env(key, value);
    }
    let output = command
        .output()
        .expect("git must run in the metric fixture");
    assert!(
        output.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout)
        .expect("git output must be UTF-8")
        .trim()
        .to_owned()
}

fn commit(repo: &Path, message: &str) {
    git(repo, &["add", "."]);
    git(repo, &["commit", "-m", message]);
}

fn merge_formal_ai_pull_request(repo: &Path, number: u64) -> String {
    let branch = format!("issue-{number}");
    let session = format!("fixture-session-{number}");
    let evidence = format!("docs/evidence/{number}/session.txt");
    let pull_request = format!("https://github.com/example/formal-ai/pull/{number}");

    git(repo, &["switch", "-c", &branch]);
    fs::create_dir_all(repo.join(format!("docs/evidence/{number}")))
        .expect("evidence directory must be created");
    fs::write(
        repo.join(&evidence),
        format!("formal-ai session {session}\n"),
    )
    .expect("session evidence must be written");
    fs::write(
        repo.join(format!("formal-ai-{number}.txt")),
        format!("generated by {session}\n"),
    )
    .expect("generated artifact must be written");
    commit(
        repo,
        &format!(
            "formal ai change\n\nFormal-AI-Session: {session}\nFormal-AI-Evidence: {evidence}\nFormal-AI-Pull-Request: {pull_request}"
        ),
    );
    git(repo, &["switch", "main"]);
    git(
        repo,
        &[
            "merge",
            "--no-ff",
            &branch,
            "-m",
            &format!("Merge pull request #{number} from example/{branch}"),
        ],
    );
    pull_request
}

fn fixture_repo() -> PathBuf {
    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("clock must be after epoch")
        .as_nanos();
    let repo = std::env::temp_dir().join(format!(
        "formal-ai-self-hosting-metric-{}-{nonce}",
        std::process::id()
    ));
    fs::create_dir_all(repo.join("data/meta")).expect("fixture directory must be created");
    git(&repo, &["init", "--quiet"]);
    git(&repo, &["config", "user.name", "Metric Fixture"]);
    git(&repo, &["config", "user.email", "metric@example.invalid"]);
    fs::write(
        repo.join("data/meta/self-hosting-ledger.lino"),
        "self_hosting_ledger\n  attribution_policy \"commit_trailers\"\n  session_trailer \
         \"Formal-AI-Session\"\n  evidence_trailer \"Formal-AI-Evidence\"\n  line_unit \
         \"added_and_deleted\"\n  default_trailing_window \"3\"\n",
    )
    .expect("fixture ledger must be written");
    fs::write(repo.join("code.txt"), "base\n").expect("base file must be written");
    commit(&repo, "fixture baseline");
    git(&repo, &["branch", "-M", "main"]);
    git(&repo, &["tag", "v1.0.0"]);
    repo
}

#[test]
fn release_cycle_requires_a_session_backed_merged_pull_request() {
    let repo = fixture_repo();
    fs::create_dir_all(repo.join("docs/evidence/direct"))
        .expect("evidence directory must be created");
    fs::write(
        repo.join("docs/evidence/direct/session.txt"),
        "formal-ai session direct-session\n",
    )
    .expect("session evidence must be written");
    fs::write(repo.join("direct.txt"), "generated directly\n")
        .expect("generated artifact must be written");
    commit(
        &repo,
        "direct change\n\nFormal-AI-Session: direct-session\nFormal-AI-Evidence: \
         docs/evidence/direct/session.txt\nFormal-AI-Pull-Request: \
         https://github.com/example/formal-ai/pull/40",
    );

    let ledger = repo.join("data/meta/self-hosting-ledger.lino");
    let status = metric_script::self_development_release_status(
        &repo, &ledger, "v1.1.0", "v1.0.0", "HEAD", 3,
    )
    .expect("policy ineligibility must not be confused with an operational error");
    assert!(matches!(
        status,
        metric_script::SelfDevelopmentReleaseStatus::Blocked(ref reason)
            if reason.contains("merged Formal AI-authored pull request")
    ));
    let error = metric_script::ensure_self_development_release(
        &repo, &ledger, "v1.1.0", "v1.0.0", "HEAD", 3,
    )
    .expect_err("a trailer on a direct commit must not impersonate a merged pull request");
    assert!(error.contains("merged Formal AI-authored pull request"));

    let pull_request = merge_formal_ai_pull_request(&repo, 41);
    let eligibility = metric_script::ensure_self_development_release(
        &repo, &ledger, "v1.1.0", "v1.0.0", "HEAD", 3,
    )
    .expect("the reviewed, session-backed pull request must make the cycle releasable");
    assert_eq!(eligibility.pull_requests, vec![pull_request]);
    assert_eq!(eligibility.target_percentage_basis_points, 0);

    fs::remove_dir_all(repo).expect("fixture directory must be removed");
}

/// Issue #1066: an ineligible cycle is blocked immediately, with no grace period.
///
/// #1065 gave deferral a seven-day, twenty-fragment budget on the theory that a
/// young cycle is merely waiting. Deferring work is forbidden in this repository
/// however hard the work is, so the budget is gone: a cycle that cannot be cut
/// is blocked from the very first push, and nothing about its age or its backlog
/// changes that.
#[test]
fn an_ineligible_cycle_is_blocked_from_the_first_push() {
    let repo = fixture_repo();
    fs::write(repo.join("change.txt"), "unreleased work\n").expect("change must be written");
    commit(&repo, "unattributed change");

    let ledger = repo.join("data/meta/self-hosting-ledger.lino");
    let fresh = metric_script::self_development_release_status(
        &repo, &ledger, "v1.1.0", "v1.0.0", "HEAD", 3,
    )
    .expect("policy ineligibility must not be confused with an operational error");
    let metric_script::SelfDevelopmentReleaseStatus::Blocked(fresh_reason) = &fresh else {
        panic!("a cycle tagged moments ago must already be blocked, not tolerated: {fresh:?}");
    };
    assert!(
        fresh_reason.contains("merged Formal AI-authored pull request"),
        "the refusal must name what is missing: {fresh_reason}"
    );

    // Neither dimension the removed budget measured may change the verdict. A
    // second fixture is aged past the old seven-day window *and* filled past the
    // old twenty-fragment one, so if either threshold is reintroduced this is
    // where the answer flips. The age is set on the commit `v1.0.0` points at,
    // because the cycle's age was read from the tagged baseline, not from HEAD.
    let aged_repo = fixture_repo();
    let stale = format!(
        "{} +0000",
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("clock must be after epoch")
            .as_secs()
            - 60 * 86_400
    );
    git_with_env(
        &aged_repo,
        &["commit", "--amend", "--no-edit"],
        &[
            ("GIT_AUTHOR_DATE", stale.as_str()),
            ("GIT_COMMITTER_DATE", stale.as_str()),
        ],
    );
    git(&aged_repo, &["tag", "-f", "v1.0.0"]);
    fs::create_dir_all(aged_repo.join("changelog.d")).expect("fragment directory must be created");
    for index in 0..40 {
        fs::write(
            aged_repo.join(format!("changelog.d/2026080{index:02}_120000_fragment.md")),
            "### Fixed\n- a merged change waiting for a release it never gets\n",
        )
        .expect("fragment must be written");
    }
    fs::write(aged_repo.join("change.txt"), "unreleased work\n").expect("change must be written");
    commit(&aged_repo, "unattributed change");

    let aged_ledger = aged_repo.join("data/meta/self-hosting-ledger.lino");
    let aged = metric_script::self_development_release_status(
        &aged_repo,
        &aged_ledger,
        "v1.1.0",
        "v1.0.0",
        "HEAD",
        3,
    )
    .expect("policy ineligibility must not be confused with an operational error");
    let metric_script::SelfDevelopmentReleaseStatus::Blocked(aged_reason) = &aged else {
        panic!(
            "a sixty-day-old cycle with forty pending fragments must still be blocked: {aged:?}"
        );
    };
    assert_eq!(
        aged_reason, fresh_reason,
        "age and backlog must not change the refusal by one character"
    );
    assert!(
        !aged_reason.contains("budget"),
        "no budget may survive anywhere in the refusal: {aged_reason}"
    );

    // The hard gate rejects it too: both release paths share one answer.
    let error = metric_script::ensure_self_development_release(
        &aged_repo,
        &aged_ledger,
        "v1.1.0",
        "v1.0.0",
        "HEAD",
        3,
    )
    .expect_err("a blocked cycle must never be releasable");
    assert_eq!(&error, aged_reason);

    fs::remove_dir_all(repo).expect("fixture directory must be removed");
    fs::remove_dir_all(aged_repo).expect("aged fixture directory must be removed");
}

