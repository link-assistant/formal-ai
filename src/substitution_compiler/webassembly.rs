use std::fmt::Write as _;

use super::rust_runtime::{COMMON_RUNTIME, rules_source};
use super::{CompiledSubstitutionFile, SubstitutionProgramIr};

pub(super) fn emit(
    ir: &SubstitutionProgramIr,
    stem: &str,
) -> (CompiledSubstitutionFile, Vec<CompiledSubstitutionFile>) {
    let source = rust_file(ir, stem);
    let source_name = source.name.clone();
    (
        source,
        vec![CompiledSubstitutionFile {
            name: String::from("run_substitution_wasm.mjs"),
            contents: interop_module(&source_name),
        }],
    )
}

pub(super) fn rust_file(ir: &SubstitutionProgramIr, stem: &str) -> CompiledSubstitutionFile {
    let mut contents = String::from(WASM_PRELUDE);
    let _ = writeln!(
        contents,
        "const MAX_APPLICATIONS: usize = {};",
        ir.max_applications
    );
    contents.push_str(COMMON_RUNTIME);
    contents.push_str(&rules_source(ir));
    contents.push_str(WASM_ENTRY_POINTS);
    CompiledSubstitutionFile {
        name: format!("{stem}_wasm.rs"),
        contents,
    }
}

pub(super) fn interop_module(wasm_source: &str) -> String {
    format!(
        "// Generated JavaScript interop; substitution semantics remain in Rust/WASM.\n// Compile {wasm_source} to a WebAssembly module before loading this file.\n{WASM_INTEROP}"
    )
}

const WASM_PRELUDE: &str = r"// Generated by Formal AI's Rust-owned substitution compiler.
#![no_std]

extern crate alloc;

use alloc::borrow::ToOwned as _;
use alloc::collections::{BTreeMap, BTreeSet};
use alloc::format;
use alloc::string::String;
use core::alloc::{GlobalAlloc, Layout};
use core::cell::UnsafeCell;
use core::fmt::Write as _;
use core::sync::atomic::{AtomicUsize, Ordering};

const INPUT_CAPACITY: usize = 65_536;
const OUTPUT_CAPACITY: usize = 65_536;
const HEAP_CAPACITY: usize = 2_097_152;

static mut INPUT: [u8; INPUT_CAPACITY] = [0; INPUT_CAPACITY];
static mut OUTPUT: [u8; OUTPUT_CAPACITY] = [0; OUTPUT_CAPACITY];

struct Heap { buffer: UnsafeCell<[u8; HEAP_CAPACITY]> }
unsafe impl Sync for Heap {}
static HEAP: Heap = Heap { buffer: UnsafeCell::new([0; HEAP_CAPACITY]) };
static OFFSET: AtomicUsize = AtomicUsize::new(0);
struct Allocator;

unsafe impl GlobalAlloc for Allocator {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        let base = HEAP.buffer.get() as usize;
        loop {
            let current = OFFSET.load(Ordering::Relaxed);
            let address = (base + current + layout.align() - 1) & !(layout.align() - 1);
            let next = address - base + layout.size();
            if next > HEAP_CAPACITY { return core::ptr::null_mut(); }
            if OFFSET.compare_exchange(current, next, Ordering::AcqRel, Ordering::Relaxed).is_ok() {
                return address as *mut u8;
            }
        }
    }
    unsafe fn dealloc(&self, _pointer: *mut u8, _layout: Layout) {}
}

#[global_allocator]
static ALLOCATOR: Allocator = Allocator;

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo<'_>) -> ! { loop {} }

";

const WASM_ENTRY_POINTS: &str = r#"
#[unsafe(no_mangle)]
pub extern "C" fn input_ptr() -> *mut u8 { core::ptr::addr_of_mut!(INPUT).cast::<u8>() }

#[unsafe(no_mangle)]
pub extern "C" fn output_ptr() -> *mut u8 { core::ptr::addr_of_mut!(OUTPUT).cast::<u8>() }

#[unsafe(no_mangle)]
pub extern "C" fn input_capacity() -> usize { INPUT_CAPACITY }

#[unsafe(no_mangle)]
pub extern "C" fn run(length: usize) -> usize {
    OFFSET.store(0, Ordering::Release);
    let length = length.min(INPUT_CAPACITY);
    let bytes = unsafe { core::slice::from_raw_parts(core::ptr::addr_of!(INPUT).cast::<u8>(), length) };
    let Ok(input) = core::str::from_utf8(bytes) else { return 0; };
    let output = transform(input);
    let length = output.len().min(OUTPUT_CAPACITY);
    unsafe {
        core::ptr::copy_nonoverlapping(output.as_ptr(), core::ptr::addr_of_mut!(OUTPUT).cast::<u8>(), length);
    }
    length
}
"#;

const WASM_INTEROP: &str = r#"
export async function instantiateSubstitution(wasmBytes) {
  const { instance } = await WebAssembly.instantiate(wasmBytes, {});
  return (input) => {
    const bytes = new TextEncoder().encode(input);
    if (bytes.length > instance.exports.input_capacity()) {
      throw new Error("input exceeds WASM capacity");
    }
    new Uint8Array(instance.exports.memory.buffer, instance.exports.input_ptr(), bytes.length).set(bytes);
    const outputLength = instance.exports.run(bytes.length);
    const output = new Uint8Array(
      instance.exports.memory.buffer,
      instance.exports.output_ptr(),
      outputLength,
    );
    return new TextDecoder().decode(output);
  };
}

if (typeof process !== "undefined" && process.release?.name === "node") {
  const wasmPath = process.argv[2];
  if (!wasmPath) throw new Error("usage: node INTEROP.mjs PROGRAM.wasm");
  const { readFile } = await import("node:fs/promises");
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  const runSubstitution = await instantiateSubstitution(await readFile(wasmPath));
  process.stdout.write(runSubstitution(Buffer.concat(chunks).toString("utf8")));
}
"#;
