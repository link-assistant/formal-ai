use std::fmt::Write as _;

use super::rust_runtime::{rules_source, COMMON_RUNTIME};
use super::{CompiledSubstitutionFile, SubstitutionProgramIr};

pub(super) fn emit(
    ir: &SubstitutionProgramIr,
    stem: &str,
) -> (CompiledSubstitutionFile, Vec<CompiledSubstitutionFile>) {
    let mut contents = String::from(
        r"// Generated by Formal AI's Rust-owned substitution compiler.
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::io::{self, Read as _};

",
    );
    let _ = writeln!(
        contents,
        "const MAX_APPLICATIONS: usize = {};",
        ir.max_applications
    );
    contents.push_str(COMMON_RUNTIME);
    contents.push_str(&rules_source(ir));
    contents.push_str(
        r#"
fn main() {
    let mut input = String::new();
    io::stdin().read_to_string(&mut input).expect("read stdin");
    print!("{}", transform(&input));
}
"#,
    );
    (
        CompiledSubstitutionFile {
            name: format!("{stem}.rs"),
            contents,
        },
        Vec::new(),
    )
}
